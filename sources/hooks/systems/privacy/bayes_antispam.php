/**
 * Hook class.
 */
class Hook_privacy_bayes_antispam extends Hook_privacy_base
{
    /**
     * Find privacy details.
     *
     * @return ?array A map of privacy details in a standardised format (null: disabled)
     */
    public function info() : ?array
    {
        if (!addon_installed('bayes_antispam')) {
            return null;
        }
        if (!addon_installed('bayes_common')) {
            return null;
        }

        return [
            'label' => 'bayes_antispam:BAYES_ANTISPAM',

            'description' => 'bayes_antispam:DESCRIPTION_PRIVACY_BAYES_ANTISPAM',

            'cookies' => [
            ],

            'positive' => [
                [
                    'heading' => do_lang('INFORMATION_STORAGE'),
                    'explanation' => do_lang_tempcode('bayes_antispam:PRIVACY_ACTION_BAYES_ANTISPAM_POSITIVE'),
                ],
            ],

            'general' => [
                [
                    'heading' => do_lang('INFORMATION_STORAGE'),
                    'action' => do_lang_tempcode('bayes_antispam:PRIVACY_ACTION_bayes_antispam'),
                    'reason' => do_lang_tempcode('bayes_antispam:PRIVACY_REASON_bayes_antispam'),
                ]
            ],

            'database_records' => [
            ],
        ];
    }
}
