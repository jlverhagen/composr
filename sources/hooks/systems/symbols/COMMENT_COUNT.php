/**
 * Hook class.
 */
class Hook_symbol_COMMENT_COUNT
{
    /**
     * Get information about this symbol.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        return [
            'compile' => SYMBOL_COMPILE_STATIC_NONE,
            'public' => false,
        ];
    }

    /**
     * Run function for symbol hooks. Searches for tasks to perform.
     *
     * @param  array $param Symbol parameters
     * @param  string $lang The language to evaluate this symbol in (some symbols refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @return string Result
     */
    public function run(array $param, string $lang, array $escaped) : string
    {
        $value = '';

        if ($GLOBALS['STATIC_TEMPLATE_TEST_MODE']) {
            $value = '1';
        } else {
            if ((!empty($param[0])) && (isset($param[1]))) {
                static $cache_comment_count = [];
                $cache_key = $param[0] . '_' . $param[1];
                if (isset($cache_comment_count[$cache_key])) {
                    $value = $cache_comment_count[$cache_key];
                } else {
                    if (get_option('is_on_comments') == '1') {
                        $count = 0;
                        $topic_id = $GLOBALS['FORUM_DRIVER']->find_topic_id_for_topic_identifier(get_option('comments_forum_name'), $cache_key, do_lang('COMMENT'));
                        if ($topic_id !== null) {
                            $_comments = $GLOBALS['FORUM_DRIVER']->get_forum_topic_posts($topic_id, $count, 0, 0, false);
                            if (($count != 0) || (empty($param[2]))) {
                                if (is_array($_comments)) {
                                    $_value = do_lang_tempcode('_COMMENTS', escape_html(integer_format($count, 0)));
                                } else {
                                    $_value = do_lang_tempcode('_COMMENTS', escape_html(integer_format(0, 0)));
                                }
                                $value = $_value->evaluate();
                            }
                        } else {
                            $_value = do_lang_tempcode('_COMMENTS', escape_html(integer_format(0, 0)));
                            $value = $_value->evaluate();
                        }
                    } else {
                        $value = do_lang('VIEW');
                    }
                    $cache_comment_count[$cache_key] = $value;
                }
            }
        }

        if ($GLOBALS['XSS_DETECT']) {
            ocp_mark_as_escaped($value);
        }
        return $value;
    }
}
