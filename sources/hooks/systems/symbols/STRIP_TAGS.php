/**
 * Hook class.
 */
class Hook_symbol_STRIP_TAGS
{
    /**
     * Get information about this symbol.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        return [
            'compile' => SYMBOL_COMPILE_STATIC_SAFE,
            'public' => false,
        ];
    }

    /**
     * Run function for symbol hooks. Searches for tasks to perform.
     *
     * @param  array $param Symbol parameters
     * @param  string $lang The language to evaluate this symbol in (some symbols refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @return string Result
     */
    public function run(array $param, string $lang, array $escaped) : string
    {
        $value = '';

        if (isset($param[0])) {
            if (strpos($param[0], '<') === false) { // optimisation
                $value = $param[0];
            } else {
                $inclusion_list = empty($param[2]);
                $value = cms_strip_tags($param[0], isset($param[1]) ? $param[1] : '', $inclusion_list);
                if ($inclusion_list) {
                    $value = str_replace('"', '&quot;', $value); // So can be used inside HTML attributes
                }
            }
        }


        if ($GLOBALS['XSS_DETECT']) {
            ocp_mark_as_escaped($value);
        }
        return $value;
    }
}
