/**
 * Hook class.
 */
class Hook_symbol_IS_ICON_IN_SVG_SPRITE
{
    /**
     * Get information about this symbol.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        return [
            'compile' => SYMBOL_COMPILE_STATIC_NONE,
        ];
    }

    /**
     * Run function for symbol hooks. Searches for tasks to perform.
     *
     * @param  array $param Symbol parameters
     * @param  string $lang The language to evaluate this symbol in (some symbols refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @return string Result
     */
    public function run(array $param, string $lang, array $escaped) : string
    {
        if ((!function_exists('get_theme_option')) || (get_theme_option('sprite_icons') == '0')) {
            $value = '0';
            if ($GLOBALS['XSS_DETECT']) {
                ocp_mark_as_escaped($value);
            }
            return $value;
        }

        static $sprite_ids = null;

        if ($sprite_ids === null) {
            require_code('themes');
            $theme = isset($GLOBALS['FORUM_DRIVER']) ? $GLOBALS['FORUM_DRIVER']->get_theme() : 'default';
            $is_monochrome = function_exists('get_theme_option') && (get_theme_option('use_monochrome_icons') === '1');
            $sprite = '';

            $path = get_file_base() . '/themes/' . $theme . '/images_custom/icons' . ($is_monochrome ? '_monochrome' : '') . '_sprite.svg';
            if (!file_exists($path)) {
                $path = get_file_base() . '/themes/default/images_custom/icons' . ($is_monochrome ? '_monochrome' : '') . '_sprite.svg';
            }
            if (!file_exists($path)) {
                $path = get_file_base() . '/themes/default/images/icons' . ($is_monochrome ? '_monochrome' : '') . '_sprite.svg';
            }

            if (file_exists($path)) {
                $sprite = cms_file_get_contents_safe($path, FILE_READ_LOCK);
            }

            $sprite_ids = [];
            $matches = [];
            $num_matches = preg_match_all('#\sid="icon_([^"]*)"#', $sprite, $matches);
            for ($i = 0; $i < $num_matches; $i++) {
                $sprite_ids[$matches[1][$i]] = true;
            }
        }

        $icon_name = $param[0];
        $icon_id = str_replace('/', '__', $icon_name);

        $value = isset($sprite_ids[$icon_id]) ? '1' : '0';


        return $value;
    }
}

