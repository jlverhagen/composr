/**
 * Hook class.
 */
class Hook_symbol_DISPLAY_CONCEPT
{
    /**
     * Get information about this symbol.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        return [
            'compile' => SYMBOL_COMPILE_STATIC_NONE,
            'public' => false,
        ];
    }

    /**
     * Run function for symbol hooks. Searches for tasks to perform.
     *
     * @param  array $param Symbol parameters
     * @param  string $lang The language to evaluate this symbol in (some symbols refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @return string Result
     */
    public function run(array $param, string $lang, array $escaped) : string
    {
        $value = '';
        if (!empty($param[0])) {
            $key = $param[0];
            require_code('comcode_renderer');
            $_key = 'concept__' . preg_replace('#[^\w]#', '_', $key);
            $page_link = get_tutorial_link($_key);
            if ($page_link === null) {
                $temp_tpl = make_string_tempcode($key);
            } else {
                list($zone, $attributes, $hash) = page_link_decode($page_link);
                if ($zone == get_zone_name() && $attributes['page'] == get_page_name()) {
                    $_url = make_string_tempcode('#' . $hash);
                } else {
                    $_url = build_url($attributes, $zone, [], false, false, false, $hash);
                }
                $temp_tpl = do_template('COMCODE_CONCEPT', ['_GUID' => 'ee0cd05f87329923f05145180004d8a8', 'TEXT' => $key, 'URL' => $_url]);
            }
            $value = $temp_tpl->evaluate();
        }


        return $value;
    }
}
