/**
 * Hook class.
 */
class Hook_symbol_FEEDS
{
    /**
     * Get information about this symbol.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        return [
            'compile' => SYMBOL_COMPILE_STATIC_NONE,
            'public' => false,
        ];
    }

    /**
     * Run function for symbol hooks. Searches for tasks to perform.
     *
     * @param  array $param Symbol parameters
     * @param  string $lang The language to evaluate this symbol in (some symbols refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @return string Result
     */
    public function run(array $param, string $lang, array $escaped) : string
    {
        if ((get_option('is_on_rss', true) === '1') && (addon_installed('syndication'))) {
            $feeds = new Tempcode();
            if (addon_installed('news')) {
                $feeds->attach(do_template('RSS_HEADER', ['_GUID' => '53e135b04502d6df64f1570b61310f30', 'FEED_URL' => find_script('backend') . '?mode=news', 'TITLE' => do_lang('NEWS')]));
            }
            foreach ($GLOBALS['FEED_URLS'] as $feed) {
                if (substr($feed['url'], 0, 1) == '?') {
                    $feed['url'] = find_script('backend') . $feed['url'];
                }
                $map = ['_GUID' => '371ef26788e14c17b6ad2bab9f9ffd1c', 'FEED_URL' => $feed['url'], 'TITLE' => $feed['title']];
                $feeds->attach(do_template('RSS_HEADER', $map));
            }
            $value = $feeds->evaluate();
        } else {
            $value = '';
        }

        if (!empty($escaped)) {
            apply_tempcode_escaping($escaped, $value);
        }
        return $value;
    }
}
