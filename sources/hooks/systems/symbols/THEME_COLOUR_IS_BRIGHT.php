/**
 * Hook class.
 */
class Hook_symbol_THEME_COLOUR_IS_BRIGHT
{
    /**
     * Get information about this symbol.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        if (!addon_installed('themewizard')) {
            return null;
        }

        return [
            'compile' => SYMBOL_COMPILE_STATIC_NONE,
            'public' => false,
        ];
    }

    /**
     * Run function for symbol hooks. Searches for tasks to perform.
     *
     * @param  array $param Symbol parameters
     * @param  string $lang The language to evaluate this symbol in (some symbols refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @return string Result
     */
    public function run(array $param, string $lang, array $escaped) : string
    {
        global $IN_MINIKERNEL_VERSION;

        $value = '0';

        if ($GLOBALS['XSS_DETECT']) {
            ocp_mark_as_escaped($value);
        }

        if (!$IN_MINIKERNEL_VERSION) {
            require_code('themewizard');
            if (strlen($param[0]) == 7) {
                $r = floatval(hexdec(substr($param[0], 1, 2)));
                $g = floatval(hexdec(substr($param[0], 3, 2)));
                $b = floatval(hexdec(substr($param[0], 5, 2)));

                $_value = rgb_luminance($r, $g, $b);

                if ($_value >= 0.5) {
                    $value = '1';
                }
            } elseif(strlen($param[0]) == 4) {
                $r = floatval(hexdec(substr($param[0], 1, 1) . '0'));
                $g = floatval(hexdec(substr($param[0], 2, 1) . '0'));
                $b = floatval(hexdec(substr($param[0], 3, 2) . '0'));

                $_value = rgb_luminance($r, $g, $b);

                if ($_value >= 0.5) {
                    $value = '1';
                }
            }
        }

        if (!empty($escaped)) {
            apply_tempcode_escaping($escaped, $value);
        }

        return $value;
    }
}
