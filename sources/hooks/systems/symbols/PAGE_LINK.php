/**
 * Hook class.
 */
class Hook_symbol_PAGE_LINK
{
    /**
     * Get information about this symbol.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        return [
            'compile' => SYMBOL_COMPILE_STATIC_IF_AGGRESSIVE | SYMBOL_COMPILE_STATIC_SAFE_SIMPLE_KEEP,
            'public' => false,
        ];
    }

    /**
     * Run function for symbol hooks. Searches for tasks to perform.
     *
     * @param  array $param Symbol parameters
     * @param  string $lang The language to evaluate this symbol in (some symbols refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @return string Result
     */
    public function run(array $param, string $lang, array $escaped) : string
    {
        require_code('urls');

        if (isset($param[0])) {
            list($zone, $map, $hash) = page_link_decode(isset($param[0]->codename)/*faster than is_object*/ ? $param[0]->evaluate() : $param[0]);

            $skip = [];

            if (isset($param[1])) {
                $avoid_remap = !empty($param[1]);
                $skip_keep = !empty($param[2]);
                $keep_all = !empty($param[3]);
                if (isset($param[4])) {
                    $skip = array_flip(explode('|', $param[4]));
                }
            } else {
                $avoid_remap = false;
                $skip_keep = false;
                $keep_all = false;
            }

            $value = _build_url($map, $zone, $skip, $keep_all, $avoid_remap, $skip_keep, $hash);
        } else {
            $value = get_current_page_link();
        }

        if (!empty($escaped)) {
            apply_tempcode_escaping($escaped, $value);
        }
        return $value;
    }
}
