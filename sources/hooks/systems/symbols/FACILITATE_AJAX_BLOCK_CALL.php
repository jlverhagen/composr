/**
 * Hook class.
 */
class Hook_symbol_FACILITATE_AJAX_BLOCK_CALL
{
    /**
     * Get information about this symbol.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        return [
            'compile' => SYMBOL_COMPILE_STATIC_NONE,
        ];
    }

    /**
     * Run function for symbol hooks. Searches for tasks to perform.
     *
     * @param  array $param Symbol parameters
     * @param  string $lang The language to evaluate this symbol in (some symbols refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @return string Result
     */
    public function run(array $param, string $lang, array $escaped) : string
    {
        $value = '';
        if ($GLOBALS['XSS_DETECT']) {
            ocp_mark_as_escaped($value);
        }

        if (!empty($param[0])) {
            $auth_key = '';

            require_code('blocks');
            $map = comma_list_str_to_arr($param[0]);
            $_block_constraints = block_params_to_block_signature($map);
            if (isset($param[1])) {
                $_block_constraints = array_merge($_block_constraints, comma_list_str_to_arr($param[1]));
                ksort($_block_constraints);
            }
            $block_constraints = comma_list_arr_to_str($_block_constraints);

            // Store permissions
            $pass = false;
            $_safelisted_blocks = get_value('safelisted_blocks');
            if (!empty($_safelisted_blocks)) {
                $safelisted_blocks = explode(',', $_safelisted_blocks);
                if (in_array($map['block'], $safelisted_blocks)) {
                    $pass = true;
                }
            }
            if (!$pass) {
                $_auth_key = $GLOBALS['SITE_DB']->query_select('temp_block_permissions', ['id', 'p_time'], [
                    'p_session_id' => is_guest() ? '' : get_session_id(),
                    'p_block_constraints' => $block_constraints,
                ], '', 1);
                if (!isset($_auth_key[0])) {
                    $auth_key = $GLOBALS['SITE_DB']->query_insert('temp_block_permissions', [
                        'p_session_id' => is_guest() ? '' : get_session_id(),
                        'p_block_constraints' => $block_constraints,
                        'p_time' => time(),
                    ], true);
                } else {
                    $auth_key = $_auth_key[0]['id'];
                    if (time() - $_auth_key[0]['p_time'] > 100) {
                        $GLOBALS['SITE_DB']->query_update('temp_block_permissions', ['p_time' => time()], [
                            'p_session_id' => is_guest() ? '' : get_session_id(),
                            'p_block_constraints' => $block_constraints,
                        ], '', 1);
                    }
                }
            }

            $keep = symbol_tempcode('KEEP');
            $self_url_encoded = static_evaluate_tempcode(protect_url_parameter(get_self_url(true)));
            $value = find_script('snippet') . '?snippet=block&self_url=' . urlencode($self_url_encoded) . '&block_map=' . urlencode($param[0]) . $keep->evaluate();
            if (get_param_string('utheme', null) !== null) {
                $value .= '&utheme=' . urlencode($GLOBALS['FORUM_DRIVER']->get_theme());
            }
            if (!empty($auth_key)) {
                $value .= '&auth_key=' . urlencode(strval($auth_key));
            }
        }

        return $value;
    }
}

