/**
 * Hook class.
 */
class Hook_cron_bayes_antispam
{
    /**
     * Get info from this hook.
     *
     * @param  ?TIME $last_run Last time run (null: never)
     * @param  ?boolean $calculate_num_queued Calculate the number of items queued, if possible (null: the hook may decide / low priority)
     * @return ?array Return a map of info about the hook (null: disabled)
     */
    public function info(?int $last_run, ?bool $calculate_num_queued) : ?array
    {
        if (!addon_installed('bayes_antispam')) {
            return null;
        }
        if (!addon_installed('bayes_common')) {
            return null;
        }

        return [
            'label' => 'Bayes antispam -- ham training',
            'num_queued' => null,
            'minutes_between_runs' => 15,
            'enabled_by_default' => true,
        ];
    }

    /**
     * Run function for system scheduler hooks. Searches for things to do. ->info(..., true) must be called before this method.
     *
     * @param  ?TIME $last_run Last time run (null: never)
     */
    public function run(?int $last_run)
    {
        // Training ham data...

        if ($last_run === null) {
            require_code('global4');
            $_last_run = get_site_start_time();
        } else {
            $_last_run = $last_run;
        }
        $start_time = $_last_run - (60 * 60 * 24 * 7);
        $end_time = time() - (60 * 60 * 24 * 7);

        // Queue up ham training into individual tasks
        push_query_limiting(true);
        cms_extend_time_limit(TIME_LIMIT_EXTEND__SLOW);
        raise_php_memory_limit();
        require_code('antispam2');
        require_code('content');
        require_code('tasks');
        require_lang('bayes_antispam');

        $hooks = find_all_hook_obs('systems', 'content_meta_aware', 'Hook_content_meta_aware_');
        $hooks = array_merge($hooks, find_all_hook_obs('systems', 'resource_meta_aware', 'Hook_resource_meta_aware_'));
        foreach ($hooks as $hook => $ob) {
            $info = $ob->info();
            if ($info === null) {
                continue;
            }
            if (!isset($info['additional_antispam_fields'])) {
                continue;
            }
            if (!isset($info['add_time_field'])) { // We need this to figure out what to train
                continue;
            }

            $start = 0;
            $max = 100;
            do {
                $where = [];
                $add_time_field = $info['add_time_field'];

                // Unreliable because validation time is not when the content was actually validated, and we do not have special checking for validated
                /*
                if (isset($info['validated_field'])) {
                    $where[$info['validated_field']] = 1;
                    if (isset($info['validation_time_field'])) {
                        $add_time_field = $info['validation_time_field'];
                    }
                }
                */
                $rows = $info['db']->query_select($info['table'], ['*'], $where, ' AND ' . $add_time_field . '>=' . strval($start_time) . ' AND ' . $add_time_field . '<' . strval($end_time), $max, $start);
                foreach ($rows as $row) {
                    $id = $ob->get_id($row);
                    $submitter = $ob->get_submitter($row);
                    call_user_func_array__long_task(do_lang('HAM_TRAINING'), null, 'bayes_antispam', [['ham'], $hook, $id, $submitter], false, false, false);
                }

                $start += $max;
            } while (count($rows) > 0);
        }
    }
}
