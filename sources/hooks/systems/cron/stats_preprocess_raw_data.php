/**
 * Hook class.
 */
class Hook_cron_stats_preprocess_raw_data
{
    public $label = 'stats:STATS_PREPROCESS_RAW_DATA_CRON';
    public $fallback_label = 'Stats preprocessing';
    protected const END_TIME_CUTOFF = 60 * 60; // Only process up to one hour at a time to avoid server freezes.
    protected const INITIAL_BACK_TIME = 24 * 60 * 60 * 31; // Don't calculate stats older than 31 days ago to prevent server freezes.

    /**
     * Get info from this hook.
     *
     * @param  ?TIME $last_run Last time run (null: never)
     * @param  ?boolean $calculate_num_queued Calculate the number of items queued, if possible (null: the hook may decide / low priority)
     * @return ?array Return a map of info about the hook (null: disabled)
     */
    public function info(?int $last_run, ?bool $calculate_num_queued) : ?array
    {
        if (!addon_installed('stats')) {
            return null;
        }

        $minutes_between_runs = 15; // Standard; stats runs a bunch of database queries, so we do not want to run too often if we are caught up.

        $catching_up = get_value('stats_catching_up', null, true);

        if (($last_run === null) || ($catching_up !== '0')) {
            $minutes_between_runs = 1; // We have to catch up
        }

        return [
            'num_queued' => null,
            'minutes_between_runs' => $minutes_between_runs,
            'enabled_by_default' => true,
        ];
    }

    /**
     * Run function for system scheduler hooks. Searches for tasks to perform.
     */
    public function run()
    {
        // Prevent dog-piling
        set_value('stats_catching_up', '0', true);

        $start_time = null;

        // LEGACY: 11.beta9
        $_start_time = get_value('stats__last_processed', null, true);
        if ($_start_time !== null) {
            delete_value('stats__last_processed', true);
            $GLOBALS['SITE_DB']->query_delete('stats_preprocessed');
            $GLOBALS['SITE_DB']->query_delete('stats_preprocessed_flat');
        }

        $hook_start = time();

        require_code('global3');
        require_code('stats');
        require_lang('stats');
        require_code('files');

        push_query_limiting(false);
        disable_php_memory_limit();

        // Determine if we are in need of processing deltas; these are done first
        $pending_deltas = $GLOBALS['SITE_DB']->get_table_count_approx('stats_preprocessed_delta');
        $doing_deltas = ($pending_deltas > 0);

        if ($doing_deltas) {
            stats_merge_deltas();
        }

        // Memory and time check
        $ml = php_return_bytes(ini_get('memory_limit'));
        $current_memory = memory_get_usage(false);
        $near_limit = (($ml > 0) && ($current_memory >= ($ml - (1024 * 1024 * 8)))); // within 8 MB of PHP memory limit
        if (($near_limit) || ((time() - $hook_start) >= 15)) {
            set_value('stats_catching_up', '1', true);
            pop_query_limiting();
            return;
        }

        cms_profile_start_for('Hook_cron_stats_preprocess_raw_data preprocess_raw_data_for');

        $catching_up = false;

        $hook_obs = array_keys(find_all_hooks('modules', 'admin_stats'));
        cms_shuffle_assoc($hook_obs);

        foreach ($hook_obs as $hook_name) {
            $_start_time = get_value('stats__last_processed__' . $hook_name, null, true);
            if ($_start_time === null) {
                require_code('global4');
                $start_time = get_site_start_time();
            } else {
                $start_time = intval($_start_time);
            }

            // Do not process too far back
            if ($start_time < (time() - self::INITIAL_BACK_TIME)) {
                $start_time = (time() - self::INITIAL_BACK_TIME);
            }

            /*
                NB: We subtract 1 second due to an edge case; the current second is not over yet, so additional stats (especially views)
                that happen this second might later get logged. If we process this second now, those views / stats might get neglected.
            */
            $end_time = (time() - 1);

            // Do not process too much at once
            if (($end_time - $start_time) > self::END_TIME_CUTOFF) {
                $end_time = ($start_time + self::END_TIME_CUTOFF);
                $catching_up = true;
            }

            preprocess_raw_data_for($hook_name, $start_time, $end_time);

            set_value('stats__last_processed__' . $hook_name, strval($end_time), true);

            // Memory and time check
            $ml = php_return_bytes(ini_get('memory_limit'));
            $current_memory = memory_get_usage(false);
            $near_limit = (($ml > 0) && ($current_memory >= ($ml - (1024 * 1024 * 8)))); // within 8 MB of PHP memory limit
            if (($near_limit) || ((time() - $hook_start) >= 15)) {
                $catching_up = true;
                break;
            }
        }

        if ($catching_up) {
            set_value('stats_catching_up', '1', true);
        }

        // Send KPI notifications...

        send_kpi_notifications();

        pop_query_limiting();

        cms_profile_end_for('Hook_cron_stats_preprocess_raw_data preprocess_raw_data_for');
    }
}
