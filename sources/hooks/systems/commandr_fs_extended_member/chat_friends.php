/**
 * Hook class.
 */
class Hook_commandr_fs_extended_member__chat_friends
{
    /**
     * Whether the filesystem hook is active.
     *
     * @return boolean Whether it is
     */
    public function is_active() : bool
    {
        return addon_installed('chat');
    }

    /**
     * Read a virtual property for a member file.
     *
     * @param  MEMBER $member_id The member ID
     * @return mixed The data
     */
    public function read_property(int $member_id)
    {
        return table_to_portable_rows('chat_friends', [], ['member_likes' => $member_id]);
    }

    /**
     * Read a virtual property for a member file.
     *
     * @param  MEMBER $member_id The member ID
     * @param  mixed $data The data
     */
    public function write_property(int $member_id, $data)
    {
        table_from_portable_rows('chat_friends', $data, ['member_likes' => $member_id], TABLE_REPLACE_MODE_BY_EXTRA_FIELD_DATA);
    }
}
