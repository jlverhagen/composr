                    'EDIT_THIS_CALENDAR_EVENT' => '_SEARCH:cms_calendar:_edit:{ID}',
                    'ADD_CALENDAR_EVENT' => '_SEARCH:cms_calendar:add:e_type={TYPE,OPTIONAL}',
                ],
            ],
            'DELETE_CALENDAR_EVENT' => [
                'flags' => ACTIONLOG_FLAGS_NONE,
                'cma_hook' => 'event',
                'identifier_index' => 0,
