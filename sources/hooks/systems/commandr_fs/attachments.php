require_code('resource_fs');

/**
 * Hook class.
 */
class Hook_commandr_fs_attachments extends Resource_fs_base
{
    public $file_resource_type = 'attachment';

    /**
     * Standard Commandr-fs function for seeing how many resources are. Useful for determining whether to do a full rebuild.
     *
     * @param  ID_TEXT $resource_type The resource type
     * @return integer How many resources there are
     */
    public function get_resources_count(string $resource_type) : int
    {
        return $GLOBALS['SITE_DB']->query_select_value('attachments', 'COUNT(*)');
    }

    /**
     * Standard Commandr-fs function for searching for a resource by label.
     *
     * @param  ID_TEXT $resource_type The resource type
     * @param  LONG_TEXT $label The resource label
     * @return array A list of resource IDs
     */
    public function find_resource_by_label(string $resource_type, string $label) : array
    {
        $ret = $GLOBALS['SITE_DB']->query_select('attachments', ['id'], ['a_original_filename' => $label], 'ORDER BY id');
        return collapse_1d_complexity('id', $ret);
    }

    /**
     * Whether the filesystem hook is active.
     *
     * @return boolean Whether it is
     */
    public function is_active() : bool
    {
        return true;
    }

    /**
     * Standard Commandr-fs load function for resource-fs hooks. Finds the properties for some resource.
     *
     * @param  SHORT_TEXT $filename Filename
     * @param  string $path The path (blank: root / not applicable). It may be a wildcarded path, as the path is used for content-type identification only. Filenames are globally unique across a hook; you can calculate the path using ->search.
     * @return ~array Details of the resource (false: error)
     */
    public function file_load(string $filename, string $path)
    {
        list($resource_type, $resource_id) = $this->file_convert_filename_to_id($filename);

        $rows = $GLOBALS['SITE_DB']->query_select('attachments', ['*'], ['id' => intval($resource_id)], '', 1);
        if (!array_key_exists(0, $rows)) {
            return false;
        }
        $row = $rows[0];

        $properties = [
            'member_id' => remap_resource_id_as_portable('member', $row['a_member_id']),
            'file_size' => $row['a_file_size'],
            'url' => remap_urlpath_as_portable($row['a_url']),
            'thumb_url' => remap_urlpath_as_portable($row['a_thumb_url']),
            'original_filename' => $row['a_original_filename'],
            'num_downloads' => $row['a_num_downloads'],
            'last_downloaded_time' => remap_time_as_portable($row['a_last_downloaded_time']),
            'description' => $row['a_description'],
            'add_time' => remap_time_as_portable($row['a_add_time']),
        ];
        $this->_resource_load_extend($resource_type, $resource_id, $properties, $filename, $path);
        return $properties;
    }

    /**
     * Standard Commandr-fs add function for resource-fs hooks. Adds some resource with the given label and properties.
     * Attachments are not designed to be created via Resource-fs directly; return false to mark unsupported.
     *
     * @param  LONG_TEXT $filename Filename OR Resource label
     * @param  string $path The path (blank: root / not applicable)
     * @param  array $properties Properties (may be empty)
     * @param  ?ID_TEXT $force_type Resource type to try to force (null: do not force)
     * @return ~ID_TEXT The resource ID (false: error / unsupported)
     */
    public function file_add(string $filename, string $path, array $properties, ?string $force_type = null)
    {
        return false; // TODO
    }

    /**
     * Standard Commandr-fs edit function for resource-fs hooks. Attachments are immutable via Resource-fs for safety.
     *
     * @param  ID_TEXT $filename The filename
     * @param  string $path The path (blank: root / not applicable)
     * @param  array $properties Properties (may be empty)
     * @param  boolean $explicit_move Whether we are definitely moving
     * @return ~ID_TEXT The resource ID (false: error / unsupported)
     */
    public function file_edit(string $filename, string $path, array $properties, bool $explicit_move = false)
    {
        return false; // TODO
    }

    /**
     * Standard Commandr-fs delete function for resource-fs hooks. Attachments should be removed via normal APIs.
     *
     * @param  ID_TEXT $filename The filename
     * @param  string $path The path (blank: root / not applicable)
     * @return boolean Success status
     */
    public function file_delete(string $filename, string $path) : bool
    {
