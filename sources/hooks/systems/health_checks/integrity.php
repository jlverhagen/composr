    /**
     * Run a section of health checks.
     *
     * @param  integer $check_context The current state of the website (a CHECK_CONTEXT__* constant)
     * @param  boolean $manual_checks Mention manual checks
     * @param  boolean $automatic_repair Do automatic repairs where possible
     * @param  ?boolean $use_test_data_for_pass Should test data be for a pass [if test data supported] (null: no test data)
     * @param  ?array $urls_or_page_links List of URLs and/or page-links to operate on, if applicable (null: those configured)
     * @param  ?array $comcode_segments Map of field names to Comcode segments to operate on, if applicable (null: N/A)
     */
    public function testDatabaseCorruption(int $check_context, bool $manual_checks = false, bool $automatic_repair = false, ?bool $use_test_data_for_pass = null, ?array $urls_or_page_links = null, ?array $comcode_segments = null)
    {
        if ($check_context == CHECK_CONTEXT__INSTALL) {
            $this->stateCheckSkipped('Skipped; we are running from installer.');
            return;
        }
        if ($check_context == CHECK_CONTEXT__SPECIFIC_PAGE_LINKS) {
            $this->stateCheckSkipped('Skipped; running on specific page links.');
            return;
        }

        if (strpos(get_db_type(), 'mysql') !== false) {
            push_db_scope_check(false);

            $tables = $GLOBALS['SITE_DB']->query_select('db_meta', ['DISTINCT m_table']);
            foreach ($tables as $table) {
                $results = $GLOBALS['SITE_DB']->query('CHECK TABLE ' . get_table_prefix() . $table['m_table']);
                $msg_text = $results[0]['Msg_text'];
                $ok = ($msg_text == 'OK') || (strpos($msg_text, 'closed the table properly') !== false/*common false positive*/) || (strpos($msg_text, 'doesn\'t support check') !== false);

                $message = 'Corrupt table likely needing repairing: [tt]' . $table['m_table'] . '[/tt] gave status "' . $results[0]['Msg_text'] . '"';
                if (!$ok) {
                    if ($automatic_repair) {
                        $results_repair = $GLOBALS['SITE_DB']->query('REPAIR TABLE ' . get_table_prefix() . $table['m_table']);
                        $ok_repair = $results_repair[0]['Msg_text'] == 'OK';
                        if ($ok_repair) {
                            $message = 'Corrupt table automatically repaired: [tt]' . $table['m_table'] . '[/tt] gave status "' . $results[0]['Msg_text'] . '"';
                        }
                    }
                }
                $this->assertTrue($ok, $message);
            }

            pop_db_scope_check();
        } else {
            $this->stateCheckSkipped('Can only check when running MySQL (or MariaDB)');
        }
    }

    /**
     * Run a section of health checks.
     *
     * @param  integer $check_context The current state of the website (a CHECK_CONTEXT__* constant)
     * @param  boolean $manual_checks Mention manual checks
     * @param  boolean $automatic_repair Do automatic repairs where possible
     * @param  ?boolean $use_test_data_for_pass Should test data be for a pass [if test data supported] (null: no test data)
     * @param  ?array $urls_or_page_links List of URLs and/or page-links to operate on, if applicable (null: those configured)
     * @param  ?array $comcode_segments Map of field names to Comcode segments to operate on, if applicable (null: N/A)
     */
    public function testDatabaseDataIntegrity(int $check_context, bool $manual_checks = false, bool $automatic_repair = false, ?bool $use_test_data_for_pass = null, ?array $urls_or_page_links = null, ?array $comcode_segments = null)
    {
        if ($check_context == CHECK_CONTEXT__INSTALL) {
            $this->stateCheckSkipped('Skipped; we are running from the installer.');
            return;
        }
        if ($check_context == CHECK_CONTEXT__SPECIFIC_PAGE_LINKS) {
            $this->stateCheckSkipped('Skipped; running on specific page links.');
            return;
        }

        if (strpos(get_db_type(), 'mysql') === false) {
            $this->stateCheckSkipped('Can only check when running MySQL (or MariaDB)');
            return;
        }

        require_code('database');
        $old = cms_extend_time_limit(TIME_LIMIT_EXTEND__MODEST);

        $count_bad_rows = 0;

        $max = 10;
        $start = 0;
        do {
            $rows = $GLOBALS['SITE_DB']->query_select('db_meta_foreign_keys', ['*'], [], '', $max, $start);

            foreach ($rows as $row) {
                $db = get_db_for($row['from_table']);
                $db_to = get_db_for($row['to_table']);
                $special_values = @unserialize($row['special_values']);

                $query = 'SELECT COUNT(*) FROM `' . $db->table_prefix . $row['from_table'] . '` AS `ft`';
                $query .= ' LEFT JOIN `' . $db_to->table_prefix . $row['to_table'] . '` AS `tt` ON `ft`.`' . $row['from_field'] . '` = `tt`.`' . $row['to_field'] . '`';
                $query .= ' WHERE `tt`.`' . $row['to_field'] . '` IS NULL';
                $query .= ' AND `ft`.`' . $row['from_field'] . '` IS NOT NULL';
                if (is_array($special_values) && (count($special_values) > 0)) {
                    $escaped_values = '';
                    foreach ($special_values as $i => $val) {
                        if ($i > 0) {
                            $escaped_values .= ',';
                        }
                        if (is_string($val)) {
                            $escaped_values .= '\'' . db_escape_string($val) . '\'';
                        } else {
                            $escaped_values .= strval($val);
                        }
                    }
                    $query .= ' AND `ft`.`' . $row['from_field'] . '` NOT IN (' . $escaped_values . ')';
                }

                $result = $db->query_value_if_there($query);

                $count_bad_rows += $result;
            }

            $start += $max;
        } while (isset($rows) && count($rows) > 0);

        cms_set_time_limit($old);

        $this->assertTrue(($count_bad_rows == 0), 'Detected orphaned database rows @ ' . integer_format($count_bad_rows) . ' (you may wish to take a database backup and then run the data integrity tool in the upgrader).');
    }

    /**
     * Run a section of health checks.
     *
     * @param  integer $check_context The current state of the website (a CHECK_CONTEXT__* constant)
     * @param  boolean $manual_checks Mention manual checks
     * @param  boolean $automatic_repair Do automatic repairs where possible
     * @param  ?boolean $use_test_data_for_pass Should test data be for a pass [if test data supported] (null: no test data)
     * @param  ?array $urls_or_page_links List of URLs and/or page-links to operate on, if applicable (null: those configured)
     * @param  ?array $comcode_segments Map of field names to Comcode segments to operate on, if applicable (null: N/A)
     */
    public function testUpgradeCompletion(int $check_context, bool $manual_checks = false, bool $automatic_repair = false, ?bool $use_test_data_for_pass = null, ?array $urls_or_page_links = null, ?array $comcode_segments = null)
    {
        if ($check_context == CHECK_CONTEXT__INSTALL) {
            $this->stateCheckSkipped('Skipped; we are running from installer.');
            return;
        }
        if ($check_context == CHECK_CONTEXT__SPECIFIC_PAGE_LINKS) {
            $this->stateCheckSkipped('Skipped; running on specific page links.');
            return;
        }

        $version_files = cms_version_number();
        $_version_database = get_value('version');
        $version_database = floatval($_version_database);
        $this->assertTrue($version_files <= $version_database, 'The software seems to need an upgrade (on-disk ' . float_format($version_files, 1) . ' vs in-database ' . float_format($version_database, 1) . '), run upgrader');

        $version_files_database = strval(cms_version_time_db());
        $version_database_database = get_value('db_version', 'unknown', true);
        $this->assertTrue($version_files <= $version_database, 'The database seems to need an upgrade (on-disk ' . $version_files_database . ' vs in-database ' . $version_database_database . '), run upgrader');

        $_version_database = get_value('cns_version');
        $version_database = floatval($_version_database);
        $this->assertTrue($version_files <= $version_database, 'Conversr seems to need an upgrade (on-disk ' . float_format($version_files, 1) . ' vs in-database ' . float_format($version_database, 1) . '), run upgrader');
    }

