/**
 * Hook class.
 */
class Hook_directive_BOX
{
    /**
     * Get information about this directive.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        return [];
    }

    /**
     * Run function for directive hooks.
     *
     * @param  string $value The value, passed by reference
     * @param  array $param Directive parameters
     * @param  string $lang The language to evaluate this directive in (some directives refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @param  ID_TEXT $template_name The name of the template this came from (blank: not from a file / unknown)
     */
    public function run(string &$value, array $param, string $lang, array $escaped, string $template_name)
    {
        require_code('templates');

        unset($param['vars']);
        $title = isset($param[1]) ? $param[0]->evaluate() : '';
        $box_type = isset($param[2]) ? $param[1]->evaluate() : '';
        $width = isset($param[3]) ? $param[2]->evaluate() : '';
        $options = isset($param[4]) ? $param[3]->evaluate() : '';
        $meta = isset($param[5]) ? $param[4]->evaluate() : '';
        $links = isset($param[6]) ? $param[5]->evaluate() : '';
        $top_links = isset($param[7]) ? $param[6]->evaluate() : '';
        $class = isset($param[8]) ? $param[7]->evaluate() : '';
        $tmp = put_in_standard_box(array_pop($param), make_string_tempcode($title), $box_type, $width, $options, $meta, $links, $top_links, $class);
        $value = $tmp->evaluate();
    }
}
