/**
 * Hook class.
 */
class Hook_directive_CASES
{
    /**
     * Get information about this directive.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        return [];
    }

    /**
     * Run function for directive hooks.
     *
     * @param  string $value The value, passed by reference
     * @param  array $param Directive parameters
     * @param  string $lang The language to evaluate this directive in (some directives refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @param  ID_TEXT $template_name The name of the template this came from (blank: not from a file / unknown)
     */
    public function run(string &$value, array $param, string $lang, array $escaped, string $template_name)
    {
        if (isset($param[1])) {
            $value = '';
            $compare = $param[0]->evaluate();
            $substring = (isset($param[2]) && $param[1]->evaluate() == '1');
            $regexp = (isset($param[2]) && $param[1]->evaluate() == '2');
            $explode = explode(chr(10), trim($param[isset($param[2]) ? 2 : 1]->evaluate()));
            foreach ($explode as $i => $case) {
                if (strpos($case, '=') === false) {
                    continue;
                }
                list($compare_case, $value_case) = explode('=', $case, 2);
                $compare_case = trim($compare_case);
                if (
                    ((!$substring) && (!$regexp) && ($compare_case == $compare)) || // Exact match
                    (($substring) && (($compare_case == '') || (strpos($compare, $compare_case) !== false))) || // Substring
                    (($regexp) && (preg_match('#' . str_replace('#', '\#', $compare_case) . '#', $compare) != 0)) || // Regexp
                    (($compare_case == '') && (!isset($explode[$i + 1]))) // The final default case
                ) {
                    $value = $value_case;
                    break;
                }
            }
        }
    }
}
