/**
 * Hook class.
 */
class Hook_directive_INCLUDE
{
    /**
     * Get information about this directive.
     *
     * @return ?array Array of information (null: hook disabled)
     */
    public function info() : ?array
    {
        return [];
    }

    /**
     * Run function for directive hooks.
     *
     * @param  string $value The value, passed by reference
     * @param  array $param Directive parameters
     * @param  string $lang The language to evaluate this directive in (some directives refer to language elements)
     * @param  array $escaped Array of escaping operations
     * @param  ID_TEXT $template_name The name of the template this came from (blank: not from a file / unknown)
     */
    public function run(string &$value, array $param, string $lang, array $escaped, string $template_name)
    {
        if (isset($param[1])) {
            $tpl_params = $param['vars'];
            $var_data = $param[count($param) - 2]->evaluate();
            $substitutions = parse_tempcode_include($var_data, $tpl_params);
            $_template_name = $param[0]->evaluate();
            $ex = isset($param[2]) ? $param[1]->evaluate() : '';
            if ($ex == '') {
                $ex = '.tpl';
            }
            $td = isset($param[3]) ? $param[2]->evaluate() : '';
            if ($td == '') {
                $td = 'templates';
            }
            $theme = isset($param[4]) ? $param[3]->evaluate() : '';
            if ($theme == '') {
                $theme = null;
            }
            $force_original = isset($param[5]) ? $param[4]->evaluate() : '';
            if ($force_original != '1') {
                $force_original = '0';
            }

            $_value = do_template($_template_name, $tpl_params, null, true, null, $ex, $td, $theme, ($template_name == $_template_name) || ($force_original == '1'));
            $value = $_value->evaluate();

            apply_tempcode_substitutions($value, $substitutions);
        }
    }
}
