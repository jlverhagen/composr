/**
 * Hook class.
 */
class Hook_main_custom_gfx_rollover_button
{
    /**
     * Standard graphic generator function. Creates custom graphics from parameters.
     *
     * @param  array $map Map of hook parameters (relayed from block parameters map)
     * @param  object $block The block itself (contains utility methods)
     * @return Tempcode HTML to output
     */
    public function run(array $map, object &$block) : object
    {
        require_code('fonts');
        $test = check_ttf();
        if ($test !== null) {
            return $test;
        }

        if (!array_key_exists('img1', $map)) {
            $map['img1'] = 'button1';
        }
        $img_path_1 = find_theme_image($map['img1'], true, true);
        if ($img_path_1 == '') {
            return do_lang_tempcode('NO_SUCH_THEME_IMAGE', escape_html($map['img1']));
        }

        $cache_id_1 = 'rollover1_' . get_block_id($map);
        $url_1 = $block->_do_image($cache_id_1, $map, $img_path_1);
        if (is_object($url_1)) {
            return $url_1;
        }

        if (!array_key_exists('img2', $map)) {
            $map['img2'] = 'button2';
        }
        $img_path_2 = find_theme_image($map['img2'], true, true);
        if ($img_path_2 == '') {
            return do_lang_tempcode('NO_SUCH_THEME_IMAGE', escape_html($map['img2']));
        }

        $cache_id_2 = 'rollover2_' . get_block_id($map);
        $url_2 = $block->_do_image($cache_id_2, $map, $img_path_2);
        if (is_object($url_2)) {
            return $url_2;
        }

        $comb_id = 'rollover_' . uniqid('', false);

        require_javascript('custom_comcode');
        $ret = '<img data-js-function-calls="[[\'gfxRolloverButton\', \'' . $comb_id . '\', \'' . escape_html(php_addslashes($url_2))  . '\']]" id="' . $comb_id . '" class="gfx-text-overlay" alt="' . str_replace("\n", ' ', escape_html($map['data'])) . '" src="' . escape_html($url_1) . '" />';

        if (function_exists('ocp_mark_as_escaped')) {
            ocp_mark_as_escaped($ret);
        }
        return make_string_tempcode($ret);
    }
}
