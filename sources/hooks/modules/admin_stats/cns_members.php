/**
 * Hook class.
 */
class Hook_admin_stats_cns_members extends CMSStatsProvider
{
    protected $default_age_brackets;

    /**
     * Constructor.
     */
    public function __construct()
    {
        $this->default_age_brackets = [
            '<13',
            '13-17',
            '18-24',
            '25-34',
            '35-44',
            '45-54',
            '55-64',
            '65+',
        ];
    }

    /**
     * Find metadata about stats graphs that are provided by this stats hook.
     *
     * @param  boolean $for_kpi Whether this is for setting up a KPI
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function info(bool $for_kpi = false) : ?array
    {
        if (get_forum_type() != 'cns') {
            return null;
        }

        require_lang('cns');
        require_code('locations');

        $ret = [
            'members' => [
                'label' => do_lang_tempcode('JOINING'),
                'category' => 'conversions',
                'filters' => [
                    'members__day_range' => new CMSStatsDayRangeFilter('members__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                    'members__country' => has_geolocation_data() ? new CMSStatsCountryFilter('members__country', do_lang_tempcode('VISITOR_COUNTRY')) : null,
                ],
                'pivot' => new CMSStatsDatePivot('members__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'demographics' => [
                'label' => do_lang_tempcode('AGE_RANGE_JOIN'),
                'category' => 'audience_demographics',
                'filters' => [
                    'demographics__day_range' => new CMSStatsDayRangeFilter('demographics__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                    'demographics__age_brackets' => new CMSStatsTextFilter('demographics__age_brackets', do_lang_tempcode('AGE_RANGE'), implode(',', $this->default_age_brackets)),
                ],
                'pivot' => null,
            ],
            'demographics_overall' => [
                'label' => do_lang_tempcode('AGE_RANGE'),
                'category' => 'audience_demographics',
                'filters' => [
                    'demographics_overall__age_brackets' => new CMSStatsTextFilter('demographics_overall__age_brackets', do_lang_tempcode('AGE_RANGE'), implode(',', $this->default_age_brackets)),
                ],
                'pivot' => null,
            ],
            'top_members_by_visits' => [
                'label' => do_lang_tempcode('TOP_MEMBERS_BY_VISITS'),
                'category' => 'feedback_and_engagement',
                'filters' => [
                ],
                'pivot' => null,
            ],
        ];

        if (addon_installed('cns_forum')) {
            $ret['top_members_by_forum_posts'] = [
                'label' => do_lang_tempcode('TOP_MEMBERS_BY_FORUM_POSTS'),
                'category' => 'feedback_and_engagement',
                'filters' => [
                ],
                'pivot' => null,
            ];
        }

        if (addon_installed('points')) {
            $ret['top_members_by_points'] = [
                'label' => do_lang_tempcode('TOP_MEMBERS_BY_POINTS'),
                'category' => 'feedback_and_engagement',
                'filters' => [
                ],
                'pivot' => null,
            ];
        }

        return $ret;
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     * @param  array $data_buckets Map of data buckets; a map of bucket name to nested maps with the following maps in sequence: 'pivot', 'pivot interval', 'pivot value' (then further map data); passed by reference only with pre-filled zero data to later be merged
     */
    public function preprocess_raw_data(int $start_time, int $end_time, array &$data_buckets)
    {
        require_code('locations');
        require_code('temporal');

        $server_timezone = get_server_timezone();

        $max = 1000;
        $start = 0;

        $date_pivots = $this->get_date_pivots();

        $query = 'SELECT m_join_time,m_dob_year,m_dob_month,m_dob_day,m_ip_address FROM ' . $GLOBALS['FORUM_DB']->get_table_prefix() . 'f_members WHERE ';
        $query .= 'm_join_time>=' . strval($start_time) . ' AND ';
        $query .= 'm_join_time<=' . strval($end_time);
        $query .= ' ORDER BY m_join_time';
        do {
            $rows = $GLOBALS['FORUM_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $timestamp = $row['m_join_time'];
                $timestamp = tz_time($timestamp, $server_timezone);

                $country = geolocate_ip($row['m_ip_address']);
                if ($country === null) {
                    $country = '';
                }

                foreach (array_keys($date_pivots) as $pivot) {
                    $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                    $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                    if (!isset($data_buckets['members'][$pivot][$pivot_interval][$pivot_value][$country])) {
                        $data_buckets['members'][$pivot][$pivot_interval][$pivot_value][$country] = 0;
                    }
                    $data_buckets['members'][$pivot][$pivot_interval][$pivot_value][$country]++;

                    if ($row['m_dob_year'] !== null) {
                        $age = intval(date('Y')) - $row['m_dob_year'];
                        if (date('md', cms_mktime(0, 0, 0, $row['m_dob_month'], $row['m_dob_day'], $row['m_dob_year'])) > date('md')) {
                            $age--;
                        }

                        if (!isset($data_buckets['demographics'][$pivot][$pivot_interval][$pivot_value][$age])) {
                            $data_buckets['demographics'][$pivot][$pivot_interval][$pivot_value][$age] = 0;
                        }
                        $data_buckets['demographics'][$pivot][$pivot_interval][$pivot_value][$age]++;
                    }
                }

                $this->dump_delta_if_necessary($data_buckets);
            }

            $start += $max;
        } while (!empty($rows));
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     * This is for flat and timeless data.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     * @param  array $data_buckets Map of data buckets; a map of bucket name to nested maps
     */
    public function preprocess_raw_data_flat(int $start_time, int $end_time, array &$data_buckets)
    {
        // Optimisation: as this always calculates full statistics, do not always calculate
        if (($end_time < (time() - (60 * 60 * 24))) || (mt_rand(0, 29) != 0)) {
            return;
        }

        // Required in early since its use is within a loop; we do not want to call many times
        if (addon_installed('points')) {
            require_code('points');
        }

        $max = 1000;
        $start = 0;

        $query = 'SELECT id,m_username,m_cache_num_posts,m_total_sessions,m_dob_year,m_dob_month,m_dob_day FROM ' . $GLOBALS['FORUM_DB']->get_table_prefix() . 'f_members WHERE ';
        $query .= 'id<>' . strval($GLOBALS['FORUM_DRIVER']->get_guest_id());
        do {
            $rows = $GLOBALS['FORUM_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $member_id = $row['id'];
                $username = $row['m_username'];

                $visits = $row['m_total_sessions'];
                if ($visits > 0) {
                    $data_buckets['top_members_by_visits'][$username] = $visits;
                }

                if (addon_installed('cns_forum')) {
                    $posts = $row['m_cache_num_posts'];
                    if ($posts > 0) {
                        $data_buckets['top_members_by_forum_posts'][$username] = $posts;
                    }
                }

                if (addon_installed('points')) {
                    $points = points_rank($member_id);
                    if ($points > 100) { // Hard-coded minimum
                        $data_buckets['top_members_by_points'][$username] = $points;
                    }
                }

                if ($row['m_dob_year'] !== null) {
                    $age = intval(date('Y')) - $row['m_dob_year'];
                    if (date('md', cms_mktime(0, 0, 0, $row['m_dob_month'], $row['m_dob_day'], $row['m_dob_year'])) > date('md')) {
                        $age--;
                    }

                    if (!isset($data_buckets['demographics_overall'][$age])) {
                        $data_buckets['demographics_overall'][$age] = 0;
                    }
                    $data_buckets['demographics_overall'][$age]++;
                }
            }

            $start += $max;
        } while (!empty($rows));
    }

    /**
     * Generate final data from preprocessed data.
     *
     * @param  string $bucket Data bucket we want data for
     * @param  string $pivot Pivot value
     * @param  array $filters Map of filters (including pivot if applicable)
     * @return ?array Final data in standardised map format (null: could not generate)
     */
    public function generate_final_data(string $bucket, string $pivot, array $filters) : ?array
    {
        switch ($bucket) {
            case 'members':
                $data = [];
                $_data = $this->prepare_preprocessed_data_for_graph($bucket, $pivot, $filters);

                foreach ($_data as $_pivot => $__data) {
                    foreach ($__data as $pivot_interval => $_) {
                        foreach ($_ as $pivot_value => $__) {
                            $pivot_value_nice = $this->make_date_pivot_value_nice($_pivot, $pivot_interval, $pivot_value);
                            if (!isset($data[$pivot_value_nice])) {
                                $data[$pivot_value_nice] = 0;
                            }

                            if ($__ === null) {
                                continue;
                            }

                            foreach ($__ as $country => $total_joins) {
                                if ((!empty($filters[$bucket . '__country'])) && ($filters[$bucket . '__country'] != $country)) {
                                    continue;
                                }

                                $data[$pivot_value_nice] += $total_joins;
                            }
                        }
                    }
                }

                return [
                    'type' => null,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
                    'y_axis_label' => do_lang_tempcode('NEW'),
                ];

            case 'demographics':
                $age_brackets = explode(',', $filters[$bucket . '__age_brackets']);

                $data = [do_lang('OTHER') => 0];
                foreach ($age_brackets as $bracket) {
                    $data[$bracket] = 0;
                }

                $_data = $this->prepare_preprocessed_data_for_graph($bucket, $pivot, $filters);

                foreach ($_data as $_pivot => $__data) {
                    foreach ($__data as $pivot_interval => $_) {
                        foreach ($_ as $pivot_value => $__) {
                            if ($__ === null) {
                                continue;
                            }

                            foreach ($__ as $age => $num_users) {
                                $bracket = $this->find_value_bracket($age_brackets, $age);
                                if ($bracket === null) {
                                    $data[do_lang('OTHER')] += $num_users;
                                } else {
                                    $data[$bracket] += $num_users;
                                }
                            }
                        }
                    }
                }

                if (array_sum($data) == 0) {
                    $data = [];
                }

                return [
                    'type' => self::GRAPH_BAR_CHART,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('AGE_RANGE_JOIN'),
                    'y_axis_label' => do_lang_tempcode('COUNT_MEMBERS'),
                ];

            case 'top_members_by_visits':
            case 'top_members_by_forum_posts':
            case 'top_members_by_points':
                $_data = $GLOBALS['SITE_DB']->query_select_value_if_there('stats_preprocessed_flat', 'p_data', ['p_bucket' => $bucket]);
                if ($_data !== null) {
                    $data = @unserialize($_data);
                    if ($data === false) {
                        $data = [];
                    }
                } else {
                    $data = [];
                }

                switch ($bucket) {
                    case 'top_members_by_visits':
                        $y_axis_label = do_lang_tempcode('COUNT_TOTAL');
                        break;

                    case 'top_members_by_forum_posts':
                        $y_axis_label = do_lang_tempcode('COUNT_POSTS');
                        break;

                    case 'top_members_by_points':
                        $y_axis_label = do_lang_tempcode('POINTS');
                        break;

                    default:
                        $y_axis_label = new Tempcode();
                        fatal_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('d19f7e9d0cae5124bd53f48088284f2c')));
                }

                return [
                    'type' => self::GRAPH_BAR_CHART,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('USERNAME'),
                    'y_axis_label' => $y_axis_label,
                    'limit_bars' => true,
                ];
            case 'demographics_overall':
                $age_brackets = explode(',', $filters[$bucket . '__age_brackets']);

                $data = [do_lang('OTHER') => 0];
                foreach ($age_brackets as $bracket) {
                    $data[$bracket] = 0;
                }

                $_data = $GLOBALS['SITE_DB']->query_select_value_if_there('stats_preprocessed_flat', 'p_data', ['p_bucket' => $bucket]);
                if ($_data !== null) {
                    $__data = @unserialize($_data);
                    if ($__data === false) {
                        $__data = [];
                    }
                } else {
                    $__data = [];
                }

                foreach ($__data as $age => $num_users) {
                    $bracket = $this->find_value_bracket($age_brackets, $age);
                    if ($bracket === null) {
                        $data[do_lang('OTHER')] += $num_users;
                    } else {
                        $data[$bracket] += $num_users;
                    }
                }

                return [
                    'type' => self::GRAPH_BAR_CHART,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('AGE_RANGE'),
                    'y_axis_label' => do_lang_tempcode('COUNT_MEMBERS'),
                ];
        }

        fatal_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('e4ea4767cb295139b3602cd41914f4cf')));
    }
}
