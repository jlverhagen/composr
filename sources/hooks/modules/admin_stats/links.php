/**
 * Hook class.
 */
class Hook_admin_stats_links extends Source_hook_stats_provider
{
    /**
     * Get a list of top events.
     *
     * @return array List of events
     */
    protected function get_top_urls() : array
    {
        static $urls = null;
        if ($urls !== null) {
            return $urls;
        }
        $urls = [];
        $url_rows = $GLOBALS['SITE_DB']->query_select('stats_known_links', ['*'], [], 'ORDER BY l_count_logged DESC', 50);
        foreach ($url_rows as $url_row) {
            $urls[$url_row['l_url']] = $url_row['l_url'] . ' (' . integer_format($url_row['l_count_logged']) . ')';
        }
        asort($urls);
        return $urls;
    }

    /**
     * Find metadata about stats graphs that are provided by this stats hook.
     *
     * @param  boolean $for_kpi Whether this is for setting up a KPI
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function info(bool $for_kpi = false) : ?array
    {
        $top_urls = $this->get_top_urls();

        require_code('locations');

        return [
            'link_tracking' => [
                'label' => do_lang_tempcode('LINK_TRACKING'),
                'category' => 'conversions',
                'filters' => [
                    'link_tracking__day_range' => new Source_stats_filter_day_range('link_tracking__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                    'link_tracking__url' => new Source_stats_filter_list('link_tracking__url', do_lang_tempcode('URL'), $top_urls),
                    'link_tracking__country' => has_geolocation_data() ? new Source_stats_filter_country('link_tracking__country', do_lang_tempcode('VISITOR_COUNTRY')) : null,
                ],
                'pivot' => new Source_stats_filter_date_pivot('link_tracking__pivot', $this->get_date_pivots(!$for_kpi)),
            ],
        ];
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     * @param  array $data_buckets Map of data buckets; a map of bucket name to nested maps with the following maps in sequence: 'pivot', 'pivot interval', 'pivot value' (then further map data); passed by reference only with pre-filled zero data to later be merged
     */
    public function preprocess_raw_data(int $start_time, int $end_time, array &$data_buckets)
    {
        require_code('temporal');

        $server_timezone = get_server_timezone();

        $max = 1000;
        $start = 0;

        $top_urls = $this->get_top_urls();

        $links_seen = [];

        $date_pivots = $this->get_date_pivots();

        $urls_seen = [];

        $query = 'SELECT * FROM ' . get_table_prefix() . 'stats_link_tracker WHERE ';
        $query .= 'c_date_and_time>=' . strval($start_time) . ' AND ';
        $query .= 'c_date_and_time<=' . strval($end_time);
        $query .= ' ORDER BY c_date_and_time';
        do {
            $rows = $GLOBALS['SITE_DB']->query($query, $max, $start);
            foreach ($rows as $link_row) {
                $timestamp = $link_row['c_date_and_time'];
                $timestamp = tz_time($timestamp, $server_timezone);

                $country_code = geolocate_ip($link_row['c_ip_address']);
                if ($country_code === null) {
                    $country_code = '';
                }

                $url = $link_row['c_url'];

                if (!isset($urls_seen[$url])) {
                    $urls_seen[$url] = 0;
                }
                $urls_seen[$url]++;

                foreach (array_keys($date_pivots) as $pivot) {
                    $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                    $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                    if (!isset($data_buckets['link_tracking'][$pivot][$pivot_interval][$pivot_value][$country_code][$url])) {
                        $data_buckets['link_tracking'][$pivot][$pivot_interval][$pivot_value][$country_code][$url] = 0;
                    }
                    $data_buckets['link_tracking'][$pivot][$pivot_interval][$pivot_value][$country_code][$url]++;
                }

                $this->dump_delta_if_necessary($data_buckets);
            }

            $start += $max;
        } while (!empty($rows));

        foreach ($urls_seen as $url => $times_seen) {
            $times_seen_before = $GLOBALS['SITE_DB']->query_select_value_if_there('stats_known_links', 'l_count_logged', ['l_url' => $url]);
            if ($times_seen_before === null) {
                $GLOBALS['SITE_DB']->query_insert('stats_known_links', [
                    'l_url' => $url,
                    'l_count_logged' => $times_seen,
                ]);
            } else {
                $GLOBALS['SITE_DB']->query_update('stats_known_links', [
                    'l_count_logged' => $times_seen + $times_seen_before,
                ], [
                    'l_url' => $url,
                ], '', 1);
            }
        }
    }

    /**
     * Generate final data from preprocessed data.
     *
     * @param  string $bucket Data bucket we want data for
     * @param  string $pivot Pivot value
     * @param  array $filters Map of filters (including pivot if applicable)
     * @return ?array Final data in standardised map format (null: could not generate)
     */
    public function generate_final_data(string $bucket, string $pivot, array $filters) : ?array
    {
        $data = [];
        $_data = $this->prepare_preprocessed_data_for_graph($bucket, $pivot, $filters);

        foreach ($_data as $_pivot => $__data) {
            foreach ($__data as $pivot_interval => $_) {
                foreach ($_ as $pivot_value => $__) {
                    $pivot_value_nice = $this->make_date_pivot_value_nice($_pivot, $pivot_interval, $pivot_value);
                    if (!isset($data[$pivot_value_nice])) {
                        $data[$pivot_value_nice] = 0;
                    }

                    if ($__ === null) {
                        continue;
                    }

                    foreach ($__ as $country => $___) {
                        if ((!empty($filters[$bucket . '__country'])) && ($filters[$bucket . '__country'] != $country)) {
                            continue;
                        }

                        foreach ($___ as $url => $value) {
                            if ((!empty($filters[$bucket . '__url'])) && ($filters[$bucket . '__url'] != $url)) {
                                continue;
                            }

                            $data[$pivot_value_nice] += $value;
                        }
                    }
                }
            }
        }

        return [
            'type' => null,
            'data' => $data,
            'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
            'y_axis_label' => do_lang_tempcode('COUNT_TOTAL'),
        ];
    }
}
