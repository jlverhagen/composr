/**
 * Hook class.
 */
class Hook_admin_stats_users_online extends Source_hook_stats_provider
{
    /**
     * Find metadata about stats graphs that are provided by this stats hook.
     *
     * @param  boolean $for_kpi Whether this is for setting up a KPI
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function info(bool $for_kpi = false) : ?array
    {
        return [
            'users_online' => [
                'label' => do_lang_tempcode('USERS_ONLINE'),
                'category' => 'hits',
                'filters' => [
                    'users_online__day_range' => new Source_stats_filter_day_range('users_online__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => null,
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
        ];
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     * This is for flat and timeless data.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     */
    public function preprocess_raw_data_flat(int $start_time, int $end_time)
    {
        // Optimisation: as this always calculates full statistics, do not always calculate
        if (($end_time < (time() - (60 * 60 * 24))) || (mt_rand(0, 29) != 0)) {
            return;
        }

        require_code('temporal');

        $max = 1000;
        $start = 0;

        $query = 'SELECT * FROM ' . get_table_prefix() . 'usersonline_track';
        do {
            $rows = $GLOBALS['SITE_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $timestamp = $row['date_and_time'];
                $date_interval = to_epoch_interval_index($timestamp, 'days');

                $this->save_stat('users_online', null, [$date_interval]);
            }

            $start += $max;
        } while (!empty($rows));
    }

    /**
     * Generate final data from preprocessed data.
     *
     * @param  string $bucket Data bucket we want data for
     * @param  string $pivot Pivot value
     * @param  array $filters Map of filters (including pivot if applicable)
     * @return ?array Final data in standardised map format (null: could not generate)
     */
    public function generate_final_data(string $bucket, string $pivot, array $filters) : ?array
    {
        $data = [];
        $__data = $GLOBALS['SITE_DB']->query_select_value_if_there('stats_preprocessed_flat', 'p_data', ['p_bucket' => $bucket]);
        if ($__data !== null) {
            $_data = @unserialize($__data);
            if ($_data === false) {
                $_data = [];
            }
        } else {
            $_data = [];
        }

        ksort($_data, SORT_NUMERIC);

        foreach ($_data as $_interval => $value) {
            // Makeshift day pivot
            if (isset($filters[$bucket . '__day_range'])) {
                list($min_day, $max_day) = $filters[$bucket . '__day_range'];
                if (($_interval < $min_day) || ($_interval > $max_day)) {
                    continue;
                }
            }

            $interval = $this->make_date_pivot_value_nice('day_series', $_interval, 0);

            $data[$interval] = $value;
        }

        return [
            'type' => null,
            'data' => $data,
            'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
            'y_axis_label' => do_lang_tempcode('USERS_ONLINE_RECORD'),
        ];
    }
}
