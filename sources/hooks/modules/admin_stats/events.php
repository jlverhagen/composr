                'label' => do_lang_tempcode('TRACKING_CODE_USAGE'),
                'category' => 'conversions',
                'filters' => [
                    'tracking_code_usage__day_range' => new Source_stats_filter_day_range('tracking_code_usage__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                    'tracking_code_usage__country' => new Source_stats_filter_country('tracking_code_usage__country', do_lang_tempcode('VISITOR_COUNTRY')),
                    'tracking_code_usage__event' => new Source_stats_filter_list('tracking_code_usage__tracking_code', do_lang_tempcode('TRACKING_CODE'), $top_tracking_codes),
                ],
                'pivot' => new Source_stats_filter_date_pivot('tracking_code_usage__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'conversion_rates' => [
                'label' => do_lang_tempcode('CONVERSION_RATES'),
                'category' => 'conversions',
                'filters' => [
                    'conversion_rates__day_range' => new Source_stats_filter_day_range('conversion_rates__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                    'conversion_rates__country' => new Source_stats_filter_country('conversion_rates__country', do_lang_tempcode('VISITOR_COUNTRY')),
                    'conversion_rates__event' => new Source_stats_filter_list('conversion_rates__event', do_lang_tempcode('STATS_EVENT'), $top_events),
                ],
                'pivot' => new Source_stats_filter_date_pivot('conversion_rates__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'tracking_code_conversion_rates' => [
                'label' => do_lang_tempcode('TRACKING_CODE_CONVERSION_RATES'),
                'category' => 'conversions',
                'filters' => [
                    'tracking_code_conversion_rates__day_range' => new Source_stats_filter_day_range('tracking_code_conversion_rates__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                    'tracking_code_conversion_rates__country' => new Source_stats_filter_country('tracking_code_conversion_rates__country', do_lang_tempcode('VISITOR_COUNTRY')),
                    'tracking_code_conversion_rates__event' => new Source_stats_filter_list('tracking_code_conversion_rates__event', do_lang_tempcode('STATS_EVENT'), $top_events),
                    'tracking_code_conversion_rates_usage__event' => new Source_stats_filter_list('tracking_code_conversion_rates_usage__tracking_code', do_lang_tempcode('TRACKING_CODE'), $top_tracking_codes),
                ],
                'pivot' => new Source_stats_filter_date_pivot('tracking_code_conversion_rates__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
        ];
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     */
    public function preprocess_raw_data(int $start_time, int $end_time)
    {
        cms_profile_start_for('Hook_admin_stats_events->preprocess_raw_data');
        require_code('temporal');

        $server_timezone = get_server_timezone();

        $max = 100;
        $start = 0;

        require_code('locations');

        $top_events = $this->get_top_events();
        $top_tracking_codes = $this->get_top_tracking_codes();

        $date_pivots = $this->get_date_pivots();

        // Basic event processing...

        $events_seen = [];

        $query_events = 'SELECT * FROM ' . get_table_prefix() . 'stats_events WHERE ';
        $query_events .= 'e_date_and_time>=' . strval($start_time) . ' AND ';
        $query_events .= 'e_date_and_time<=' . strval($end_time);
        $query_events .= ' ORDER BY e_date_and_time';

        do {
            cms_profile_start_for('Hook_admin_stats_events->preprocess_raw_data stats_events loop ' . strval($start));

            $event_rows = $GLOBALS['SITE_DB']->query($query_events, $max, $start);
            foreach ($event_rows as $event_row) {
                $timestamp = $event_row['e_date_and_time'];
                $timestamp = tz_time($timestamp, $server_timezone);

                $country_code = $event_row['e_country_code'];
                $event = $event_row['e_event'];

                if (!isset($events_seen[$event])) {
                    $events_seen[$event] = 0;
                }
                $events_seen[$event]++;

                foreach (array_keys($date_pivots) as $pivot) {
                    $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                    $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                    if (!isset($this->data_buckets['events'][$pivot][$pivot_interval][$pivot_value][$event][$country_code])) {
                        $this->data_buckets['events'][$pivot][$pivot_interval][$pivot_value][$event][$country_code] = 0;
                    }
                    $this->data_buckets['events'][$pivot][$pivot_interval][$pivot_value][$event][$country_code]++;
                }
            }

            cms_profile_start_for('Hook_admin_stats_events->preprocess_raw_data stats_events loop ' . strval($start));

            $start += $max;
        } while (!empty($event_rows));

        // Processing of tracking codes...

        $tracking_codes_seen = [];

        $start = 0;

        // Find sessions
        $query_sessions = 'SELECT session_id,MIN(date_and_time) AS date_and_time FROM ' . get_table_prefix() . 'stats WHERE ';
        $query_sessions .= 'date_and_time>=' . strval($start_time) . ' AND ';
        $query_sessions .= 'date_and_time<=' . strval($end_time) . ' AND ';
        $query_sessions .= db_string_not_equal_to('session_id', '');
        $query_sessions .= ' GROUP BY session_id';
        $query_sessions .= ' ORDER BY date_and_time';
        do {
            cms_profile_start_for('Hook_admin_stats_events->preprocess_raw_data stats loop ' . strval($start));

            $session_rows = $GLOBALS['SITE_DB']->query($query_sessions, $max, $start);
            foreach ($session_rows as $session_row) {
                $timestamp = $session_row['date_and_time'];
                if ($timestamp < $start_time) {
                    continue;
                }
                $timestamp = tz_time($timestamp, $server_timezone);

                // Use anonymous identifiers so it is hard to trace back to specific IPs or sessions
                $session_id = cms_base64_encode($session_row['session_id'], false, true, true);

                // Find tracking codes for this session
                cms_profile_start_for('Hook_admin_stats_events->preprocess_raw_data stats loop ' . strval($start) . ' tracking codes ' . $session_id);
                $ip = null;
                $tracking_codes = [];
                $tracking_code_rows = $GLOBALS['SITE_DB']->query_select('stats', ['tracking_code', 'ip'], ['session_id' => $session_id], ' AND ' . db_string_not_equal_to('tracking_code', ''));
                foreach ($tracking_code_rows as $tracking_code_row) {
                    if ($ip === null) {
                        $ip = $tracking_code_row['ip'];
                    }
                    $tracking_codes = array_merge($tracking_codes, explode(',', $tracking_code_row['tracking_code']));
                }
                $tracking_codes = array_unique($tracking_codes);

                $country_code = geolocate_ip($ip);
                if ($country_code === null) {
                    $country_code = '';
                }

                // Each tracking code
                foreach ($tracking_codes as $tracking_code) {
                    if (!isset($tracking_codes_seen[$tracking_code])) {
                        $tracking_codes_seen[$tracking_code] = 0;
                    }
                    $tracking_codes_seen[$tracking_code]++;

                    foreach (array_keys($date_pivots) as $pivot) {
                        $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                        $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                        if (!isset($this->data_buckets['tracking_code_usage'][$pivot][$pivot_interval][$pivot_value][$tracking_code][$country_code])) {
                            $this->data_buckets['tracking_code_usage'][$pivot][$pivot_interval][$pivot_value][$tracking_code][$country_code] = 0;
                        }
                        $this->data_buckets['tracking_code_usage'][$pivot][$pivot_interval][$pivot_value][$tracking_code][$country_code]++;
                    }
                }

                cms_profile_end_for('Hook_admin_stats_events->preprocess_raw_data stats loop ' . strval($start) . ' tracking codes ' . $session_id);

                // Find events for this session
                cms_profile_start_for('Hook_admin_stats_events->preprocess_raw_data stats loop ' . strval($start) . ' events ' . $session_id);

                $events_for_session = collapse_2d_complexity('e_event', 'e_event', $GLOBALS['SITE_DB']->query_select('stats_events', ['e_event'], ['e_session_id' => $session_id]));

                // Each combination of event wrt session
                foreach (array_keys($top_events) as $event) {
                    foreach (array_keys($date_pivots) as $pivot) {
                        $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                        $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                        if (!isset($this->data_buckets['conversion_rates'][$pivot][$pivot_interval][$pivot_value][$event])) {
                            $this->data_buckets['conversion_rates'][$pivot][$pivot_interval][$pivot_value][$event] = [0, 0];
                        }

                        $this->data_buckets['conversion_rates'][$pivot][$pivot_interval][$pivot_value][$event][0]++;
                        if (isset($events_for_session[$event])) {
                            $this->data_buckets['conversion_rates'][$pivot][$pivot_interval][$pivot_value][$event][1]++;
                        }
                    }
                }

                // Each combination of event tracking code wrt session
                foreach (array_keys($top_tracking_codes) as $tracking_code) {
                    foreach (array_keys($top_events) as $event) {
                        foreach (array_keys($date_pivots) as $pivot) {
                            $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                            $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                            $this->data_buckets['tracking_code_conversion_rates'][$pivot][$pivot_interval][$pivot_value][$session_id][$tracking_code] = []; // We need this as we need to know tracking codes with no events

                            if (!isset($this->data_buckets['tracking_code_conversion_rates'][$pivot][$pivot_interval][$pivot_value][$session_id][$tracking_code][$event])) {
                                $this->data_buckets['tracking_code_conversion_rates'][$pivot][$pivot_interval][$pivot_value][$session_id][$tracking_code][$event] = [0, 0];
                            }

                            $this->data_buckets['tracking_code_conversion_rates'][$pivot][$pivot_interval][$pivot_value][$session_id][$tracking_code][$event][0]++;
                            if (isset($events_for_session[$event])) {
                                $this->data_buckets['tracking_code_conversion_rates'][$pivot][$pivot_interval][$pivot_value][$session_id][$tracking_code][$event][1]++;
                            }
                        }
                    }
                }

                cms_profile_end_for('Hook_admin_stats_events->preprocess_raw_data stats loop ' . strval($start) . ' events ' . $session_id);
            }

            cms_profile_end_for('Hook_admin_stats_events->preprocess_raw_data stats loop ' . strval($start));

            $start += $max;
        } while (!empty($session_rows));

        // Now keep a record of events
        cms_profile_start_for('Hook_admin_stats_events->preprocess_raw_data stats_known_events');
        foreach ($events_seen as $event => $times_seen) {
            $times_seen_before = $GLOBALS['SITE_DB']->query_select_value_if_there('stats_known_events', 'e_count_logged', ['e_event' => $event]);
            if ($times_seen_before === null) {
                $GLOBALS['SITE_DB']->query_insert('stats_known_events', [
                    'e_event' => $event,
                    'e_count_logged' => $times_seen,
                ]);
            } else {
                $GLOBALS['SITE_DB']->query_update('stats_known_events', [
                    'e_count_logged' => $times_seen + $times_seen_before,
                ], [
                    'e_event' => $event,
                ], '', 1);
            }
        }
        cms_profile_end_for('Hook_admin_stats_events->preprocess_raw_data stats_known_events');

        // Now keep a record of tracking codes
        cms_profile_start_for('Hook_admin_stats_events->preprocess_raw_data stats_known_tracking');
        foreach ($tracking_codes_seen as $tracking_code => $times_seen) {
            $times_seen_before = $GLOBALS['SITE_DB']->query_select_value_if_there('stats_known_tracking', 't_count_logged', ['t_tracking_code' => $tracking_code]);
            if ($times_seen_before === null) {
                $GLOBALS['SITE_DB']->query_insert('stats_known_tracking', [
                    't_tracking_code' => $tracking_code,
                    't_count_logged' => $times_seen,
                ]);
            } else {
                $GLOBALS['SITE_DB']->query_update('stats_known_tracking', [
                    't_count_logged' => $times_seen + $times_seen_before,
                ], [
                    't_tracking_code' => $tracking_code,
                ], '', 1);
            }
        }
        cms_profile_end_for('Hook_admin_stats_events->preprocess_raw_data stats_known_tracking');

        cms_profile_end_for('Hook_admin_stats_events->preprocess_raw_data');
    }

    /**
     * Generate final data from preprocessed data.
     *
     * @param  string $bucket Data bucket we want data for
     * @param  string $pivot Pivot value
     * @param  array $filters Map of filters (including pivot if applicable)
     * @return ?array Final data in standardised map format (null: could not generate)
     */
    public function generate_final_data(string $bucket, string $pivot, array $filters) : ?array
    {
        $data = [];
        $range = $this->convert_day_range_filter_to_pair($pivot, $filters[$bucket . '__day_range']);
        $data = $this->fill_data_by_date_pivots_for_graph($pivot, $range[0], $range[1]);

        switch ($bucket) {
            case 'events':
                $start = 0;
                do {
                    $rows = $this->get_preprocessed_data_for_graph($range, $bucket, $pivot, $filters, $start);

                    foreach ($rows as $row) {
                        list($event, $country) = explode('||', $row['p_key']);
                        if ((!empty($filters[$bucket . '__event'])) && ($filters[$bucket . '__event'] != $event)) {
                            continue;
                        }
                        if ((!empty($filters[$bucket . '__country'])) && ($filters[$bucket . '__country'] != $country)) {
                            continue;
                        }

                        $pivot_value_nice = $this->make_date_pivot_value_nice($row['p_pivot'], $row['p_pivot_interval'], $row['p_pivot_value']);
                        if (!isset($data[$pivot_value_nice])) {
                            $data[$pivot_value_nice] = 0;
                        }

                        $data[$pivot_value_nice] += $row['p_value'];
                    }
                } while (count($rows) > 0);

                return [
                    'type' => null,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
                    'y_axis_label' => do_lang_tempcode('COUNT_TOTAL'),
                ];

            case 'tracking_code_usage':
                $start = 0;
                do {
                    $rows = $this->get_preprocessed_data_for_graph($range, $bucket, $pivot, $filters, $start);

                    foreach ($rows as $row) {
                        list($tracking_code, $country) = explode('||', $row['p_key']);
                        if ((!empty($filters[$bucket . '__tracking_code'])) && ($filters[$bucket . '__tracking_code'] != $tracking_code)) {
                            continue;
                        }
                        if ((!empty($filters[$bucket . '__country'])) && ($filters[$bucket . '__country'] != $country)) {
                            continue;
                        }

                        $pivot_value_nice = $this->make_date_pivot_value_nice($row['p_pivot'], $row['p_pivot_interval'], $row['p_pivot_value']);
                        if (!isset($data[$pivot_value_nice])) {
                            $data[$pivot_value_nice] = 0;
                        }

                        $data[$pivot_value_nice] += $row['p_value'];
                    }
                } while (count($rows) > 0);

                return [
                    'type' => null,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
                    'y_axis_label' => do_lang_tempcode('COUNT_TOTAL'),
                ];

            case 'conversion_rates':
                /*
                    NB: For this graph, we need both the number of conversions and sessions. However, each are stored in a separate database row.
                    So, we need to keep track of these in $_data first. Then, after we finish getting everything from the database,
                    we perform the actual calculation into $data.
                */
                $_data = [];
                $start = 0;
                do {
                    $rows = $this->get_preprocessed_data_for_graph($range, $bucket, $pivot, $filters, $start);

                    foreach ($rows as $row) {
                        list($event, $conversion_or_session) = explode('||', $row['p_key']);
                        if ((!empty($filters[$bucket . '__event'])) && ($filters[$bucket . '__event'] != $event)) {
                            continue;
                        }

                        $pivot_value_nice = $this->make_date_pivot_value_nice($row['p_pivot'], $row['p_pivot_interval'], $row['p_pivot_value']);
                        if (!isset($_data[$pivot_value_nice])) {
                            $_data[$pivot_value_nice] = [0, 0];
                        }

                        $_data[$pivot_value_nice][$conversion_or_session] += $row['p_value'];
                    }
                } while (count($rows) > 0);

                foreach ($_data as $pivot_value_nice => $conversions_and_sessions) {
                    list($num_sessions, $num_conversions) = $conversions_and_sessions;

                    if (!isset($data[$pivot_value_nice])) {
                        $data[$pivot_value_nice] = 0;
                    }
                    if ($num_sessions > 0) { // TODO: buggy?
                        $data[$pivot_value_nice] = 100.0 * (floatval($num_conversions) / floatval($num_sessions));
                    }
                }

                return [
                    'type' => null,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
                    'y_axis_label' => do_lang_tempcode('PERCENTAGE'),
                ];

            case 'tracking_code_conversion_rates':
                /*
                    NB: For this graph, we need both the number of conversions and sessions. However, each are stored in a separate database row.
                    So, we need to keep track of these in $_data first. Then, after we finish getting everything from the database,
                    we perform the actual calculation into $data.
                */
                $_data = [];
                $start = 0;
                do {
                    $rows = $this->get_preprocessed_data_for_graph($range, $bucket, $pivot, $filters, $start);

                    foreach ($rows as $row) {
                        list($session, $tracking_code, $event, $conversion_or_session) = explode('||', $row['p_key']);
                        if ((!empty($filters[$bucket . '__tracking_code'])) && ($filters[$bucket . '__tracking_code'] != $tracking_code)) {
                            continue;
                        }
                        if ((!empty($filters[$bucket . '__event'])) && ($filters[$bucket . '__event'] != $event)) {
                            continue;
                        }

                        $pivot_value_nice = $this->make_date_pivot_value_nice($row['p_pivot'], $row['p_pivot_interval'], $row['p_pivot_value']);
                        if (!isset($_data[$pivot_value_nice])) {
                            $_data[$pivot_value_nice] = [0, 0];
                        }

                        $_data[$pivot_value_nice][$conversion_or_session] += $row['p_value'];
                    }
                } while (count($rows) > 0);

                foreach ($_data as $pivot_value_nice => $conversions_and_sessions) {
                    list($num_sessions, $num_conversions) = $conversions_and_sessions;

                    if (!isset($data[$pivot_value_nice])) {
                        $data[$pivot_value_nice] = 0;
                    }
                    if ($num_sessions > 0) { // TODO: buggy?
                        $data[$pivot_value_nice] = 100.0 * (floatval($num_conversions) / floatval($num_sessions));
                    }
                }

                return [
                    'type' => null,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
                    'y_axis_label' => do_lang_tempcode('PERCENTAGE'),
                ];
        }

        fatal_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('7e0f287999a35d65a4b4b743337a2f4b')));
    }
}
