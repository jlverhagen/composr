/**
 * Hook class.
 */
class Hook_admin_stats_comments extends Source_hook_stats_provider
{
    protected $comments_brackets;

    /**
     * Constructor.
     */
    public function __construct()
    {
        $this->comments_brackets = [
            '0',
            '1',
            '2',
            '3-4',
            '5-9',
            '10-29',
            '30+',
        ];
    }

    /**
     * Find metadata about stats graphs that are provided by this stats hook.
     *
     * @param  boolean $for_kpi Whether this is for setting up a KPI
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function info(bool $for_kpi = false) : ?array
    {
        if (get_forum_type() != 'cns') {
            return null;
        }

        if (get_option('is_on_strong_forum_tie') == '0') {
            return null;
        }

        if (get_option('is_on_comments') == '0') {
            return null;
        }

        $forum = get_option('comments_forum_name');
        if (!is_integer($forum)) {
            $forum_id = $GLOBALS['FORUM_DRIVER']->forum_id_from_name($forum);
            if ($forum_id === null) {
                return null;
            }
        }

        return [
            'comments' => [ // Average number
                'label' => do_lang_tempcode('COMMENTS'),
                'category' => 'feedback_and_engagement',
                'filters' => [
                    'comments__day_range' => new Source_stats_filter_day_range('comments__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                    'comments_tallies__content_type' => new Source_stats_filter_list('comments_tallies__content_type', do_lang_tempcode('CONTENT_TYPE'), $this->find_all_feedback_type_codes()),
                ],
                'pivot' => new Source_stats_filter_date_pivot('comments__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'comments_tallies' => [ // Tally by content
                'label' => do_lang_tempcode('COMMENT_ENGAGEMENT'),
                'category' => 'feedback_and_engagement',
                'filters' => [
                    'comments_tallies__day_range' => new Source_stats_filter_day_range('comments_tallies__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                    'comments_tallies__content_type' => new Source_stats_filter_list('comments_tallies__content_type', do_lang_tempcode('CONTENT_TYPE'), $this->find_all_feedback_type_codes()),
                ],
                'pivot' => null,
            ],
        ];
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     */
    public function preprocess_raw_data(int $start_time, int $end_time)
    {
        require_code('temporal');

        $server_timezone = get_server_timezone();

        $feedback_type_codes = $this->find_all_feedback_type_codes();

        $max = 1000;
        $start = 0;

        $date_pivots = $this->get_date_pivots();

        $forum = get_option('comments_forum_name');
        if (!is_integer($forum)) {
            $forum_id = $GLOBALS['FORUM_DRIVER']->forum_id_from_name($forum);
            if ($forum_id === null) {
                return;
            }
        } else {
            $forum_id = intval($forum);
        }

        do {
            $topics = $GLOBALS['FORUM_DB']->query_select('f_topics', ['id', 't_description', 't_cache_first_time', 't_cache_num_posts'], ['t_forum_id' => $forum_id], '', $max, $start);
            foreach ($topics as $topic) {
                $matches = [];
                if (preg_match('#\#(' . implode('|', array_keys($feedback_type_codes)) . ')_(.*)$#', $topic['t_description'], $matches) != 0) {
                    $feedback_type_code = $matches[1];
                    $content_id = $matches[2];

                    $timestamp = $topic['t_cache_first_time'];
                    $timestamp = tz_time($timestamp, $server_timezone);

                    if ($timestamp < $start_time) {
                        continue;
                    }
                    if ($timestamp > $end_time) {
                        continue;
                    }

                    $num_comments = $topic['t_cache_num_posts'] - 1;

                    foreach (array_keys($date_pivots) as $pivot) {
                        $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                        $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                        if (!isset($this->data_buckets['comments'][$pivot][$pivot_interval][$pivot_value][$feedback_type_code])) {
                            $this->data_buckets['comments'][$pivot][$pivot_interval][$pivot_value][$feedback_type_code] = [0, 0];
                        }
                        $this->data_buckets['comments'][$pivot][$pivot_interval][$pivot_value][$feedback_type_code][0] += $num_comments;
                        $this->data_buckets['comments'][$pivot][$pivot_interval][$pivot_value][$feedback_type_code][1]++;

                        $comment_bracket = $this->find_value_bracket($this->comments_brackets, $num_comments);
                        if ($comment_bracket !== null) {
                            if (!isset($this->data_buckets['comments_tallies'][$pivot][$pivot_interval][$pivot_value][$comment_bracket])) {
                                $this->data_buckets['comments_tallies'][$pivot][$pivot_interval][$pivot_value][$comment_bracket] = 0;
                            }
                            $this->data_buckets['comments_tallies'][$pivot][$pivot_interval][$pivot_value][$comment_bracket]++;
                        }
                    }
                }

                $this->dump_data_buckets_if_necessary();
            }

            $start += $max;
        } while (!empty($topics));
    }

    /**
     * Generate final data from preprocessed data.
     *
     * @param  string $bucket Data bucket we want data for
     * @param  string $pivot Pivot value
     * @param  array $filters Map of filters (including pivot if applicable)
     * @return ?array Final data in standardised map format (null: could not generate)
     */
    public function generate_final_data(string $bucket, string $pivot, array $filters) : ?array
    {
        switch ($bucket) {
            case 'comments':
                $_data = [];
                $data = [];

                $range = $this->convert_day_range_filter_to_pair($pivot, $filters[$bucket . '__day_range']);
                $data = $this->fill_data_by_date_pivots_for_graph($pivot, $range[0], $range[1]);

                /*
                    NB: For this graph, we need both the number of posts and topics. However, each are stored in a separate database row.
                    So, we need to keep track of these in $_data first. Then, after we finish getting everything from the database,
                    we perform the actual calculation into $data.
                */
                $start = 0;
                do {
                    $rows = $this->get_preprocessed_data_for_graph($range, $bucket, $pivot, $filters, $start);

                    foreach ($rows as $row) {
                        list($feedback_type_code, $posts_or_topics) = explode('||', $row['p_key']);
                        if ((!empty($filters[$bucket . '__content_type'])) && ($filters[$bucket . '__content_type'] != $feedback_type_code)) {
                            continue;
                        }

                        $pivot_value_nice = $this->make_date_pivot_value_nice($row['p_pivot'], $row['p_pivot_interval'], $row['p_pivot_value']);
                        if (!isset($_data[$pivot_value_nice])) {
                            $_data[$pivot_value_nice] = [0, 0];
                        }

                        $_data[$pivot_value_nice][$posts_or_topics] += $row['p_value'];
                    }
                } while (count($rows) > 0);

                foreach ($_data as $pivot_value_nice => $posts_and_topics) {
                    list($posts, $topics) = $posts_and_topics;

                    if (!isset($data[$pivot_value_nice])) {
                        $data[$pivot_value_nice] = 0;
                    }

                    if ($topics != 0) {
                        $data[$pivot_value_nice] += (floatval($posts) / floatval($topics));
                    }
                }

                if (array_sum($data) == 0) {
                    $data = [];
                }

                return [
                    'type' => null,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
                    'y_axis_label' => do_lang_tempcode('COUNT_NEW'),
                ];

            case 'comments_tallies':
                $data = [];
                $range = $this->convert_day_range_filter_to_pair($pivot, $filters[$bucket . '__day_range']);
                $data = $this->fill_data_by_date_pivots_for_graph($pivot, $range[0], $range[1]);

                var_dump($data);
                exit;

                $start = 0;
                do {
                    $rows = $this->get_preprocessed_data_for_graph($range, $bucket, $pivot, $filters, $start);

                    foreach ($rows as $row) {
                        if (!isset($data[$row['p_key']])) {
                            $data[$row['p_key']] = 0;
                        }
                        $data[$row['p_key']] += $row['p_value'];
                    }
                } while (count($rows) > 0);

                if (array_sum($data) == 0) {
                    $data = [];
                }

                return [
                    'type' => self::GRAPH_BAR_CHART,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('COMMENTS'),
                    'y_axis_label' => do_lang_tempcode('ENTRIES'),
                ];
        }

        fatal_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('94469dd17f8452eea3bb965c3b99bb51')));
    }
}
