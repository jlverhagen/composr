/**
 * Hook class.
 */
class Hook_admin_stats_points extends Source_hook_stats_provider
{
    /**
     * Find metadata about stats graphs that are provided by this stats hook.
     *
     * @param  boolean $for_kpi Whether this is for setting up a KPI
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function info(bool $for_kpi = false) : ?array
    {
        if (!addon_installed('points')) {
            return null;
        }

        require_lang('points');

        return [
            'points_sent' => [
                'label' => do_lang_tempcode('POINTS_SENT'),
                'category' => 'inter_member_engagement',
                'filters' => [
                    'points_sent__day_range' => new Source_stats_filter_day_range('points_sent__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => new Source_stats_filter_date_pivot('points_sent__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'points_transacted' => [
                'label' => do_lang_tempcode('POINTS_AGGREGATE_ROWS'),
                'category' => 'economic_activity',
                'filters' => [
                    'points_sent__day_range' => new Source_stats_filter_day_range('points_transacted__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => new Source_stats_filter_date_pivot('points_transacted__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'points_spent' => [
                'label' => do_lang_tempcode('POINTS_SPENT'),
                'category' => 'economic_activity',
                'filters' => [
                    'points_spent__day_range' => new Source_stats_filter_day_range('points_spent__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => new Source_stats_filter_date_pivot('points_spent__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'points_received' => [
                'label' => do_lang_tempcode('POINTS_RECEIVED'),
                'category' => 'economic_activity',
                'filters' => [
                    'points_received__day_range' => new Source_stats_filter_day_range('points_received__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => new Source_stats_filter_date_pivot('points_received__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'gift_points_used' => [
                'label' => do_lang_tempcode('GIFT_POINTS_USED'),
                'category' => 'economic_activity',
                'filters' => [
                    'gift_points_used__day_range' => new Source_stats_filter_day_range('gift_points_used__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => new Source_stats_filter_date_pivot('gift_points_used__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
        ];
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     * @param  array $data_buckets Map of data buckets; a map of bucket name to nested maps with the following maps in sequence: 'pivot', 'pivot interval', 'pivot value' (then further map data); passed by reference only with pre-filled zero data to later be merged
     */
    public function preprocess_raw_data(int $start_time, int $end_time, array &$data_buckets)
    {
        require_code('temporal');

        $server_timezone = get_server_timezone();

        $date_pivots = $this->get_date_pivots();

        // Ledger processes

        $max = 1000;
        $start = 0;

        $query = 'SELECT * FROM ' . get_table_prefix() . 'points_ledger WHERE ';
        $query .= 'status=0 AND ';
        $query .= 'date_and_time>=' . strval($start_time) . ' AND ';
        $query .= 'date_and_time<=' . strval($end_time);
        $query .= ' ORDER BY date_and_time';
        do {
            $rows = $GLOBALS['SITE_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $timestamp = $row['date_and_time'];
                $timestamp = tz_time($timestamp, $server_timezone);

                foreach (array_keys($date_pivots) as $pivot) {
                    $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                    $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                    // All point transactions
                    if (!isset($data_buckets['points_transacted'][$pivot][$pivot_interval][$pivot_value])) {
                        $data_buckets['points_transacted'][$pivot][$pivot_interval][$pivot_value] = 0;
                    }
                    $data_buckets['points_transacted'][$pivot][$pivot_interval][$pivot_value] += ($row['amount_gift_points'] + $row['amount_points']);

                    // Points sent between members (including via escrow)
                    if ((!is_guest($row['sending_member']) && !is_guest($row['receiving_member'])) || ($row['t_type'] == 'points_escrow')) {
                        if (!isset($data_buckets['points_sent'][$pivot][$pivot_interval][$pivot_value])) {
                            $data_buckets['points_sent'][$pivot][$pivot_interval][$pivot_value] = 0;
                        }
                        $data_buckets['points_sent'][$pivot][$pivot_interval][$pivot_value] += ($row['amount_gift_points'] + $row['amount_points']);
                    }

                    // Points spent (except charged by warnings)
                    if (is_guest($row['receiving_member']) && ($row['t_type'] != 'warning')) {
                        if (!isset($data_buckets['points_spent'][$pivot][$pivot_interval][$pivot_value])) {
                            $data_buckets['points_spent'][$pivot][$pivot_interval][$pivot_value] = 0;
                        }
                        $data_buckets['points_spent'][$pivot][$pivot_interval][$pivot_value] += ($row['amount_gift_points'] + $row['amount_points']);
                    }

                    // Points received
                    if (!is_guest($row['receiving_member'])) {
                        if (!isset($data_buckets['points_received'][$pivot][$pivot_interval][$pivot_value])) {
                            $data_buckets['points_received'][$pivot][$pivot_interval][$pivot_value] = 0;
                        }
                        $data_buckets['points_received'][$pivot][$pivot_interval][$pivot_value] += ($row['amount_gift_points'] + $row['amount_points']);
                    }

                    // Gift points used
                    if (!is_guest($row['sending_member'])) {
                        if (!isset($data_buckets['gift_points_used'][$pivot][$pivot_interval][$pivot_value])) {
                            $data_buckets['gift_points_used'][$pivot][$pivot_interval][$pivot_value] = 0;
                        }
                        $data_buckets['gift_points_used'][$pivot][$pivot_interval][$pivot_value] += $row['amount_gift_points'];
                    }
                }

                $this->dump_delta_if_necessary($data_buckets);
            }

            $start += $max;
        } while (!empty($rows));
    }

    /**
     * Generate final data from preprocessed data.
     *
     * @param  string $bucket Data bucket we want data for
     * @param  string $pivot Pivot value
     * @param  array $filters Map of filters (including pivot if applicable)
     * @return ?array Final data in standardised map format (null: could not generate)
     */
    public function generate_final_data(string $bucket, string $pivot, array $filters) : ?array
    {
        $data = [];
        $_data = $this->prepare_preprocessed_data_for_graph($bucket, $pivot, $filters);

        foreach ($_data as $_pivot => $__data) {
            foreach ($__data as $pivot_interval => $_) {
                foreach ($_ as $pivot_value => $num_transactions) {
                    $pivot_value_nice = $this->make_date_pivot_value_nice($_pivot, $pivot_interval, $pivot_value);
                    if (!isset($data[$pivot_value_nice])) {
                        $data[$pivot_value_nice] = 0;
                    }

                    if ($num_transactions === null) {
                        continue;
                    }

                    $data[$pivot_value_nice] += $num_transactions;
                }
            }
        }

        switch($bucket) {
            case 'gift_points_used':
                $y_label = do_lang_tempcode('GIFT_POINTS');
                break;
            default:
                $y_label = do_lang_tempcode('POINTS');
        }

        return [
            'type' => null,
            'data' => $data,
            'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
            'y_axis_label' => $y_label,
        ];
    }
}
