/**
 * Hook class.
 */
class Hook_admin_stats_security_incidents extends Source_hook_stats_provider
{
    /**
     * Find metadata about stats categories that are defined by this stats hook.
     *
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function category_info() : ?array
    {
        if (!addon_installed('securitylogging')) {
            return null;
        }

        return [
            'security' => [
                'label_lang_string' => 'SECURITY',
                'icon' => 'menu/adminzone/audit/security_log',
            ],
        ];
    }

    /**
     * Find metadata about stats graphs that are provided by this stats hook.
     *
     * @param  boolean $for_kpi Whether this is for setting up a KPI
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function info(bool $for_kpi = false) : ?array
    {
        if (!addon_installed('securitylogging')) {
            return null;
        }

        require_code('locations');
        require_lang('security');

        $ret = [];

        $ret['security_incidents'] = [
            'label' => do_lang_tempcode('SECURITY_LOG'),
            'category' => 'security',
            'filters' => [
                'security_incidents__day_range' => new Source_stats_filter_day_range('security_incidents__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                'security_incidents__include_hackattacks' => new Source_stats_filter_tick('security_incidents__include_hackattacks', do_lang_tempcode('SECURITY_ALERTS')),
                'security_incidents__include_failedlogins' => new Source_stats_filter_tick('security_incidents__include_failedlogins', do_lang_tempcode('FAILED_LOGINS')),
                'security_incidents__country' => new Source_stats_filter_country('security_incidents__country', do_lang_tempcode('COUNTRY')),
            ],
            'pivot' => new Source_stats_filter_date_pivot('security_incidents__pivot', $this->get_date_pivots(!$for_kpi)),
        ];

        return $ret;
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     */
    public function preprocess_raw_data(int $start_time, int $end_time)
    {
        require_code('temporal');
        require_code('locations');

        $max = 1000;
        $start = 0;

        $query = 'SELECT * FROM ' . get_table_prefix() . 'failedlogins WHERE ';
        $query .= 'date_and_time>=' . strval($start_time) . ' AND ';
        $query .= 'date_and_time<=' . strval($end_time);
        $query .= ' ORDER BY date_and_time';
        do {
            $rows = $GLOBALS['SITE_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $timestamp = $row['date_and_time'];

                $country = geolocate_ip($row['ip']);
                if ($country === null) {
                    $country = '';
                }

                $this->save_stat('security_incidents', $timestamp, ['failedlogins', $country]);
            }

            $start += $max;
        } while (!empty($rows));

        $start = 0;

        $query = 'SELECT date_and_time,ip FROM ' . get_table_prefix() . 'hackattack WHERE ';
        $query .= 'date_and_time>=' . strval($start_time) . ' AND ';
        $query .= 'date_and_time<=' . strval($end_time);
        $query .= ' ORDER BY date_and_time';
        do {
            $rows = $GLOBALS['SITE_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $timestamp = $row['date_and_time'];

                $country = geolocate_ip($row['ip']);
                if ($country === null) {
                    $country = '';
                }

                $this->save_stat('security_incidents', $timestamp, ['hackattacks', $country]);
            }

            $start += $max;
        } while (!empty($rows));
    }

    /**
     * Generate final data from preprocessed data.
     *
     * @param  string $bucket Data bucket we want data for
     * @param  string $pivot Pivot value
     * @param  array $filters Map of filters (including pivot if applicable)
     * @return ?array Final data in standardised map format (null: could not generate)
     */
    public function generate_final_data(string $bucket, string $pivot, array $filters) : ?array
    {
        switch ($bucket) {
            case 'security_incidents':
                $data = [];
                $_data = $this->prepare_preprocessed_data_for_graph($bucket, $pivot, $filters);

                foreach ($_data as $_pivot => $__data) {
                    foreach ($__data as $pivot_interval => $_) {
                        foreach ($_ as $pivot_value => $__) {
                            $pivot_value_nice = $this->make_date_pivot_value_nice($_pivot, $pivot_interval, $pivot_value);
                            if (!isset($data[$pivot_value_nice])) {
                                $data[$pivot_value_nice] = 0;
                            }

                            if ($__ === null) {
                                continue;
                            }

                            foreach ($__ as $record_type => $num_incidents) {
                                if ((empty($filters[$bucket . '__include_failedlogins'])) && ($record_type == 'failedlogins')) {
                                    continue;
                                }

                                if ((empty($filters[$bucket . '__include_hackattacks'])) && ($record_type == 'hackattacks')) {
                                    continue;
                                }

                                $data[$pivot_value_nice] += $num_incidents;
                            }
                        }
                    }
                }

                return [
                    'type' => null,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
                    'y_axis_label' => do_lang_tempcode('COUNT_NEW'),
                ];

            case 'security_incidents_countries':
                require_code('locations');

                $data = [];
                $_data = $this->prepare_preprocessed_data_for_graph($bucket, $pivot, $filters);

                foreach ($_data as $_pivot => $__data) {
                    foreach ($__data as $pivot_interval => $_) {
                        foreach ($_ as $pivot_value => $__) {
                            if ($__ === null) {
                                continue;
                            }

                            foreach ($__ as $record_type => $___) {
                                foreach ($___ as $country => $total_incidents) {
                                    if ((empty($filters[$bucket . '__include_failedlogins'])) && ($record_type == 'failedlogins')) {
                                        continue;
                                    }

                                    if ((empty($filters[$bucket . '__include_hackattacks'])) && ($record_type == 'hackattacks')) {
                                        continue;
                                    }

                                    $_country = find_country_name_from_iso($country);
                                    if ($_country === null) {
                                        $_country = do_lang('OTHER');
                                    }

                                    if (!isset($data[$_country])) {
                                        $data[$_country] = 0;
                                    }
                                    $data[$_country] += $total_incidents;
                                }
                            }
                        }
                    }
                }

                return [
                    'type' => self::GRAPH_BAR_CHART,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('COUNTRY'),
                    'y_axis_label' => do_lang_tempcode('COUNT_TOTAL'),
                    'limit_bars' => true,
                ];
        }

        fatal_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('935fdd2a812e55df94196faad20c5371')));
    }
}
