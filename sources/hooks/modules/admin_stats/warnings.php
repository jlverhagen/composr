/**
 * Hook class.
 */
class Hook_admin_stats_warnings extends Source_hook_stats_provider
{

    /**
     * Find metadata about stats categories that are defined by this stats hook.
     *
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function category_info() : ?array
    {
        if (!addon_installed('cns_warnings')) {
            return null;
        }

        require_lang('cns_warnings');

        return [
            'moderation' => [
                'label_lang_string' => 'PUNITIVE_ACTIONS',
                'icon' => 'menu/social/warnings',
            ],
        ];
    }

    /**
     * Find metadata about stats graphs that are provided by this stats hook.
     *
     * @param  boolean $for_kpi Whether this is for setting up a KPI
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function info(bool $for_kpi = false) : ?array
    {
        if (!addon_installed('cns_warnings')) {
            return null;
        }

        require_lang('cns');
        require_lang('cns_warnings');
        require_code('locations');

        $ret = [
            'recorded_punishments' => [
                'label' => do_lang_tempcode('WARNINGS'),
                'category' => 'moderation',
                'filters' => [
                    'recorded_punishments__day_range' => new Source_stats_filter_day_range('recorded_punishments__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                    'recorded_punishments__country' => has_geolocation_data() ? new Source_stats_filter_country('recorded_punishments__country', do_lang_tempcode('VISITOR_COUNTRY')) : null,
                    'recorded_punishments__reason' => new Source_stats_filter_text('recorded_punishments__reason', do_lang_tempcode('REASON'), ''),
                ],
                'pivot' => new Source_stats_filter_date_pivot('recorded_punishments__pivot', $this->get_date_pivots(!$for_kpi)),
            ],
            'recorded_punishment_reasons' => [
                'label' => do_lang_tempcode('WARNINGS_BY_REASON'),
                'category' => 'moderation',
                'filters' => [
                    'recorded_punishment_reasons__country' => has_geolocation_data() ? new Source_stats_filter_country('recorded_punishment_reasons__country', do_lang_tempcode('VISITOR_COUNTRY')) : null,
                ],
                'pivot' => null,
            ],
        ];
        if (has_geolocation_data()) {
            $ret['recorded_punishment_countries'] = [
                'label' => do_lang_tempcode('_COUNTRIES', do_lang_tempcode('WARNINGS')),
                'category' => 'moderation',
                'filters' => [
                    'recorded_punishment_countries__reason' => new Source_stats_filter_text('recorded_punishment_countries__reason', do_lang_tempcode('REASON'), ''),
                ],
                'pivot' => null,
            ];
        }

        return $ret;
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     */
    public function preprocess_raw_data(int $start_time, int $end_time)
    {
        require_code('temporal');
        require_code('locations');

        $max = 1000;
        $start = 0;

        $query = 'SELECT w_time,w_explanation,m_ip_address FROM ' . $GLOBALS['FORUM_DB']->get_table_prefix() . 'f_warnings w JOIN ' . $GLOBALS['FORUM_DB']->get_table_prefix() . 'f_members m ON m.id=w.w_member_id WHERE ';
        $query .= 'w_time>=' . strval($start_time) . ' AND ';
        $query .= 'w_time<=' . strval($end_time);
        $query .= ' ORDER BY w_time';
        do {
            $rows = $GLOBALS['FORUM_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $timestamp = $row['w_time'];

                $country = geolocate_ip($row['m_ip_address']);
                if ($country === null) {
                    $country = '';
                }

                $explanation = $row['w_explanation'];

                $this->save_stat('recorded_punishments', $timestamp, [$country, $explanation]);
            }

            $start += $max;
        } while (!empty($rows));
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     * This is for flat and timeless data.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     */
    public function preprocess_raw_data_flat(int $start_time, int $end_time)
    {
        $max = 1000;
        $start = 0;

        $query = 'SELECT w_time,w_explanation,m_ip_address FROM ' . $GLOBALS['FORUM_DB']->get_table_prefix() . 'f_warnings w JOIN ' . $GLOBALS['FORUM_DB']->get_table_prefix() . 'f_members m ON m.id=w.w_member_id WHERE ';
        $query .= 'w_time>=' . strval($start_time) . ' AND ';
        $query .= 'w_time<=' . strval($end_time);
        $query .= ' ORDER BY w_time';
        do {
            $rows = $GLOBALS['FORUM_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $reason = $row['w_explanation'];
                $country = geolocate_ip($row['m_ip_address']);
                if ($country === null) {
                    $country = '';
                }

                if (has_geolocation_data()) {
                    $this->save_stat('recorded_punishment_countries', null, [$reason, $country]);
                }
                $this->save_stat('recorded_punishment_reasons', null, [$country, $reason]);
            }

            $start += $max;
        } while (!empty($rows));
    }

    /**
     * Generate final data from preprocessed data.
     *
     * @param  string $bucket Data bucket we want data for
     * @param  string $pivot Pivot value
     * @param  array $filters Map of filters (including pivot if applicable)
     * @return ?array Final data in standardised map format (null: could not generate)
     */
    public function generate_final_data(string $bucket, string $pivot, array $filters) : ?array
    {
        switch ($bucket) {
            case 'recorded_punishments':
                $data = [];
                $range = $this->convert_day_range_filter_to_pair($pivot, $filters[$bucket . '__day_range']);
                $data = $this->fill_data_by_date_pivots_for_graph($pivot, $range[0], $range[1]);

                $start = 0;
                do {
                    $rows = $this->get_preprocessed_data_for_graph($range, $bucket, $pivot, $filters, $start);

                    foreach ($rows as $row) {
                        list($country, $explanation) = explode('||', $row['p_key']);
                        if ((!empty($filters[$bucket . '__country'])) && ($filters[$bucket . '__country'] != $country)) {
                            continue;
                        }
                        if ((!empty($filters[$bucket . '__reason'])) && ($filters[$bucket . '__reason'] != $explanation)) {
                            continue;
                        }

                        $pivot_interval = $this->calculate_date_pivot_interval($pivot, $row['p_date_and_time']);
                        $pivot_value = $this->calculate_date_pivot_value($pivot, $row['p_date_and_time']);
                        $pivot_value_nice = $this->make_date_pivot_value_nice($pivot, $pivot_interval, $pivot_value);

                        if (!isset($data[$pivot_value_nice])) {
                            $data[$pivot_value_nice] = 0.0;
                        }
                        $data[$pivot_value_nice] += $row['p_value'];
                    }
                } while (count($rows) > 0);

                return [
                    'type' => null,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
                    'y_axis_label' => do_lang_tempcode('COUNT_NEW'),
                ];

            case 'recorded_punishment_reasons':
                $data = [];

                $start = 0;
                do {
                    $rows = $this->get_preprocessed_data_for_graph(null, $bucket, null, $filters, $start);

                    foreach ($rows as $row) {
                        list($country, $explanation) = explode('||', $row['p_key']);
                        if ((!empty($filters[$bucket . '__country'])) && ($filters[$bucket . '__country'] != $country)) {
                            continue;
                        }

                        if (!isset($data[$explanation])) {
                            $data[$explanation] = 0.0;
                        }
                        $data[$explanation] += $row['p_value'];
                    }
                } while (count($rows) > 0);

                return [
                    'type' => self::GRAPH_PIE_CHART,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('REASON'),
                    'y_axis_label' => do_lang_tempcode('COUNT_TOTAL'),
                ];

            case 'recorded_punishment_countries':
                $data = [];
                $start = 0;
                do {
                    $rows = $this->get_preprocessed_data_for_graph(null, $bucket, null, $filters, $start);

                    foreach ($rows as $row) {
                        list($explanation, $country) = explode('||', $row['p_key']);
                        if ((!empty($filters[$bucket . '__reason'])) && ($filters[$bucket . '__reason'] != $explanation)) {
                            continue;
                        }

                        if (!isset($data[$country])) {
                            $data[$country] = 0.0;
                        }
                        $data[$country] += $row['p_value'];
                    }
                } while (count($rows) > 0);

                return [
                    'type' => self::GRAPH_PIE_CHART,
                    'data' => $data,
                    'x_axis_label' => do_lang_tempcode('COUNTRY'),
                    'y_axis_label' => do_lang_tempcode('COUNT_TOTAL'),
                    'limit_bars' => true,
                ];
        }

        fatal_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('73576d1294dd5e51bbdc119f44fa72fa')));
    }
}
