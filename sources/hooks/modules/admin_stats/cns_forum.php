/**
 * Hook class.
 */
class Hook_admin_stats_cns_forum extends Source_hook_stats_provider
{
    /**
     * Find metadata about stats categories that are defined by this stats hook.
     *
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function category_info() : ?array
    {
        if (!addon_installed('cns_forum')) {
            return null;
        }

        return [
            'forum' => [
                'label_lang_string' => 'FORUM',
                'icon' => 'menu/social/forum/forums',
            ],
        ];
    }

    /**
     * Find metadata about stats graphs that are provided by this stats hook.
     *
     * @param  boolean $for_kpi Whether this is for setting up a KPI
     * @return ?array Map of metadata (null: hook is disabled)
     */
    public function info(bool $for_kpi = false) : ?array
    {
        if (!addon_installed('cns_forum')) {
            return null;
        }
        if (get_forum_type() != 'cns') {
            return null;
        }

        require_lang('cns');

        return [
            'public_topics' => [
                'label' => do_lang_tempcode('FORUM_TOPICS'),
                'category' => 'forum',
                'filters' => [
                    'public_topics__day_range' => new Source_stats_filter_day_range('public_topics__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => new Source_stats_filter_date_pivot('public_topics__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'public_posts' => [
                'label' => do_lang_tempcode('FORUM_POSTS'),
                'category' => 'forum',
                'filters' => [
                    'public_posts__day_range' => new Source_stats_filter_day_range('public_posts__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => new Source_stats_filter_date_pivot('public_posts__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'topic_poll_votes' => [
                'label' => do_lang_tempcode('TOPIC_POLL_VOTES'),
                'category' => 'forum',
                'filters' => [
                    'topic_poll_votes__day_range' => new Source_stats_filter_day_range('topic_poll_votes__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => new Source_stats_filter_date_pivot('topic_poll_votes__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'private_topics' => [
                'label' => do_lang_tempcode('PRIVATE_TOPICS'),
                'category' => 'inter_member_engagement',
                'filters' => [
                    'private_topics__day_range' => new Source_stats_filter_day_range('private_topics__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => new Source_stats_filter_date_pivot('private_topics__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
            'private_posts' => [
                'label' => do_lang_tempcode('PRIVATE_POSTS'),
                'category' => 'inter_member_engagement',
                'filters' => [
                    'private_posts__day_range' => new Source_stats_filter_day_range('private_posts__day_range', do_lang_tempcode('DATE_RANGE'), null, $for_kpi),
                ],
                'pivot' => new Source_stats_filter_date_pivot('private_posts__pivot', $this->get_date_pivots(!$for_kpi)),
                'support_kpis' => self::KPI_HIGH_IS_GOOD,
            ],
        ];
    }

    /**
     * Preprocess raw data in the database into something we can efficiently draw graphs/conclusions from.
     *
     * @param  TIME $start_time Start timestamp
     * @param  TIME $end_time End timestamp
     */
    public function preprocess_raw_data(int $start_time, int $end_time)
    {
        require_code('temporal');

        $server_timezone = get_server_timezone();

        $max = 1000;
        $start = 0;

        $date_pivots = $this->get_date_pivots();

        $query = 'SELECT t_forum_id,t_cache_first_time FROM ' . $GLOBALS['FORUM_DB']->get_table_prefix() . 'f_topics WHERE ';
        $query .= 't_cache_first_time>=' . strval($start_time) . ' AND ';
        $query .= 't_cache_first_time<=' . strval($end_time);
        $query .= ' ORDER BY t_cache_first_time';
        do {
            $rows = $GLOBALS['FORUM_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $timestamp = $row['t_cache_first_time'];
                if ($timestamp === null) {
                    continue;
                }
                $timestamp = tz_time($timestamp, $server_timezone);

                foreach (array_keys($date_pivots) as $pivot) {
                    $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                    $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                    if ($row['t_forum_id'] === null) {
                        if (!isset($this->data_buckets['private_topics'][$pivot][$pivot_interval][$pivot_value])) {
                            $this->data_buckets['private_topics'][$pivot][$pivot_interval][$pivot_value] = 0;
                        }
                        $this->data_buckets['private_topics'][$pivot][$pivot_interval][$pivot_value]++;
                    } else {
                        if (!isset($this->data_buckets['public_topics'][$pivot][$pivot_interval][$pivot_value])) {
                            $this->data_buckets['public_topics'][$pivot][$pivot_interval][$pivot_value] = 0;
                        }
                        $this->data_buckets['public_topics'][$pivot][$pivot_interval][$pivot_value]++;
                    }
                }

                $this->dump_data_buckets_if_necessary();
            }

            $start += $max;
        } while (!empty($rows));

        $start = 0;

        $query = 'SELECT p_cache_forum_id,p_whisper_to_member,p_time FROM ' . $GLOBALS['FORUM_DB']->get_table_prefix() . 'f_posts WHERE ';
        $query .= 'p_time>=' . strval($start_time) . ' AND ';
        $query .= 'p_time<=' . strval($end_time);
        $query .= ' ORDER BY p_time';
        do {
            $rows = $GLOBALS['FORUM_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $timestamp = $row['p_time'];
                $timestamp = tz_time($timestamp, $server_timezone);

                foreach (array_keys($date_pivots) as $pivot) {
                    $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                    $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                    if (($row['p_cache_forum_id'] === null) || ($row['p_whisper_to_member'] !== null)) {
                        if (!isset($this->data_buckets['private_posts'][$pivot][$pivot_interval][$pivot_value])) {
                            $this->data_buckets['private_posts'][$pivot][$pivot_interval][$pivot_value] = 0;
                        }
                        $this->data_buckets['private_posts'][$pivot][$pivot_interval][$pivot_value]++;
                    } else {
                        if (!isset($this->data_buckets['public_posts'][$pivot][$pivot_interval][$pivot_value])) {
                            $this->data_buckets['public_posts'][$pivot][$pivot_interval][$pivot_value] = 0;
                        }
                        $this->data_buckets['public_posts'][$pivot][$pivot_interval][$pivot_value]++;
                    }
                }

                $this->dump_data_buckets_if_necessary();
            }

            $start += $max;
        } while (!empty($rows));

        $start = 0;

        $query = 'SELECT pv_date_time,pv_revoked FROM ' . $GLOBALS['FORUM_DB']->get_table_prefix() . 'f_poll_votes WHERE ';
        $query .= 'pv_revoked=0 AND ';
        $query .= 'pv_date_time>=' . strval($start_time) . ' AND ';
        $query .= 'pv_date_time<=' . strval($end_time);
        $query .= ' ORDER BY pv_date_time';
        do {
            $rows = $GLOBALS['FORUM_DB']->query($query, $max, $start);
            foreach ($rows as $row) {
                $timestamp = $row['pv_date_time'];
                $timestamp = tz_time($timestamp, $server_timezone);

                foreach (array_keys($date_pivots) as $pivot) {
                    $pivot_interval = $this->calculate_date_pivot_interval($pivot, $timestamp);
                    $pivot_value = $this->calculate_date_pivot_value($pivot, $timestamp);

                    if (!isset($this->data_buckets['topic_poll_votes'][$pivot][$pivot_interval][$pivot_value])) {
                        $this->data_buckets['topic_poll_votes'][$pivot][$pivot_interval][$pivot_value] = 0;
                    }
                    $this->data_buckets['topic_poll_votes'][$pivot][$pivot_interval][$pivot_value]++;
                }

                $this->dump_data_buckets_if_necessary();
            }

            $start += $max;
        } while (!empty($rows));
    }

    /**
     * Generate final data from preprocessed data.
     *
     * @param  string $bucket Data bucket we want data for
     * @param  string $pivot Pivot value
     * @param  array $filters Map of filters (including pivot if applicable)
     * @return ?array Final data in standardised map format (null: could not generate)
     */
    public function generate_final_data(string $bucket, string $pivot, array $filters) : ?array
    {
        $data = [];
        $range = $this->convert_day_range_filter_to_pair($pivot, $filters[$bucket . '__day_range']);
        $data = $this->fill_data_by_date_pivots_for_graph($pivot, $range[0], $range[1]);

        $start = 0;
        do {
            $rows = $this->get_preprocessed_data_for_graph($range, $bucket, $pivot, $filters, $start);

            foreach ($rows as $row) {
                $pivot_value_nice = $this->make_date_pivot_value_nice($row['p_pivot'], $row['p_pivot_interval'], $row['p_pivot_value']);
                if (!isset($data[$pivot_value_nice])) {
                    $data[$pivot_value_nice] = 0;
                }

                $data[$pivot_value_nice] += $row['p_value'];
            }
        } while (count($rows) > 0);

        return [
            'type' => null,
            'data' => $data,
            'x_axis_label' => do_lang_tempcode('TIME_IN_TIMEZONE', escape_html(make_nice_timezone_name(get_site_timezone()))),
            'y_axis_label' => do_lang_tempcode('COUNT_NEW'),
        ];
    }
}
