/**
 * Cleanup old stats.
 */
function cleanup_stats()
{
    if (!$GLOBALS['SITE_DB']->table_is_locked('stats')) {
        $cutoff = strval(time() - 60 * 60 * 24 * intval(get_option('stats_store_time')));

        $where = 'date_and_time<' . $cutoff;
        $GLOBALS['SITE_DB']->query('DELETE FROM ' . get_table_prefix() . 'stats WHERE ' . $where, 500/*to reduce lock times*/, 0, true); // Errors suppressed in case DB write access broken

        $where = 'e_date_and_time<' . $cutoff;
        $GLOBALS['SITE_DB']->query('DELETE FROM ' . get_table_prefix() . 'stats_events WHERE ' . $where, 500/*to reduce lock times*/, 0, true); // Errors suppressed in case DB write access broken

        $where = 'c_date_and_time<' . $cutoff;
        $GLOBALS['SITE_DB']->query('DELETE FROM ' . get_table_prefix() . 'stats_link_tracker WHERE ' . $where, 500/*to reduce lock times*/, 0, true); // Errors suppressed in case DB write access broken
    }
}

/**
 * Pre-process raw data for a stats hook.
 *
 * @param  string $hook_name The hook name to preprocess data in
 * @param  TIME $start_time Start time
 * @param  ?TIME $end_time End time (null: now)
 */
function preprocess_raw_data_for(string $hook_name, int $start_time = 0, ?int $end_time = null)
{
    require_code('temporal');

    if ($end_time === null) {
        // Prevent an edge case where something could be logged before the current second is over and never get counted
        $end_time = time() - 1;
    }

    $hook_ob = get_hook_ob('modules', 'admin_stats', filter_naughty_harsh($hook_name, true), 'Hook_admin_stats_', true);
    if ($hook_ob === null) {
        return;
    }

    $info = $hook_ob->info();
    if ($info === null) {
        return;
    }

    if (!$hook_ob instanceof Source_hook_stats_provider) {
        return;
    }

    push_query_limiting(false);
    raise_php_memory_limit();

    cms_profile_start_for('preprocess_raw_data_for::' . $hook_name);

    cms_profile_start_for('preprocess_raw_data_for::' . $hook_name . '->preprocess_raw_data');

    // Build delta structure
    $hook_ob->data_buckets = [];
    foreach (array_keys($info) as $bucket) {
        $hook_ob->data_buckets[$bucket] = [];
    }

    // Preprocess new data...

    $extend_time = intval((($end_time - $start_time) / (60 * 60)) + 1.0); // We grant 1 second for every hour to be processed

    $old = cms_extend_time_limit($extend_time);

    $hook_ob->preprocess_raw_data($start_time, $end_time);

    // Dump final delta data...

    $hook_ob->dump_data_buckets_if_necessary(true, false);

    cms_set_time_limit($old);

    cms_profile_end_for('preprocess_raw_data_for::' . $hook_name . '->preprocess_raw_data');

    // Now for flat data...

    cms_profile_start_for('preprocess_raw_data_for::' . $hook_name . '->preprocess_raw_data_flat');

    $old = cms_extend_time_limit(TIME_LIMIT_EXTEND__MODEST);

    // First we need to load up any data we already processed for any days within the time range, so anything new will MERGE into that...

    $hook_ob->data_buckets = [];
    foreach (array_keys($info) as $bucket) {
        $p_data = $GLOBALS['SITE_DB']->query_select_value_if_there('stats_preprocessed_flat', 'p_data', [
            'p_bucket' => $bucket,
        ]);
        if ($p_data !== null) {
            $hook_ob->data_buckets[$bucket] = @unserialize($p_data);
            if ($hook_ob->data_buckets[$bucket] === false) {
                $hook_ob->data_buckets[$bucket] = [];
            }
        }
    }

    // Preprocess new data...

    $hook_ob->preprocess_raw_data_flat($start_time, $end_time);

    // Re-save into the database...

    foreach ($hook_ob->data_buckets as $bucket => $data) {
        $GLOBALS['SITE_DB']->query_insert_or_replace('stats_preprocessed_flat', [
            'p_data' => serialize($data),
        ], [
            'p_bucket' => $bucket,
        ]);
    }

    $hook_ob->data_buckets = [];

    cms_set_time_limit($old);

    cms_profile_end_for('preprocess_raw_data_for::' . $hook_name . '->preprocess_raw_data_flat');

    pop_query_limiting();

    cms_profile_end_for('preprocess_raw_data_for::' . $hook_name);
}

/**
 * Process (merge) pending deltas into the official statistics.
 *
 * @param  integer $time_limit Only keep processing deltas for this many seconds; will still terminate if memory use starts getting high
 */
function stats_merge_deltas(int $time_limit = 15)
{
    $start = time();

    cms_profile_start_for('Hook_cron_stats_preprocess_raw_data deltas');

    $old = cms_extend_time_limit($time_limit + 1);

    push_query_limiting(false);

    require_code('files');
    $ml = php_return_bytes(ini_get('memory_limit'));
    $current_memory = memory_get_usage(false);
    $near_limit = (($ml > 0) && ($current_memory >= ($ml - (1024 * 1024 * 8)))); // within 8 MB of PHP memory limit

    while ((!$near_limit) && ((time() - $start) < $time_limit)) { // Time and memory checks
        // Not ideal to process one at a time, but some rows can be several MBs, so we need to avoid out of memory issues
        $row = $GLOBALS['SITE_DB']->query_select('stats_preprocessed_delta', ['*'], [], ' ORDER BY id', 1);
        if (!array_key_exists(0, $row)) { // No more to do
            break;
        }

        $stats_row = $GLOBALS['SITE_DB']->query_select('stats_preprocessed', ['*'], [
            'p_bucket' => $row[0]['p_bucket'],
            'p_pivot' => $row[0]['p_pivot'],
            'p_pivot_interval' => $row[0]['p_pivot_interval'],
            'p_pivot_value' => $row[0]['p_pivot_value'],
        ], '', 1);

        if (!array_key_exists(0, $stats_row)) {
            $GLOBALS['SITE_DB']->query_insert('stats_preprocessed', [
                'p_bucket' => $row[0]['p_bucket'],
                'p_pivot' => $row[0]['p_pivot'],
                'p_pivot_interval' => $row[0]['p_pivot_interval'],
                'p_pivot_value' => $row[0]['p_pivot_value'],
                'p_data' => $row[0]['p_data'],
            ]);
        } else {
            $row_u = @unserialize($row[0]['p_data']);
            if ($row_u === false) {
                warn_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('67b35ad8e6935ab8b8f76f5734789f72')), escape_html('TODO'));
            }

            $stats_row_u = @unserialize($stats_row[0]['p_data']);
            if ($stats_row_u === false) {
                warn_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('df243edab1d45299b9d8b79f6de6d357')), escape_html('TODO'));
            }

            stats_deep_merge($stats_row_u, $row_u);

            $GLOBALS['SITE_DB']->query_update('stats_preprocessed', ['p_data' => serialize($stats_row_u)], [
                'p_bucket' => $row[0]['p_bucket'],
                'p_pivot' => $row[0]['p_pivot'],
                'p_pivot_interval' => $row[0]['p_pivot_interval'],
                'p_pivot_value' => $row[0]['p_pivot_value'],
            ]);
        }

        $GLOBALS['SITE_DB']->query_delete('stats_preprocessed_delta', ['id' => $row[0]['id']]);

        unset($row);
        unset($row_u);
        unset($stats_row);
        unset($stats_row_u);
        unset($merged_data);

        $current_memory = memory_get_usage(false);
        $near_limit = (($ml > 0) && ($current_memory >= ($ml - (1024 * 1024 * 8)))); // within 8 MB of PHP memory limit
    }

    cms_set_time_limit($old);

    pop_query_limiting();

    cms_profile_end_for('Hook_cron_stats_preprocess_raw_data preprocess_raw_data_for');
}

/**
 * Deep-merge two statistics arrays.
 *
 * @param  mixed $base The base statistics, passed and modified by reference
 * @param  mixed $delta The statistics we are merging into $base
 */
function stats_deep_merge(&$base, $delta)
{
    // Sanity check: $base and $delta must both be arrays or both not be arrays
    if (is_array($base) && !is_array($delta)) {
        warn_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('13e4e28074765b2480c21e0e1a75fa27')), escape_html('TODO'));
    }
    if (!is_array($base) && is_array($delta)) {
        warn_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('3a468e9dfb835362a1dc7673c3234f1f')), escape_html('TODO'));
    }

    if (!is_array($delta)) {
        if (is_numeric($delta)) { // Numbers get added together (counters)
            $base = $base + $delta;
        } else { // All other types overwrite previous values
            $base = $delta;
        }
        return;
    }

    foreach ($delta as $k => $v) {
        // Does not exist on base? Create it!
        if (!array_key_exists($k, $base)) {
            $base[$k] = $v;
            continue;
        }

        if (is_array($v)) { // Arrays get merged
            stats_deep_merge($base[$k], $v);
        } elseif (is_numeric($v)) { // Numbers get added together (counters)
            $base[$k] = $base[$k] + $v;
        } else { // All other types overwrite previous values
            $base[$k] = $v;
        }
    }
}

/**
 * Send out KPI notifications, as appropriate based on today's date.
 */
function send_kpi_notifications()
{
    cms_profile_start_for('send_kpi_notifications');

    $series = [ // Runs day after a period ends
        'year_series' => (date('m-d') == '01-01'),
        'quarter_series' => (date('d') == '01') && (in_array(date('m'), ['01', '04', '07', '10'])),
        'month_series' => (date('d') == '01'),
        'day_series' => true,
        '' => true, // No pivot; treated as day_series
    ];

    $kpis = [];
    foreach ($series as $pivot => $send_today) {
        if ($send_today) {
            $_kpis = gather_kpis($pivot);
            $kpis = array_merge($kpis, $_kpis);
        }
    }

    if (!empty($kpis)) {
        $kpis_for_tpl = [];
        foreach ($kpis as $kpi) {
            list($kpi_row, , , , , , $edit_url, , $target, $current, $hits_target) = $kpi;
            $graph_name = $kpi_row['k_graph_name'];
            $edit_url = build_url(['page' => 'admin_stats', 'type' => '_edit', 'id' => $kpi_row['id']], get_module_zone('admin_stats'), [], false, false, true);
            $view_url = build_url(['page' => 'admin_stats', 'type' => 'kpis'], get_module_zone('admin_stats'), [], false, false, true, 'graph_' . $graph_name);
            $username = $GLOBALS['FORUM_DRIVER']->get_username($kpi_row['k_submitter'], true);
            $kpis_for_tpl[] = [
                'TITLE' => $kpi_row['k_title'],
                'CURRENT' => ($current === null) ? null : (is_integer($current) ? integer_format($current, 0) : float_format($current, 4, true)),
                'HITS_TARGET' => $hits_target,
                'TARGET' => ($target === null) ? null : float_format($target, 4, true),
                'EDIT_URL' => $edit_url,
                'VIEW_URL' => $view_url,
                'GRAPH_NAME' => $kpi_row['k_graph_name'],
                'USERNAME' => $username,
                'ADDED' => get_timezoned_date($kpi_row['k_added_time']),
                'NOTES' => $kpi_row['k_notes'],
            ];
        }

        require_code('notifications');
        $mail = do_notification_template('KPI_UPDATE_MAIL', [
            'KPIS' => $kpis_for_tpl,
        ], null, false, null, '.txt', 'text');

        Source_notification_dispatcher::dispatch_notification('kpis', '', do_lang('NOTIFICATION_TYPE_kpis'), $mail->evaluate(get_site_default_lang()));
    }

    cms_profile_end_for('send_kpi_notifications');
}
