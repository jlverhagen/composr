/**
 * Perform a software-level rewrite of the current URL when Nginx is the server.
 * The rules in this function must match recommended.htaccess.
 */
function nginx_rewrite()
{
    // Only run if server software looks like nginx
    $server_software = isset($_SERVER['SERVER_SOFTWARE']) ? $_SERVER['SERVER_SOFTWARE'] : '';
    if (stripos($server_software, 'nginx') === false) {
        return;
    }

    $uri = preg_replace('#\?.*#', '', isset($_SERVER['REQUEST_URI']) ? $_SERVER['REQUEST_URI'] : '');
    if (substr($uri, 0, 1) == '/') {
        $uri = substr($uri, 1);
    }
    $matches = [];

    // Get regex for all zones
    require_code('zones');
    $zones = find_all_zones();
    unset($zones['site']); // We force this in because find_all_zones will not return it if single public zone is enabled
    unset($zones['']); // We also force the welcome zone
    $zone_regex = '(|site|' . implode('|', $zones) . ')';

    // WebDAV
    if (preg_match('#^/?webdav(/.*|$)#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, 'data_custom/webdav.php');
        return;
    }

    // Rewrite module index.php
    if (preg_match('#^([^=]*)pages/(modules|modules_custom)/([^/]*)\.php$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=$3');
        return;
    }

    // PG Style

    if (preg_match('#^([^=]*)pg/s/([^\&\?]*)/index\.php$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=wiki&id=$2');
        return;
    }
    if (preg_match('#^([^=]*)pg/([^/\&\?]*)/([^/\&\?]*)/([^\&\?]*)/index\.php(.*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=$2&type=$3&id=$4$5');
        return;
    }
    if (preg_match('#^([^=]*)pg/([^/\&\?]*)/([^/\&\?]*)/index\.php(.*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=$2&type=$3$4');
        return;
    }
    if (preg_match('#^([^=]*)pg/([^/\&\?]*)/index\.php(.*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=$2$3');
        return;
    }
    if (preg_match('#^([^=]*)pg/index\.php(.*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=$3');
        return;
    }
    if (preg_match('#^([^=]*)pg/s/([^\&\?]*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=wiki&id=$2');
        return;
    }
    if (preg_match('#^([^=]*)pg/([^/\&\?]*)/([^/\&\?]*)/([^\&\?]*)/$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=$2&type=$3&id=$4');
        return;
    }
    if (preg_match('#^([^=]*)pg/([^/\&\?]*)/([^/\&\?]*)/([^\&\?]*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=$2&type=$3&id=$4');
        return;
    }
    if (preg_match('#^([^=]*)pg/([^/\&\?]*)/([^/\&\?]*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=$2&type=$3');
        return;
    }
    if (preg_match('#^([^=]*)pg/([^/\&\?]*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?page=$2');
        return;
    }
    if (preg_match('#^([^=]*)pg/s/([^\&\?\.]*)&(.*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?$3&page=wiki&id=$2');
        return;
    }
    if (preg_match('#^([^=]*)pg/([^/\&\?\.]*)/([^/\&\?\.]*)/([^/\&\?\.]*)&(.*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?$5&page=$2&type=$3&id=$4');
        return;
    }
    if (preg_match('#^([^=]*)pg/([^/\&\?\.]*)/([^/\&\?\.]*)&(.*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?$4&page=$2&type=$3');
        return;
    }
    if (preg_match('#^([^=]*)pg/([^/\&\?\.]*)&(.*)$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1index.php\?$3&page=$2');
        return;
    }

    // HTM Style
    
    if (preg_match('#^' . $zone_regex . '/s/([^\&\?]*)\.htm$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1/index.php\?page=wiki&id=$2');
        return;
    }
    if (preg_match('#^s/([^\&\?]*)\.htm$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, 'index\.php\?page=wiki&id=$1');
        return;
    }
    if (preg_match('#^' . $zone_regex . '/([^/\&\?]+)/([^/\&\?]*)/([^\&\?]*)\.htm$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1/index.php\?page=$2&type=$3&id=$4');
        return;
    }
    if (preg_match('#^' . $zone_regex . '/([^/\&\?]+)/([^/\&\?]*)\.htm$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1/index.php\?page=$2&type=$3');
        return;
    }
    if (preg_match('#^' . $zone_regex . '/([^/\&\?]+)\.htm$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, '$1/index.php\?page=$2');
        return;
    }
    if (preg_match('#^([^/\&\?]+)/([^/\&\?]*)/([^\&\?]*)\.htm$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, 'index.php\?page=$1&type=$2&id=$3');
        return;
    }
    if (preg_match('#^([^/\&\?]+)/([^/\&\?]*)\.htm$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, 'index.php\?page=$1&type=$2');
        return;
    }
    if (preg_match('#^([^/\&\?]+)\.htm$#', $uri, $matches) != 0) {
        _roll_nginx_redirect($matches, 'index.php\?page=$1');
        return;
    }
}

/**
 * Perform a software-level URL rewrite for a pretty URL.
 * 
 * @param  array $matches The matches detected in preg_match for our rewrite rule
 * @param  string $to The Apache-style URL to be rewritten to
 * @ignore
 */
function _roll_nginx_redirect(array $matches, string $to)
{
    $to = str_replace('\\?', '?', $to);
    foreach ($matches as $i => $match) {
        $to = str_replace('$' . strval($i), urlencode($match), $to);
    }

    $qs = preg_replace('#^[^\?]*(\?|$)#', '', $to);
    $_SERVER['QUERY_STRING'] = $qs;
    if ($qs != '') {
        if (strpos($_SERVER['REQUEST_URI'], '?') === false) {
            $_SERVER['REQUEST_URI'] .= '?' . $qs;
        } else {
            $_SERVER['REQUEST_URI'] .= '&' . $qs;
        }
    }
    $arr = [];
    parse_str($qs, $arr);
    $_GET += $arr;
}
