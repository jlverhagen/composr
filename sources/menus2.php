/**
 * Delete a menu item.
 *
 * @param  AUTO_LINK $id The ID of the menu item to delete
 */
function delete_menu_item(int $id)
{
    $rows = $GLOBALS['SITE_DB']->query_select('menu_items', ['i_caption', 'i_caption_long', 'i_menu'], ['id' => $id], '', 1);
    if (!array_key_exists(0, $rows)) {
        warn_exit(do_lang_tempcode('MISSING_RESOURCE', 'menu_item', escape_html(strval($id))));
    }
    $_caption = $rows[0]['i_caption'];
    $_caption_long = $rows[0]['i_caption_long'];
    $menu_id = $rows[0]['i_menu'];

    $GLOBALS['SITE_DB']->query_delete('menu_items', ['id' => $id], '', 1);
    $caption = get_translated_text($_caption);
    delete_lang($_caption);
    delete_lang($_caption_long);

    if ($menu_id != '_preview') {
        require_lang('menus');
        log_it('DELETE_MENU_ITEM', strval($id), $caption);

        if ((addon_installed('commandr')) && (!running_script('install')) && (!get_mass_import_mode())) {
            require_code('resource_fs');
            expunge_resource_fs_moniker('menu_item', strval($id));
        }
    }
}

/**
 * Delete a menu.
 *
 * @param  ID_TEXT $menu_id The ID of the menu
 */
function delete_menu(string $menu_id)
{
    // Get content language strings currently used
    $old_menu_bits = list_to_map('id', $GLOBALS['SITE_DB']->query_select('menu_items', ['id', 'i_caption', 'i_caption_long'], ['i_menu' => $menu_id]));

    // Erase old stuff
    foreach ($old_menu_bits as $menu_item_id => $lang_code) {
        $GLOBALS['SITE_DB']->query_delete('menu_items', ['id' => $menu_item_id], '', 1);
        delete_lang($lang_code['i_caption']);
        delete_lang($lang_code['i_caption_long']);
    }

    if ($menu_id != '_preview') {
        if (get_option('header_menu_call_string') == $menu_id || get_option('header_menu_call_string') == '') {
            // Reset option to default, for auto-managed menus
            $GLOBALS['SITE_DB']->query_delete('config', ['c_name' => 'header_menu_call_string'], '', 1);

            // Clear caches
            require_code('caches3');
            if (function_exists('persistent_cache_delete')) {
                persistent_cache_delete('OPTIONS');
            }
            Source_self_learning_cache::erase_smart_cache();
            erase_cached_templates(false, ['GLOBAL_HTML_WRAP']); // Config option saves into templates
        }

        delete_cache_entry('menu');
        persistent_cache_delete(['MENU', $menu_id]);

        if ((addon_installed('commandr')) && (!running_script('install')) && (!get_mass_import_mode())) {
            require_code('resource_fs');
            expunge_resource_fs_moniker('menu', $menu_id);
        }
    }
}

/**
 * Copy a part of the Sitemap to a new menu.
 *
 * @param  ID_TEXT $target_menu The ID of the menu to save into
 * @param  SHORT_TEXT $source Sitemap details
 */
function copy_from_sitemap_to_new_menu(string $target_menu, string $source)
{
    require_code('comcode_from_html');
    require_code('menus');

    $is_sitemap_menu = (preg_match('#^[' . URL_CONTENT_REGEXP . ']+$#', $source) == 0);

    if (!$is_sitemap_menu) {
        $test = $GLOBALS['SITE_DB']->query_select_value('menu_items', 'COUNT(*)', ['i_menu' => $source]);
        if ($test == 0) {
            return; // Nothing to copy
        }
    }

    $root = _build_sitemap_menu($source);
    $order = 0;
    _copy_from_sitemap_to_new_menu($target_menu, $root, $order);
}

/**
 * Copy a Sitemap node's children into a new menu.
 *
 * @param  ID_TEXT $target_menu The ID of the menu to save into
 * @param  array $node Sitemap node, containing children
 * @param  integer $order Sequence order to save with
 * @param  ?AUTO_LINK $parent Menu parent ID (null: root)
 *
 * @ignore
 */
function _copy_from_sitemap_to_new_menu(string $target_menu, array $node, int &$order, ?int $parent = null)
{
    if (isset($node['children'])) {
        foreach ($node['children'] as $child) {
            $theme_image_code = null;
            if ($child['extra_meta']['image'] !== null) {
                $_theme_image_url = $child['extra_meta']['image'];
                if (substr($_theme_image_url, 0, strlen(get_custom_base_url() . '/')) == get_custom_base_url() . '/') {
                    if ($theme_image_code !== null) {
                        $_theme_image_url = substr($theme_image_code, strlen(get_custom_base_url() . '/'));
                    }
                    $theme_image_code = $GLOBALS['SITE_DB']->query_select_value_if_there('theme_images', 'id', ['url' => $_theme_image_url]);
                }
            }

            $branch_id = add_menu_item(
                $target_menu,
                $order,
                $parent,
                semihtml_to_comcode($child['title']->evaluate(), true),
                ($child['page_link'] === null) ? '' : $child['page_link'],
                1,
                '',
                1,
                0,
                ($child['extra_meta']['description'] === null) ? '' : semihtml_to_comcode($child['extra_meta']['description']->evaluate(), true),
                ($theme_image_code === null) ? '' : $theme_image_code,
                0
            );

            $order++;

            _copy_from_sitemap_to_new_menu($target_menu, $child, $order, $branch_id);
        }
    }
}

/**
 * Find all the menu items being saved.
 *
 * @return array A list of the menu item IDs being saved (i.e. what it is referenced as in POST)
 */
function menu_items_being_saved() : array
{
    $xml = post_param_string('xml');

    // Set error handling to throw exceptions (we need to be strict because any attempts to auto-recover the XML may result in loss of menu items)
    $previous = libxml_use_internal_errors(true);

    $parsed = simplexml_load_string($xml, null, LIBXML_HTML_NOIMPLIED | LIBXML_PEDANTIC);

    // Check for errors
    $errors = libxml_get_errors();
    libxml_clear_errors();
    libxml_use_internal_errors($previous);

    if ($errors || !$parsed) {
        $error = ((count($errors) > 0) ? $errors[0]->message : 'Invalid XML structure');
        warn_exit('XML Parse Error: ' . $error); // TODO: lang string
    }

    $ret = [];
    _menu_items_being_saved($parsed, $ret);

    return $ret;
}

/**
 * Process and validate a menu branch.
 *
 * @param  mixed $xml SimpleXMLElement of the menu items
 * @param  array $ret Processed menu items, passed by reference
 * @param  ?ID_TEXT $parent_id The ID of the menu which is a parent to this one (null: this is a top-level menu item)
 * @ignore
 */
function _menu_items_being_saved($xml, array &$ret, ?string $parent_id = null)
{
    if (!isset($xml->menubranch)) {
        return;
    }

    require_code('urls');
    require_code('urls2');
    require_lang('menus');

    foreach ($xml->menubranch as $child) {
        $obj = [
            'id' => uniqid('NEW_', true), // We are deleting and re-creating everything
            'new_window' => (int)$child['new_window'],
            'check_permissions' => (int)$child['check_permissions'],
            'include_sitemap' => (int)$child['include_sitemap'],
            'expanded' => (int)$child['expanded'],
            'caption' => (string)$child['caption'],
            'caption_long' => (string)$child['caption_long'],
            'url' => (string)$child['url'],
            'theme_image' => (string)$child['theme_image'],
            'page_only' => (string)$child['page_only'],
            'parent_id' => $parent_id,
        ];

        // Validation (strict)...

        // New window
        if (($obj['new_window'] !== 0) && ($obj['new_window'] !== 1)) {
            warn_exit(do_lang_tempcode('MENU_EDITOR_INVALID_XML__0_OR_1', escape_html('new_window')));
            return;
        }

        // Check permissions
        if (($obj['check_permissions'] !== 0) && ($obj['check_permissions'] !== 1)) {
            warn_exit(do_lang_tempcode('MENU_EDITOR_INVALID_XML__0_OR_1', escape_html('new_window')));
            return;
        }

        // Expanded
        if (($obj['expanded'] !== 0) && ($obj['expanded'] !== 1)) {
            warn_exit(do_lang_tempcode('MENU_EDITOR_INVALID_XML__0_OR_1', escape_html('new_window')));
            return;
        }

        // Validation (lenient)...

        // Give a warning on empty captions
        if (trim($obj['caption']) == '') {
            attach_message(do_lang_tempcode('MENU_EDITOR_MISSING_CAPTION'), 'notice');
        }

        // Give a warning on broken URLs
        if (trim($obj['url']) != '') {
            $obj['url'] = filter_naughty($obj['url']);

            /*
            $url = page_link_to_url($obj['url'], true);
            $ok = check_url_exists($url, 60 * 60 * 24 * 7);
            if (!$ok) {
                attach_message('Double-check the URL for item ' . strval($obj['id']) . ' as it may be broken (or it is not accessible by guests).', 'notice');
            }
            */
        }

        // Give a warning on invalid theme image codes
        if (trim($obj['theme_image']) != '') {
            $url = find_theme_image($obj['theme_image'], true);
            if ($url == '') {
                attach_message(do_lang_tempcode('NO_SUCH_THEME_IMAGE', escape_html($obj['theme_image'])), 'warn');
            }
        }

        $ret[] = $obj;

        if ($child->count() > 0) {
            _menu_items_being_saved($child, $ret, $obj['id']);
        }
    }
}

/**
 * Save a menu from details parsed from the menu editor.
 *
 * @param  ID_TEXT $menu_id The name of the menu the item is on
 * @param  array $menu_items Menu items to save, processed from menu_items_being_saved
 */
function save_menu_items_from_editor(string $menu_id, array $menu_items)
{
    require_code('urls');

    // Round 1: delete all menu items
    $ids_in_db = $GLOBALS['SITE_DB']->query_select('menu_items', ['DISTINCT id']);
    foreach ($ids_in_db as $row) {
        $old_caption = $GLOBALS['SITE_DB']->query_select_value('menu_items', 'i_caption', ['id' => $row['id']]);
        $old_caption_long = $GLOBALS['SITE_DB']->query_select_value('menu_items', 'i_caption_long', ['id' => $row['id']]);

        $GLOBALS['SITE_DB']->query_delete('menu_items', ['id' => $row['id']]);
        delete_lang($old_caption);
        delete_lang($old_caption_long);
    }

    // Round 2: maintenance
    foreach ($menu_items as $order => &$menu_item) {
        // See if we can tidy a URL back to a page-link
        if (isset($menu_item['url'])) {
            if (preg_match('#^[' . URL_CONTENT_REGEXP . ']+$#', $menu_item['url']) != 0) {
                $menu_item['url'] = ':' . $menu_item['url']; // So users do not have to think about zones
            }
            $page_link = url_to_page_link($menu_item['url'], true);
            if ($page_link != '') {
                $menu_item['url'] = $page_link;
            } elseif (strpos($menu_item['url'], ':') === false) {
                $menu_item['url'] = fixup_protocolless_urls($menu_item['url']);
            }
        }
    }

    unset($menu_item);

    // Round 3: save new menu items
    $new_map = [];
    foreach ($menu_items as $order => $menu_item) {
        $menu_save_map = [
            'i_menu' => $menu_id,
            'i_order' => $order,
            'i_parent_id' => isset($new_map[$menu_item['parent_id']]) ? $new_map[$menu_item['parent_id']] : null,
            'i_link' => $menu_item['url'],
            'i_check_permissions' => intval($menu_item['check_permissions']),
            'i_expanded' => intval($menu_item['expanded']),
            'i_new_window' => intval($menu_item['new_window']),
            'i_include_sitemap' => intval($menu_item['include_sitemap']),
            'i_page_only' => $menu_item['page_only'],
            'i_theme_img_code' => $menu_item['theme_image'],
        ];

        $menu_save_map += insert_lang_comcode('i_caption', $menu_item['caption'], 1);
        $menu_save_map += insert_lang_comcode('i_caption_long', $menu_item['caption_long'], 1);
        $new_map[$menu_item['id']] = $GLOBALS['SITE_DB']->query_insert('menu_items', $menu_save_map, true);
    }
}
