/**
 * Check our rate limiter (and log a hit if enabled).
 */
function check_rate_limit()
{
    if (!class_exists('SQLite3')) {
        return;
    }

    global $SITE_INFO;
    $rate_limiting = !empty($SITE_INFO['rate_limiting']);
    if (!$rate_limiting) {
        return;
    }

    if ((empty($_SERVER['REMOTE_ADDR'])) || (basename($_SERVER['SCRIPT_NAME']) != 'index.php')) {
        return;
    }

    static $already_checked = false;
    if ($already_checked === true) {
        return;
    }
    $already_checked = true;

    // Basic context
    $ip = $_SERVER['REMOTE_ADDR'];

    //if (!(((!empty($_SERVER['SERVER_ADDR'])) && ($ip == $_SERVER['SERVER_ADDR'])) || ((!empty($_SERVER['LOCAL_ADDR'])) && ($ip == $_SERVER['LOCAL_ADDR'])))) {
        // Make the directory where we will create the database
        $path = get_custom_file_base() . '/data_custom/sqlitedb/rate_limiter.sqlite';

        if (!is_file($path)) {
            return;
        }

        // Open the database
        $db_link = new SQLite3($path);
        $db_link->busyTimeout(5000);
        $db_link->createFunction('MD5', 'md5', 1);
        $db_link->exec('PRAGMA foreign_keys=ON;');
        

        // Quick test to make sure that we have a connection. Bail if we don't; we don't want to crash.
        $statement = $db_link->prepare('SELECT 1');
        $result = $statement->execute();
        if ($result === false) {
            return;
        }

        // Prune old records
        $rate_limit_time_window = empty($SITE_INFO['rate_limit_time_window']) ? 10 : intval($SITE_INFO['rate_limit_time_window']);
        $statement = $db_link->prepare('DELETE FROM rate_limiting WHERE ip=:ip AND date_and_time<:date_and_time');
        $statement->bindValue(':ip', $ip, SQLITE3_TEXT);
        $statement->bindValue(':date_and_time', (time() - $rate_limit_time_window), SQLITE3_INTEGER);
        $statement->execute();
        $statement->close();

        // Get our current count
        $statement = $db_link->prepare('SELECT COUNT(ip) AS hit_count FROM rate_limiting WHERE ip=:ip');
        $statement->bindValue(':ip', $ip, SQLITE3_TEXT);
        $result = $statement->execute();
        if ($result === false) {
            return;
        }
        $hit_count = 0;
        while ($row = $result->fetchArray(SQLITE3_ASSOC)) {
            $hit_count += $row['hit_count'];
        }
        $statement->close();

        // Do we have to block?
        $rate_limit_hits_per_window = empty($SITE_INFO['rate_limit_hits_per_window']) ? 5 : intval($SITE_INFO['rate_limit_hits_per_window']);
        if ($hit_count >= $rate_limit_hits_per_window) {
            http_response_code(429);
            header('Content-Type: text/plain');
            exit('We only allow ' . strval($rate_limit_hits_per_window - 1) . ' page hits every ' . strval($rate_limit_time_window) . ' seconds. You\'re at ' . strval($hit_count) . '.');
        }

        // Record new hit
        $statement = $db_link->prepare('INSERT INTO rate_limiting (ip, date_and_time) VALUES (:ip, :date_and_time)');
        $statement->bindValue(':ip', $ip, SQLITE3_TEXT);
        $statement->bindValue(':date_and_time', time(), SQLITE3_INTEGER);
        $statement->execute();
        $statement->close();

        $db_link->close();

        unset($statement);
        unset($db_link);
    //}
}
