/**
 * Remove an item from the general cache (most commonly used for blocks).
 *
 * @param  mixed $cached_for The type of what we are caching (e.g. block name) (ID_TEXT or an array of ID_TEXT, the array may be pairs re-specifying $identifier)
 * @param  ?array $identifier A map of identifying characteristics (null: no identifying characteristics, decache all OR $cached_for is an array)
 * @param  ?MEMBER $member_id Member to only decache for (null: no limit)
 */
function delete_cache_entry($cached_for, ?array $identifier = null, ?int $member_id = null)
{
    if (get_mass_import_mode()) {
        return;
    }

    require_code('caches2');
    _delete_cache_entry($cached_for, $identifier, $member_id);
}

/**
 * Find the cache-on parameters for 'codename's caching style (prevents us needing to load up extra code to find it).
 *
 * @param  ID_TEXT $codename The codename of what will be checked for caching
 * @return ?array The cached result (null: no cached result)
 */
function find_cache_on(string $codename) : ?array
{
    // See if we have it cached
    global $BLOCK_CACHE_ON_CACHE;
    if ($BLOCK_CACHE_ON_CACHE === null) {
        $BLOCK_CACHE_ON_CACHE = persistent_cache_get('BLOCK_CACHE_ON_CACHE');
        if ($BLOCK_CACHE_ON_CACHE === null) {
            $BLOCK_CACHE_ON_CACHE = list_to_map('cached_for', $GLOBALS['SITE_DB']->query_select('cache_on', ['*']));
            persistent_cache_set('BLOCK_CACHE_ON_CACHE', $BLOCK_CACHE_ON_CACHE);
        }
    }
    if (isset($BLOCK_CACHE_ON_CACHE[$codename])) {
        return $BLOCK_CACHE_ON_CACHE[$codename];
    }
    return null;
}

/**
 * Find the cached result of what is named by codename and the further constraints.
 * This will use persistent cache if enabled, else the database.
 *
 * @param  ID_TEXT $codename The codename to check for caching
 * @param  LONG_TEXT $cache_identifier The further restraints (a serialized map)
 * @param  integer $special_cache_flags Special cache flags
 * @param  integer $ttl The TTL for the cache entry in minutes. Defaults to a very big ttl
 * @param  boolean $tempcode Whether we are caching Tempcode (needs special care)
 * @param  boolean $caching_via_cron Whether to defer caching to the system scheduler. Note that this option only works if the block's defined cache signature depends only on $map (timezone and bot-type are automatically considered)
 * @param  array $map Parameters to call up block with if we have to defer caching
 * @return ?mixed The cached result (null: no cached result)
 */
function get_cache_entry(string $codename, string $cache_identifier, int $special_cache_flags = CACHE_AGAINST_DEFAULT, int $ttl = 10000, bool $tempcode = false, bool $caching_via_cron = false, array $map = [])
{
    $det = [$codename, $cache_identifier, hash('sha256', $cache_identifier), $special_cache_flags, $ttl, $tempcode, $caching_via_cron, $map];

    global $SMART_CACHE;
    $test = (get_page_name() == 'admin_addons'/*special case*/) ? [] : $SMART_CACHE->get('blocks_needed');
    if ($test !== false) {
        if (($test === null) || (count($test) < 20)) {
            $SMART_CACHE->append('blocks_needed', serialize($det));
        } else {
            $SMART_CACHE->set('blocks_needed', false); // Disable it for this smart-cache bucket, we probably have some block(s) with the cache signature varying too much
        }
    }

    $rets = _get_cache_entries([$det]);
    if (!array_key_exists(0, $rets)) {
        return null;
    }
    return $rets[0];
}

/**
 * Fill in cache signature details from the environment, based on $special_cache_flags.
 *
 * @param  ?integer $special_cache_flags Special cache flags (null: none)
 * @param  ?BINARY $staff_status Staff status to limit to (null: Get from environment)
 * @param  ?MEMBER $member_id Member to limit to (null: Get from environment)
 * @param  ?SHORT_TEXT $groups Sorted permissive usergroup list to limit to (null: Get from environment)
 * @param  ?BINARY $is_bot Bot status to limit to (null: Get from environment)
 * @param  ?MINIID_TEXT $timezone Timezone to limit to (null: Get from environment)
 * @param  ?ID_TEXT $theme The theme this is being cached for (null: Get from environment)
 * @param  ?LANGUAGE_NAME $lang The language this is being cached for (null: Get from environment)
 */
function get_cache_signature_details(?int $special_cache_flags, ?int &$staff_status, ?int &$member_id, ?string &$groups, ?int &$is_bot, ?string &$timezone, ?string &$theme, ?string &$lang)
{
    if ($staff_status === null) {
        $staff_status = (($special_cache_flags !== null) && (($special_cache_flags & CACHE_AGAINST_STAFF_STATUS) !== 0)) ? ($GLOBALS['FORUM_DRIVER']->is_staff(get_member()) ? 1 : 0) : null;
    }
    if ($member_id === null) {
        $member_id = (($special_cache_flags !== null) && (($special_cache_flags & CACHE_AGAINST_MEMBER) !== 0)) ? get_member() : null;
    }
    if ($groups === null) {
        if (($special_cache_flags !== null) && (($special_cache_flags & CACHE_AGAINST_PERMISSIVE_GROUPS) !== 0)) {
            static $groups_cache = null;

            if ($groups_cache === null) {
                $is_super_admin = $GLOBALS['FORUM_DRIVER']->is_super_admin(get_member());
                $actual_groups = filter_group_permissivity($GLOBALS['FORUM_DRIVER']->get_members_groups(get_member()));
                $m_zone = collapse_1d_complexity('zone_name', $GLOBALS['SITE_DB']->query_select('member_zone_access', ['zone_name'], ['member_id' => get_member()]));
                $m_page = array_map('array_values', $GLOBALS['SITE_DB']->query_select('member_page_access', ['page_name', 'zone_name'], ['member_id' => get_member()], 'ORDER BY zone_name,page_name'));
                $m_privileges = array_map('array_values', $GLOBALS['SITE_DB']->query_select('member_privileges', ['privilege', 'the_page', 'module_the_name', 'category_name', 'the_value'], ['member_id' => get_member()], 'ORDER BY privilege,the_page,module_the_name,category_name,the_value'));
                $m_categories = array_map('array_values', $GLOBALS['SITE_DB']->query_select('member_category_access', ['module_the_name', 'category_name'], ['member_id' => get_member()], 'ORDER BY module_the_name,category_name'));
                if ((empty($m_zone)) && (empty($m_page)) && (empty($m_privileges)) && (empty($m_categories))) {
                    $groups_cache = implode(',', array_map('strval', $actual_groups));
                } else {
                    $groups_cache = json_encode([$actual_groups, $m_zone, $m_page, $m_privileges, $m_categories, $is_super_admin]);
                }
            }

            if (strlen($groups_cache) > 255) {
                $groups_cache = hash('sha256', $groups_cache);
            }

            $groups = $groups_cache;
        } else {
            $groups = '';
        }
    }
    if ($is_bot === null) {
        $is_bot = (($special_cache_flags !== null) && (($special_cache_flags & CACHE_AGAINST_BOT_STATUS) !== 0)) ? ((get_bot_type() === null) ? 0 : 1) : null;
    }
    if ($timezone === null) {
        require_code('temporal');
        $timezone = (($special_cache_flags !== null) && (($special_cache_flags & CACHE_AGAINST_TIMEZONE) !== 0)) ? get_users_timezone(get_member()) : '';
    }
    if ($theme === null) {
        $theme = $GLOBALS['FORUM_DRIVER']->get_theme();
    }
    if ($lang === null) {
        $lang = user_lang();
    }
}

/**
 * Ability to do multiple get_cache_entry at once, for performance reasons.
 * This will use persistent cache if enabled, else the database.
 *
 * @param  array $dets An array of tuples of parameters (as per get_cache_entry, almost)
 * @return array Array of results
 *
 * @ignore
 */
function _get_cache_entries(array $dets) : array
{
    static $cache = [];

    if (empty($dets)) {
        return [];
    }

    // Edge case: cache table might not be upgraded yet, so do not support cache if running the upgrader
    if (running_script('upgrader')) {
        return [];
    }

    $rets = [];
    $cache_rows = [];

    // Get our cache rows
    foreach ($dets as $i => $det) {
        list($codename, $cache_identifier, $cache_identifier_hash, $special_cache_flags, $ttl, $tempcode, $caching_via_cron, $map) = $det;
        $sz = serialize([$codename, $cache_identifier_hash, $special_cache_flags]);

        if (isset($cache[$sz]) && ($cache[$sz][0] !== null)) { // Already loaded previously
            // We still need to check if this is stale
            $stale = (($ttl !== null) && (time() > ($cache[$sz][1] + $ttl * 60)));
            if (!$stale) {
                $rets[$i] = $cache[$sz][0];
                continue;
            }

            unset($cache[$sz]);
        }

        $staff_status = null;
        $member_id = null;
        $groups = null;
        $is_bot = null;
        $timezone = null;
        $theme = null;
        $lang = null;
        get_cache_signature_details($special_cache_flags, $staff_status, $member_id, $groups, $is_bot, $timezone, $theme, $lang);

        if ($GLOBALS['PERSISTENT_CACHE'] !== null) {
            $cache_row = persistent_cache_get(['CACHE', $codename, $cache_identifier_hash, $lang, $theme, $staff_status, $member_id, $groups, $is_bot, $timezone], time() - ($ttl * 60));

            if ($cache_row === null) { // No
                if ($caching_via_cron) {
                    require_code('caches2');
                    request_via_cron($codename, $map, $special_cache_flags, $tempcode);
                    $ret = paragraph(do_lang_tempcode('CACHE_NOT_READY_YET'), '', 'nothing-here');
                } else {
                    $ret = null;
                }

                $cache[$sz] = [$ret, time()];
                $rets[$i] = $ret;
                continue;
            }

            $cache_rows[$i] = $cache_row;
        } else {
            // We cannot bulk-process SQL because then we cannot accurately determine which $det cache rows we received from the database
            $where = [
                'cached_for' => $codename,
                'identifier' => cms_base64_encode($cache_identifier, false, true, true),
                'staff_status' => $staff_status,
                'the_member' => $member_id,
                'the_groups' => ($groups === null) ? '' : $groups,
                'is_bot' => $is_bot,
                'timezone' => ($timezone === null) ? '' : $timezone,
                'the_theme' => $theme,
                'lang' => $lang,
            ];
            $cache_row = $GLOBALS['SITE_DB']->query_select('cache', ['cached_for','identifier','the_value','date_and_time','dependencies'], $where, '', 1);

            if (!array_key_exists(0, $cache_row)) {
                if ($caching_via_cron) {
                    require_code('caches2');
                    request_via_cron($codename, $map, $special_cache_flags, $tempcode);
                    $ret = paragraph(do_lang_tempcode('CACHE_NOT_READY_YET'), '', 'nothing-here');
                } else {
                    $ret = null;
                }

                $cache[$sz] = [$ret, time()];
                $rets[$i] = $ret;
                continue;
            }

            $cache_rows[$i] = $cache_row[0];
        }
    }

    // Now process each cache row we received
    foreach ($cache_rows as $i => $cache_row) {
        list($codename, $cache_identifier, $cache_identifier_hash, $special_cache_flags, $ttl, $tempcode, $caching_via_cron, $map) = $dets[$i];
        $sz = serialize([$codename, $cache_identifier_hash, $special_cache_flags]);

        $stale = (($ttl !== null) && (time() > ($cache_row['date_and_time'] + $ttl * 60)));

        if ($stale) { // Stale
            if (!$caching_via_cron) {
                $ret = null;
                $cache[$sz] = [$ret, time()];
                $rets[$i] = $ret;
                continue;
            }

            require_code('caches2');
            request_via_cron($codename, $map, $special_cache_flags, $tempcode);
        }

        // Process the cache data (only necessary for database cache)
        if ($GLOBALS['PERSISTENT_CACHE'] === null) {
            if ($tempcode) {
                $ob = new Tempcode();
                if (!$ob->from_assembly($cache_row['the_value'], true)) { // Error
                    $ret = null;
                    $cache[$sz] = [$ret, time()];
                    $rets[$i] = $ret;
                    continue;
                }

                $cache_row['the_value'] = $ob;
            } else {
                $cache_row['the_value'] = @unserialize($cache_row['the_value']);

                if ($cache_row['the_value'] === false) { // Corrupt data
                    $cache[$sz] = null;
                    $rets[$i] = null;
                    continue;
                }
            }
        }

        // Load in any dependencies defined
        $ret = $cache_row['the_value'];
        if ($cache_row['dependencies'] != '') {
            $bits = explode('!', $cache_row['dependencies']);
            $langs_required = explode(':', $bits[0]); // Sometimes lang has got intertwined with non cacheable stuff (and thus was itself not cached), so we need the lang files
            foreach ($langs_required as $lang) {
                if ($lang != '') {
                    require_lang($lang, null, null, true);
                }
            }
            if (isset($bits[1])) {
                $javascripts_required = explode(':', $bits[1]);
                foreach ($javascripts_required as $javascript) {
                    require_javascript($javascript);
                }
            }
            if (isset($bits[2])) {
                $csss_required = explode(':', $bits[2]);
                foreach ($csss_required as $css) {
                    require_css($css);
                }
            }
        }

        $cache[$sz] = [$ret, $cache_row['date_and_time']];
        $rets[$i] = $ret;
    }

    return $rets;
}
