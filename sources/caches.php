/**
 * Standard code module initialisation function.
 *
 * @ignore
 */
function init__caches()
{
    require_code('self_learning_cache');

    global $BLOCK_CACHE_ON_CACHE;
    $BLOCK_CACHE_ON_CACHE = null;

    global $ALLOW_DOUBLE_DECACHE;
    $ALLOW_DOUBLE_DECACHE = false;

    if (!defined('CACHE_AGAINST_NOTHING_SPECIAL')) {
        // These are ways we might enhance block caching with standardised (queryable) additional caching restraints
        define('CACHE_AGAINST_NOTHING_SPECIAL', 0);
        // -
        define('CACHE_AGAINST_STAFF_STATUS', 1);
        define('CACHE_AGAINST_MEMBER', 2);
        define('CACHE_AGAINST_PERMISSIVE_GROUPS', 4);
        define('CACHE_AGAINST_BOT_STATUS', 8);
        define('CACHE_AGAINST_TIMEZONE', 16);
        // -
        define('CACHE_AGAINST_DEFAULT', CACHE_AGAINST_BOT_STATUS | CACHE_AGAINST_TIMEZONE);
    }

    global $PERSISTENT_CACHE, $SITE_INFO;
    /** The persistent cache access object (null if there is no persistent cache).
     *
     * @global ?object $PERSISTENT_CACHE
     */
    $PERSISTENT_CACHE = null;

    persistent_cache_init();

    /** The smart cache (self-learning cache).
     *
     * @global boolean $SMART_CACHE
     */
    global $SMART_CACHE, $RELATIVE_PATH, $IN_SELF_ROUTING_SCRIPT;
    if ($IN_SELF_ROUTING_SCRIPT) {
        $zone = $RELATIVE_PATH;
        $page = get_param_string('page', '', INPUT_FILTER_NONE); // Not get_page_name for bootstrap order reasons
        $screen = get_param_string('type', 'browse', INPUT_FILTER_NONE);
        $bucket_name = $zone . ':' . $page . ':' . $screen;
        if ($page != 'topicview' && $screen == 'browse') {
            $bucket_name .= ':' . get_param_string('id', '', INPUT_FILTER_NONE);
        }
    } else {
        $bucket_name = 'script__' . current_script();

        if ($RELATIVE_PATH == '_tests') {
            $bucket_name .= '__' . get_param_string('id', '', INPUT_FILTER_NONE);
        }
    }
    $SMART_CACHE = object_factory('Source_self_learning_cache', false, [$bucket_name], true);

    // Some loading from the smart cache
    global $CSS_OUTPUT_STARTED_LIST, $JS_OUTPUT_STARTED_LIST;
    $CSS_OUTPUT_STARTED_LIST = [];
    $JS_OUTPUT_STARTED_LIST = [];
    global $JAVASCRIPTS, $JS_OUTPUT_STARTED_LIST, $CSSS, $CSS_OUTPUT_STARTED_LIST;
    $test = $SMART_CACHE->get('JAVASCRIPTS');
    if ($test !== null) {
        $JAVASCRIPTS += $test;
        $JS_OUTPUT_STARTED_LIST += $test;
    }
    $test = $SMART_CACHE->get('CSSS');
    if ($test !== null) {
        $CSSS += $test;
        $CSS_OUTPUT_STARTED_LIST += $test;
    }
}

/**
 * Try to initialise a persistent cache if we can.
 */
function persistent_cache_init()
{
    static $is_initialising = false;

    global $SITE_INFO, $PERSISTENT_CACHE;

    if (isset($PERSISTENT_CACHE)) {
        return;
    }

    if (empty($SITE_INFO['use_persistent_cache'])) {
        return;
    }

    if (!function_exists('find_all_hooks')) {
        return;
    }

    // We might trigger this again while trying to find a persistent cache to use. Prevent this loop.
    if ($is_initialising) {
        return;
    }
    $is_initialising = true;

    $priorities = [];
    $hooks = find_all_hooks('systems', 'persistent_caching');
    foreach ($hooks as $hook => $type) {
        require_code('hooks/systems/persistent_caching/' . filter_naughty_harsh($hook));
        $priority = call_user_func('Hook_persistent_cache_' . filter_naughty_harsh($hook) . '::cache_priority');
        if ($priority) { // Not false and not zero
            $priorities[] = ['hook' => $hook, 'priority' => $priority];
        }
    }

    sort_maps_by($priorities, 'priority');

    if (array_key_exists(0, $priorities)) {
        $PERSISTENT_CACHE = get_hook_ob('systems', 'persistent_caching', filter_naughty_harsh($priorities[0]['hook']), 'Hook_persistent_cache_');
    }

    $is_initialising = false;
    // NB: sources/hooks/systems/health_checks/persistent_cache.php also references some of this ^
}

/**
 * Get data from the persistent cache.
 *
 * @param  mixed $key Key
 * @param  ?TIME $min_cache_date Minimum timestamp that entries from the cache may hold (null: don't care)
 * @return ?mixed The data (null: not found / null entry)
 */
function persistent_cache_get($key, ?int $min_cache_date = null)
{
    global $PERSISTENT_CACHE;
    persistent_cache_init();

    //if (($GLOBALS['DEV_MODE']) && (mt_rand(0, 3) == 1)) return null;  Annoying when doing performance tests, but you can enable to test persistent cache more
    if ($PERSISTENT_CACHE === null) {
        return null;
    }

    $test = $PERSISTENT_CACHE->get(get_file_base() . serialize($key), $min_cache_date); // First we'll try specifically for site
    if ($test !== null) {
        return $test;
    }
    /*if (!is_a($PERSISTENT_CACHE, 'Hook_persistent_cache_filesystem')) {  Server-wide bad idea
        $test = $PERSISTENT_CACHE->get(('cms' . float_to_raw_string(cms_version_number())) . serialize($key), $min_cache_date); // And last we'll try server-wide
    }*/
    return $test;
}

/**
 * Put data into the persistent cache.
 *
 * @param  mixed $key Key
 * @param  mixed $data The data
 * @param  boolean $server_wide Whether it is server-wide data
 * @param  ?integer $expire_secs The expiration time in seconds. (null: Default expiry in 60 minutes, or never if it is server-wide).
 */
function persistent_cache_set($key, $data, bool $server_wide = false, ?int $expire_secs = null)
{
    global $PERSISTENT_CACHE;
    persistent_cache_init();

    if ($PERSISTENT_CACHE === null) {
        return;
    }
    if ($expire_secs === null) {
        $expire_secs = $server_wide ? 0 : (60 * 60);
    }

    /*if (is_a($PERSISTENT_CACHE, 'Hook_persistent_cache_filesystem')) {   Server-wide bad idea
        $server_wide = false;
    }*/
    $server_wide = false;

    $PERSISTENT_CACHE->set(($server_wide ? ('cms' . float_to_raw_string(cms_version_number())) : get_file_base()) . serialize($key), $data, 0, $expire_secs);
}

/**
 * Delete data from the persistent cache.
 *
 * @param  mixed $key Key name
 * @param  boolean $substring Whether we are deleting via substring
 */
function persistent_cache_delete($key, bool $substring = false)
{
    global $PERSISTENT_CACHE;
    persistent_cache_init();

    if ($PERSISTENT_CACHE === null) {
        return;
    }

    if ($substring) {
        $list = $PERSISTENT_CACHE->load_objects_list();
        foreach (array_keys($list) as $l) {
            $delete = true;
            foreach (is_array($key) ? $key : [$key] as $key_part) {
                if (strpos($l, $key_part) === false) { // Should work even though key was serialized, in reasonable cases
                    $delete = false;
                    break;
                }
            }
            if ($delete) {
                $PERSISTENT_CACHE->delete($l);
            }
        }
    } else {
        $PERSISTENT_CACHE->delete(get_file_base() . serialize($key));
        /*if (!is_a($PERSISTENT_CACHE, 'Hook_persistent_cache_filesystem')) {  Server-wide bad idea
            $PERSISTENT_CACHE->delete('cms' . float_to_raw_string(cms_version_number()) . serialize($key));
        }*/
    }
}

/**
 * Remove all data from the persistent cache and static cache.
 */
function erase_persistent_cache()
{
    static $done_once = false;
    global $ALLOW_DOUBLE_DECACHE;
    if (!$ALLOW_DOUBLE_DECACHE) {
        if ($done_once) {
            return;
        }
    }
    $done_once = true;

    // Only flush HTTP cache whose modification and access times are older than 7 days; the task queue may need newer ones
    $path = get_custom_file_base() . '/caches/http';
    if (is_dir($path)) {
        $d = opendir($path);
        while (($e = readdir($d)) !== false) {
            $file_time = max(fileatime(get_custom_file_base() . '/caches/http/' . $e), filemtime(get_custom_file_base() . '/caches/http/' . $e));
            if ((substr($e, -4) == '.bin') && ($file_time <= (time() - (60 * 60 * 24 * 7)))) {
                @unlink(get_custom_file_base() . '/caches/http/' . $e);
            }
        }
        closedir($d);
    }

    // Also flush static cache
    erase_static_cache();

    // Also flush failover cache
    require_code('files');
    if (cms_is_writable(get_custom_file_base() . '/data_custom/failover_rewritemap.txt')) {
        cms_file_put_contents_safe(get_custom_file_base() . '/data_custom/failover_rewritemap.txt', '', FILE_WRITE_FAILURE_SOFT | FILE_WRITE_FIX_PERMISSIONS);
    }
    if (cms_is_writable(get_custom_file_base() . '/data_custom/failover_rewritemap__mobile.txt')) {
        cms_file_put_contents_safe(get_custom_file_base() . '/data_custom/failover_rewritemap__mobile.txt', '', FILE_WRITE_FAILURE_SOFT | FILE_WRITE_FIX_PERMISSIONS);
    }

    // Flush database cache
    $GLOBALS['SITE_DB']->query_delete('cache');

    global $PERSISTENT_CACHE;
    persistent_cache_init();

    // Do not continue if we do not have a persistent cache
    if ($PERSISTENT_CACHE === null) {
        return;
    }

    // Clear the filesystem cache as well since we cannot set expiration dates on files
    if (!is_a($PERSISTENT_CACHE, 'Hook_persistent_cache_filesystem')) {
        $path = get_custom_file_base() . '/caches/persistent';
        if (is_dir($path)) {
            $d = opendir($path);
            while (($e = readdir($d)) !== false) {
                if (substr($e, -4) == '.gcd') {
                    // Ideally we'd lock while we delete, but it's not stable (and the workaround would be too slow for our efficiency context). So some people reading may get errors while we're clearing the cache. Fortunately this is a rare op to perform.
                    @unlink(get_custom_file_base() . '/caches/persistent/' . $e);
                }
            }
            closedir($d);
        }
    }

    $PERSISTENT_CACHE->flush();
}

/**
 * Remove all data from the static cache.
 */
function erase_static_cache()
{
    $path = get_custom_file_base() . '/caches/static';
    if (!file_exists($path)) {
        return;
    }
    $d = opendir($path);
    while (($e = readdir($d)) !== false) {
        if ((substr($e, -4) == '.htm' || substr($e, -4) == '.xml' || substr($e, -3) == '.gz' || substr($e, -3) == '.br') && (strpos($e, '__failover_mode') === false)) {
            // Ideally we'd lock while we delete, but it's not stable (and the workaround would be too slow for our efficiency context). So some people reading may get errors while we're clearing the cache. Fortunately this is a rare op to perform.
            @unlink(get_custom_file_base() . '/caches/static/' . $e);
        }
    }
    closedir($d);
}

/**
 * Check to see if caching is enabled.
 *
 * @param  string $type Cache type
 * @set block lang comcode_page template
 * @param  ?string $name The name (filename? codename?) of what we are using the cache for, so we can support low-level cache avoidance via URL parameter (null: none)
 * @return boolean Whether it has the caching
 */
function has_caching_for(string $type, ?string $name = null) : bool
{
    if (!function_exists('get_option')) {
        return false;
    }

    $cache_avoid_for = get_param_string('keep_cache_avoid_for', null);

    static $cache = [];
    if ($cache_avoid_for === null || $name === null) {
        if (isset($cache[$type])) {
            return $cache[$type];
        }
    }

    $setting = (get_option('is_on_' . $type . '_cache', true) === '1');

    $positive = (get_param_integer('keep_cache', 0) == 1) || (get_param_integer('cache', 0) == 1) || (get_param_integer('keep_cache_' . $type . 's', 0) == 1) || (get_param_integer('cache_' . $type . 's', 0) == 1);

    $not_negative = (get_param_integer('keep_cache', null) !== 0) && (get_param_integer('cache', null) !== 0) && (get_param_integer('keep_cache_' . $type . 's', null) !== 0) && (get_param_integer('cache_' . $type . 's', null) !== 0);

    $specific_avoid = ($cache_avoid_for !== null) && ($name !== null) && (preg_match('#' . str_replace('#', '\#', $cache_avoid_for) . '#', $name) != 0);

    $ret = ($setting || $positive) && $not_negative && !$specific_avoid;

    if ($cache_avoid_for === null || $name === null) {
        $cache[$type] = $ret;
    }
    return $ret;
}

