function init__symbols()
{
    global $BLOCKS_CACHE, $PAGES_CACHE, $PANELS_CACHE, $STATIC_TEMPLATE_TEST_MODE;
    $BLOCKS_CACHE = [];
    $PAGES_CACHE = [];
    $PANELS_CACHE = [];
    $STATIC_TEMPLATE_TEST_MODE = false;
}

/**
 * Evaluate a Tempcode symbol, directive, or language string.
 *
 * @param  string $lang The language to evaluate this symbol in (some symbols refer to language elements)
 * @param  array $escaped Array of escaping operations
 * @param  integer $type The type of symbol this is (TC_SYMBOL, TC_DIRECTIVE, TC_LANGUAGE_REFERENCE)
 * @set 0 4 2
 * @param  ID_TEXT $name The name of the symbol
 * @param  array $param Parameters to the symbol. For all but directive it is an array of strings. For directives it is an array of Tempcode objects. Actually there may be template-style parameters in here, as an influence of singular_bind and these may be Tempcode, but we ignore them.
 * @param  ID_TEXT $template_name The name of the template this came from (blank: not from a file / unknown); only passed for directives to avoid infinite loops with INCLUDE
 * @return mixed The result. Either Tempcode, or a string.
 */
function ecv(string $lang, array $escaped, int $type, string $name, array $param, string $template_name = '')
{
    static $symbols = null;
    static $directives = [];

    $name = trim($name);

    // SYMBOLS

    if ($type === TC_SYMBOL) {
        // Special names
        if ($name === '?') {
            $name = 'TERNARY';
        }
        if ($name === '') {
            $name = 'COMMENT';
        }

        // Prepare symbols if we have not done so already
        if ($symbols === null) {
            $symbols = [];
            if (running_script('install')) {
                $symbols = ['BETA_CSS_PROPERTY' => object_factory('Hook_symbol_BETA_CSS_PROPERTY')]; // Needed for installer to look good ('get_hook_ob' won't run in initial steps of quick installer)
            }
        }

        // Find the symbol hook / object
        if (!running_script('install') && !isset($symbols[$name])) {
            $symbols[$name] = get_hook_ob('systems', 'symbols', $name, 'Hook_symbol_', true);
        }

        if (isset($symbols[$name])) {
            // Found it!
            $info = $symbols[$name]->info();
            if ($info === null) {
                $value = ''; // Silent fail / return blank if the symbol exists but is disabled
            } else {
                $value = $symbols[$name]->run($param, $lang, $escaped);
            }

            if (!empty($escaped)) {
                if (is_object($value)) {
                    $value = $value->evaluate();
                }
                apply_tempcode_escaping($escaped, $value);
            }
        } else {
            // The symbol is a defined constant?
            if (defined($name)) {
                $value = @strval(constant($name));
                if (!is_string($value)) {
                    $value = strval($value);
                }

                if (!empty($escaped)) {
                    if (is_object($value)) {
                        $value = $value->evaluate();
                    }
                    apply_tempcode_escaping($escaped, $value);
                }
            } else {
                // Symbol does not exist at all
                $value = '';
                if ($GLOBALS['XSS_DETECT']) {
                    ocp_mark_as_escaped($value);
                }

                if (!running_script('install')) {
                    trigger_error(do_lang('MISSING_SYMBOL', escape_html($name)), E_USER_NOTICE);

                    persistent_cache_delete('HOOKS'); // May be a cache issue, find it on refresh
                }
            }
        }

        return $value;
    }

    // DIRECTIVES...

    if ($type === TC_DIRECTIVE) {
        $value = '';
        if ($GLOBALS['XSS_DETECT']) {
            ocp_mark_as_escaped($value);
        }

        // In our param we should have a map of bubbled template parameters (under 'vars') and our numbered directive parameters

        if ($param === null) {
            $param = [];
        }

        // Closure-based Tempcode parser may send in strings, so we need to adapt...
        static $directive_tempcodified_params = [];
        foreach ($param as $key => $val) {
            if (is_string($val)) {
                if (!isset($directive_tempcodified_params[$val])) {
                    $directive_tempcodified_params[$val] = make_string_tempcode($val);
                }
                $param[$key] = $directive_tempcodified_params[$val];
            }
        }

        if (!isset($param['vars'])) {
            $param['vars'] = [];
        }

        if (!isset($directives[$name])) {
            $directives[$name] = get_hook_ob('systems', 'directives', filter_naughty_harsh($name), 'Hook_directive_', true);
            if ($directives[$name] === null) {
                trigger_error(do_lang('UNKNOWN_DIRECTIVE', escape_html($name)), E_USER_NOTICE);
            }
        }

        if (isset($directives[$name])) {
            $info = $directives[$name]->info();
            if ($info !== null) {
                $directives[$name]->run($value, $param, $lang, $escaped, $template_name);
            }

            if (!empty($escaped)) {
                apply_tempcode_escaping($escaped, $value);
            }
        }

        return $value;
    }

    // LANGUAGE STRINGS...

    if ($type === TC_LANGUAGE_REFERENCE) {
        $a = isset($param[0]) ? (is_object($param[0]) ? $param[0]->evaluate() : $param[0]) : null;
        $b = isset($param[1]) ? (is_object($param[1]) ? $param[1]->evaluate() : $param[1]) : null;
        $c = isset($param[2]) ? array_splice($param, 2) : null;
        if ($c !== null) {
            foreach ($c as $i => $cc) {
                if (is_object($cc)) {
                    $c[$i] = $cc->evaluate();
                }
            }
        }
        static $dle = false;
        if (!$dle) {
            $dle = function_exists('do_lang');
        }
        $value = $dle ? do_lang($name, $a, $b, $c, $lang, false) : escape_html($name . ':' . (($a !== null) ? $a : '') . ',' . (($b !== null) ? $b : ''));
        if ($value === null) {
            trigger_error(do_lang('MISSING_LANG_STRING', escape_html($name)), E_USER_NOTICE);

            $value = '';
            if ($GLOBALS['XSS_DETECT']) {
                ocp_mark_as_escaped($value);
            }
            return $value;
        }

        if ((!empty($escaped)) && ($escaped !== [ENTITY_ESCAPED])) {
            apply_tempcode_escaping(array_diff($escaped, [ENTITY_ESCAPED]), $value); // Escape but without ENTITY_ESCAPED because we don't do that on language strings
        } elseif ($GLOBALS['XSS_DETECT']) {
            ocp_mark_as_escaped($value);
        }

        return $value;
    }

    // We should never get here
    trigger_error(do_lang('INTERNAL_ERROR', comcode_escape('TODO')), E_USER_NOTICE);
    return '';
}
