/**
 * Load a Bayes classifier for use with classifying spam.
 *
 * @param  ?MEMBER $member_id The member for which we will get the language (null: use $lang)
 * @param  ?LANGUAGE_NAME $lang The language to use, if $member_id is null (null: site default language)
 * @return ?object The initialised classifier object (null: could not load)
 */
function load_bayes_antispam(?int $member_id = null, ?string $lang = null) : ?object
{
    if (!addon_installed('bayes_antispam')) {
        return null;
    }
    if (!addon_installed('bayes_common')) {
        return null;
    }

    require_code('bayes');

    if ($member_id !== null) {
        $lang = get_lang($member_id);
    } elseif ($lang === null) {
        $lang = get_site_default_lang();
    }

    // We use object_factory for cache support
    return object_factory('CMS_Bayes_classifier', false, [$GLOBALS['SITE_DB'], 'antispam_bayes', $lang, floatval(get_option('antispam_bayes_smoothing'))], true);
}

/**
 * Get training data for the Bayes antispam system from a given content type and ID.
 *
 * @param  ID_TEXT $content_type The content type
 * @param  ID_TEXT $content_id The content ID
 * @param  boolean $fail_ok Whether to bail with an empty array opposed to throwing an internal error
 * @param  boolean $force Whether to return data anyway even if the content is newer than 7 days old
 * @param  array $skip_fields Array of fields we should not return in the data
 * @return array List of strings to train on the Bayes model
 */
function content_get_antispam_data(string $content_type, string $content_id, bool $fail_ok = false, bool $force = false, array $skip_fields = []) : array
{
    if (!addon_installed('bayes_antispam') || !addon_installed('bayes_common')) {
        if ($fail_ok) {
            return [];
        }
        warn_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('TODO')));
    }

    require_code('content');
    require_code('comcode');

    list($_content_title, $submitter_id, $cma_info, $content_row, $content_url, $content_url_email_safe, $cma_ob) = content_get_details($content_type, $content_id, false, true);
    if ($cma_ob === null) {
        if ($fail_ok) {
            return [];
        }
        warn_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('TODO')));
    }
    if ($cma_info === null) { // Not an error; hook is disabled
        return [];
    }

    // Hook should not be trained on?
    if (!isset($cma_info['additional_antispam_fields'])) {
        return [];
    }

    // Unless forced, do not return training data if the content is newer than 7 days old (the system scheduler will eventually take care of that)
    if (!$force && !isset($cma_info['add_time_field'])) {
        return [];
    }
    if (!$force && ($content_row[$cma_info['add_time_field']] > (time() - (60 * 60 * 24 * 7)))) {
        return [];
    }

    /*
        FUDGE: do not train on private topics or their posts dealing with warnings.
        This is because they often contain a copy of, or discussion of, spam content. We do not want to accidentally train that as ham.
    */
    if (addon_installed('cns_warnings') && ($content_type == 'topic')) {
        require_lang('cns_warnings');

        if ($_content_title === do_lang('NEW_WARNING_TO_YOU')) {
            return [];
        }
    }
    if (addon_installed('cns_warnings') && ($content_type == 'post')) {
        require_lang('cns_warnings');

        list($topic_title) = content_get_details('topic', strval($content_row['p_topic_id']), false, true);
        if ($topic_title === do_lang('NEW_WARNING_TO_YOU')) {
            return [];
        }
    }

    $ret = [];

    // Title
    if (!in_array('title', $skip_fields)) {
        // FUDGE: for catalogue entries, the title comes from one of the fields which we will be getting via additional_antispam_fields anyway.
        if ($content_type != 'catalogue_entry') {
            $content_title = $cma_ob->get_title($content_row, FIELD_RENDER_COMCODE);
            if (($content_title !== null) && ($content_title != '')) {
                $ret[] = strip_comcode($content_title, false, [], true, true);
            }
        }
    }

    // Description
    if (!in_array('description', $skip_fields)) {
        $content_description = $cma_ob->get_description($content_row, FIELD_RENDER_COMCODE);
        if ($content_description != '') {
            $ret[] = strip_comcode($content_description, false, [], true, true);
        }
    }

    // Custom fields; actually these are already trained through catalogue entries
    /*
    if (!in_array('custom_fields', $skip_fields)) {
        if (($cma_info['support_custom_fields']) && (addon_installed('catalogues'))) {
            require_code('fields');
            $catalogue_entry_id = get_bound_content_entry($content_type, $content_id);
            if ($catalogue_entry_id !== null) {
                $cf_ret = content_get_antispam_data('catalogue_entry', strval($catalogue_entry_id), true);
                $ret = array_merge($ret, $cf_ret);
            }
        }
    }
    */

    // Additional fields
    if (!in_array('additional_antispam_fields', $skip_fields)) {
        foreach ($cma_info['additional_antispam_fields'] as $field) {
            if (in_array('additional__' . $field, $skip_fields)) {
                continue;
            }
            $additional_text = $cma_ob->get_textual_field($content_row, FIELD_RENDER_PLAIN, $cma_info, $field, null, null);
            if (($additional_text !== null) && ($additional_text != '')) {
                foreach (explode('||NEWITEM||', $additional_text) as $train_line) {
                    $ret[] = strip_comcode($train_line, false, [], true, true);
                }
            }
        }
    }

    return $ret;
}
