/**
 * Get a list of the defined tables.
 *
 * @param  object $db Database connector to look in
 * @return array The tables
 */
function find_all_tables(object $db) : array
{
    $fields = $db->query_select('db_meta', ['m_table', 'm_name', 'm_type'], [], 'ORDER BY m_table');
    $tables = [];
    foreach ($fields as $field) {
        if (!isset($tables[$field['m_table']])) {
            $tables[$field['m_table']] = [];
        }
        $tables[$field['m_table']][$field['m_name']] = $field['m_type'];
    }

    // FUDGE: these tables are not included in db_meta
    $tables['db_meta'] = [
        'm_table' => '*ID_TEXT',
        'm_name' => '*ID_TEXT',
        'm_type' => 'ID_TEXT',
    ];
    $tables['db_meta_indices'] = [
        'i_table' => '*ID_TEXT',
        'i_name' => '*ID_TEXT',
        'i_fields' => '*ID_TEXT',
    ];
    $tables['db_meta_foreign_keys'] = [
        'from_table' => '*ID_TEXT',
        'from_field' => '*ID_TEXT',
        'to_table' => 'ID_TEXT',
        'to_field' => 'ID_TEXT',
        'special_values' => 'SERIAL',
    ];

    ksort($tables);

    return $tables;
}

/**
 * Get an SQL dump of a database.
 *
 * @param  resource $out_file File to stream into
 * @param  boolean $include_drops Whether to include 'DROP' statements
 * @param  boolean $include_data Whether to include table data, otherwise we just want the structure
 * @param  boolean $output_statuses Whether to output status as we go
 * @param  array $skip Array of table names to skip
 * @param  ?array $only Array of only table names to do (null: all)
 * @param  ?object $db Database connector to use (null: site database)
 * @param  ?string $intended_db_type Database driver to use (null: site database driver)
 */
function get_sql_dump($out_file, bool $include_drops = false, bool $include_data = true, bool $output_statuses = false, array $skip = [], ?array $only = null, ?object $db = null, ?string $intended_db_type = null)
{
    disable_php_memory_limit();
    $old_limit = cms_disable_time_limit();
    push_db_scope_check(false);
    push_query_limiting(false);

    require_code('database_helper');

    if ($db === null) {
        $db = $GLOBALS['SITE_DB'];
    }

    if ($intended_db_type === null) {
        $intended_db_type = get_db_type();
    }
    require_code('database/' . filter_naughty_harsh($intended_db_type));
    $db_static = object_factory('Source_database_static_' . filter_naughty_harsh($intended_db_type), false, [get_table_prefix()]);

    if (!$db->driver->has_drop_table_if_exists($db->connection_write)) {
        $include_drops = false; // "DROP IF EXISTS" only supported on some DBs.
    }

    // Tables
    $tables = find_all_tables($db);
    foreach ($tables as $table_name => $fields) {
        if (in_array($table_name, $skip)) {
            continue;
        }
        if (($only !== null) && (!in_array($table_name, $only))) {
            continue;
        }

        if ($output_statuses) {
            print('Dumping table ' . $table_name . "\n");
            cms_flush_safe();
        }

        if ($include_drops) {
            $queries = $db_static->drop_table_if_exists__sql($db->get_table_prefix() . $table_name, $db->connection_write);
            foreach ($queries as $i => $sql) {
                if ($i != 0) {
                    fwrite($out_file, "\n");
                }

                fwrite($out_file, $sql . ";\n");
            }
        }

        $fields_copy = $fields;
        foreach ($fields_copy as $name => $type) {
            if (multi_lang_content() === false) {
                if (strpos($type, '_TRANS') !== false) {
                    if (strpos($type, '__COMCODE') !== false) {
                        $fields[$name . '__text_parsed'] = 'LONG_TEXT';
                        $fields[$name . '__source_user'] = 'MEMBER';
                    }

                    $fields[$name] = 'LONG_TEXT'; // In the DB layer, it must now save as such
                }
            }
        }
        $save_bytes = _helper_needs_to_save_bytes($table_name, $fields);
        $queries = $db_static->create_table__sql($db->get_table_prefix() . $table_name, $fields, $db->connection_write, $table_name, $save_bytes);
        foreach ($queries as $i => $sql) {
            if ($i != 0) {
                fwrite($out_file, "\n");
            }

            fwrite($out_file, $sql . ";\n");
        }

        // Indexes
        $indexes = $db->query_select('db_meta_indices', ['*'], ['i_table' => $table_name]);
        foreach ($indexes as $i => $index) {
            if ($i != 0) {
                fwrite($out_file, "\n");
            }

            $index_name = $index['i_name'];

            if ($index_name[0] == '#') {
                $_index_name = substr($index_name, 1);
                $is_full_text = true;
            } else {
                $_index_name = $index_name;
                $is_full_text = false;
            }

            $fields = [];
            foreach (explode(',', $index['i_fields']) as $field_name) {
                $db_type = $GLOBALS['SITE_DB']->query_select_value_if_there('db_meta', 'm_type', ['m_table' => $table_name, 'm_name' => $field_name]);
                $fields[$field_name] = $db_type;
            }

            $_fields = _helper_generate_index_fields($table_name, $fields, $is_full_text);

            if ($_fields !== null) {
                $unique_key_fields = implode(',', _helper_get_table_key_fields($table_name));

                $queries = $db_static->create_index__sql($db->get_table_prefix() . $table_name, $index_name, $_fields, $db->connection_write, $table_name, $unique_key_fields, $db->get_table_prefix());
                foreach ($queries as $sql) {
                    fwrite($out_file, $sql . ";\n");
                }
            }
        }

        // TODO: foreign key constraints when we support them

        // Data
        if ($include_data) {
            $start = 0;
            do {
                $data = $db->query_select($table_name, ['*'], [], '', 100, $start, false, []);
                $values_buildup = '';
                foreach ($data as $row_counter => $map) {
                    $keys = '';
                    $all_values = [];

                    foreach ($map as $key => $value) {
                        if ($keys != '') {
                            $keys .= ', ';
                        }
                        $keys .= $key;

                        $_value = (!is_array($value)) ? [$value] : $value;

                        $v = null;
                        foreach ($_value as $i => $v) {
                            if (!array_key_exists($i, $all_values)) {
                                $all_values[$i] = '';
                            }
                            $values = $all_values[$i];

                            if ($values != '') {
                                $values .= ', ';
                            }

                            if ($value === null) {
                                $values .= 'NULL';
                            } else {
                                if (is_float($v)) {
                                    $values .= float_to_raw_string($v);
                                } elseif (is_integer($v)) {
                                    $values .= strval($v);
                                } else {
                                    $values .= '\'' . db_escape_string($v) . '\'';
                                }
                            }

                            $all_values[$i] = $values; // essentially appends, as $values was loaded from former $all_values[$i] value
                        }
                    }

                    if ((!$db->driver->has_batch_inserts()) || (!isset($data[$row_counter + 1])) || (($row_counter != 0) && ($row_counter % 40) == 0)) {
                        $sql = 'INSERT INTO ' . $db->get_table_prefix() . $table_name . ' (' . $keys . ') VALUES ' . $values_buildup . '(' . $all_values[0] . ')';
                        fwrite($out_file, $sql . ";\n");

                        $values_buildup = '';
                    } else {
                        $values_buildup .= '(' . $all_values[0] . '),' . "\n";
                    }
                }

                $start += 100;
            } while (!empty($data));

            // Divider, if we put out some data
            if ($start > 0) {
                fwrite($out_file, "\n");
            }
        }
    }

    pop_db_scope_check();
    pop_query_limiting();

    cms_set_time_limit($old_limit);
}
