            $ret['week_of_year'] = do_lang_tempcode('PIVOT_X_OF', do_lang_tempcode('_WEEK'));
        }
        $ret['month_series'] = do_lang_tempcode('PIVOT_X_SERIES', do_lang_tempcode('MONTH'));
