    /**
     * Get the pivot value (date-differentiation value within a bucket) for a standard date pivot type.
     *
     * @param  string $pivot Pivot type
     * @param  TIME $timestamp Timestamp
     * @return integer Pivot value
     */
    protected function calculate_date_pivot_value(string $pivot, int $timestamp) : int
    {
        require_code('temporal');

        switch ($pivot) {
            case 'hour_of_day':
                return intval(cms_date('H', $timestamp));
            case 'day_series':
                return 0; // Always only have one entry per interval
            case 'day_of_week':
                return intval(cms_date('w', $timestamp));
            case 'week_series':
                return 0; // Always only have one entry per interval
            case 'week_of_year':
                return intval(cms_date('W', $timestamp));
            case 'month_series':
                return 0; // Always only have one entry per interval
            case 'month_of_year':
                return intval(cms_date('m', $timestamp));
            case 'quarter_series':
                return 0; // Always only have one entry per interval
            case 'quarter_of_year':
                $_month = to_epoch_interval_index($timestamp, 'months');
                $month = ($_month % 12);
                return intval($month / 3);
            case 'year_series':
                return 0; // Always only have one entry per interval
        }

        fatal_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('3ad7fc19c15355a88480afc058c36e78')));
        return 0;
    }

    /**
     * Get the pivot interval for a standard date pivot type.
     *
     * @param  string $pivot Pivot type
     * @param  TIME $timestamp Timestamp
     * @return integer Pivot interval
     */
    protected function calculate_date_pivot_interval(string $pivot, int $timestamp) : int
    {
        require_code('temporal');

        switch ($pivot) {
            case 'hour_of_day':
            case 'day_series':
                return to_epoch_interval_index($timestamp, 'days');
            case 'day_of_week':
            case 'week_series':
                return to_epoch_interval_index($timestamp, 'weeks');
            case 'month_series':
                return to_epoch_interval_index($timestamp, 'months');
            case 'quarter_series':
                return intval(to_epoch_interval_index($timestamp, 'months') / 3);
            case 'week_of_year':
            case 'month_of_year':
            case 'quarter_of_year':
            case 'year_series':
                return to_epoch_interval_index($timestamp, 'years');
        }

        fatal_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('994970ac19665c158f27f7dbd486725b')));
        return 0;
    }

    /**
     * Fill up an array with all standard date pivot values between a day range.
     *
     * @param  string $pivot Pivot type
     * @param  integer $start The pivot interval at which we are starting
     * @param  integer $end The pivot interval at which we are ending
     * @return array Array of 'pivot', 'pivot interval', 'pivot value'
     */
    public function fill_data_by_date_pivots(string $pivot, int $start, int $end) : array
    {
        require_code('temporal');

        $data = [];
        switch ($pivot) {
            case 'hour_of_day':
                for ($i = $start; $i <= $end; $i++) {
                    for ($j = 0; $j <= 23; $j++) {
                        $data[$pivot][$i][$j] = null;
                    }
                }
                break;

            case 'day_series':
                for ($i = $start; $i <= $end; $i++) {
                    $data[$pivot][$i][0] = null;
                }
                break;

            case 'day_of_week':
                for ($i = $start; $i <= $end; $i++) {
                    for ($j = 0; $j <= 6; $j++) {
                        $data[$pivot][$i][$j] = null;
                    }
                }
                break;

            case 'week_series':
                for ($i = $start; $i <= $end; $i++) {
                    $data[$pivot][$i][0] = null;
                }
                break;

            case 'week_of_year':
                for ($i = $start; $i <= $end; $i++) {
                    for ($j = 1; $j <= 53; $j++) {
                        $data[$pivot][$i][$j] = null;
                    }
                }
                break;

            case 'month_series':
                for ($i = $start; $i <= $end; $i++) {
                    $data[$pivot][$i][0] = null;
                }
                break;

            case 'month_of_year':
                for ($i = $start; $i <= $end; $i++) {
                    for ($j = 0; $j <= 11; $j++) {
                        $data[$pivot][$i][$j] = null;
                    }
                }
                break;

            case 'quarter_series':
                for ($i = $start; $i <= $end; $i++) {
                    $data[$pivot][$i][0] = null;
                }
                break;

            case 'quarter_of_year':
                for ($i = $start; $i <= $end; $i++) {
                    for ($j = 0; $j <= 3; $j++) {
                        $data[$pivot][$i][$j] = null;
                    }
                }
                break;

            case 'year_series':
                for ($i = $start; $i <= $end; $i++) {
                    $data[$pivot][$i][0] = null;
                }
                break;

            default:
                fatal_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('b7e50ce76c7f534d9b736f432fcb0072')));
        }

        return $data;
    }

    /**
     * Fill up an array with all standard date pivot values between a day range (used for generating graphs).
     *
     * @param  string $pivot Pivot type
     * @param  integer $start The pivot interval at which we are starting
     * @param  integer $end The pivot interval at which we are ending
     * @return array Map of "nice" pivot interval to initial value of 0
     */
    public function fill_data_by_date_pivots_for_graph(string $pivot, int $start, int $end) : array
    {
        $ret = [];
        $data = $this->fill_data_by_date_pivots($pivot, $start, $end);

        foreach ($data as $_pivot => $__data) {
            foreach ($__data as $pivot_interval => $_) {
                foreach ($_ as $pivot_value => $__) {
                    $pivot_value_nice = $this->make_date_pivot_value_nice($_pivot, $pivot_interval, $pivot_value);
                    $ret[$pivot_value_nice] = 0;
                }
            }
        }

        return $ret;
    }

    /**
     * Convert a pivot interval filter array to a range pair if it only specifies one value.
     *
     * @param  ID_TEXT $pivot The pivot for which we are calculating the interval
     * @param  mixed $_range_value The value of the $bucket . __day_range filter property
     * @return array An array pair of start, end indicating the day range; start and end are the number of days since epoch (1970)
     */
    protected function convert_day_range_filter_to_pair(string $pivot, $_range_value) : array
    {
        require_code('temporal');

        // Work out what our range value is as an integer if applicable if $_range_value is not already a range pair
        $range_value = null;
        if (is_array($_range_value) && (count($_range_value) == 1) && (is_integer($_range_value[0]))) {
            $range_value = $_range_value[0];
        }
        if (is_integer($_range_value)) {
            $range_value = $_range_value;
        }

        $from = null;
        $to = null;

        // If $range_value has a value, this means $_range_value had only one value. Treat this as a day range length from (now - value) to now.
        if ($range_value !== null) {
            $from = from_epoch_interval_index($range_value, 'days');
            $to = from_epoch_interval_index(time(), 'days');
        }

        // If range is an array of exactly two integers, treat as a day range from key 0 to key 1
        if (is_array($_range_value) && (count($_range_value) == 2) && is_integer($_range_value[0]) && is_integer($_range_value[1])) {
            $from = from_epoch_interval_index($_range_value[0], 'days');
            $to = from_epoch_interval_index($_range_value[1], 'days');
        }

        // Was range invalid?
        if ($from === null) {
            warn_exit(do_lang_tempcode('INTERNAL_ERROR', escape_html('e4d7c28853cb5b6da6d4a315774aae54')));
        }

        // Convert to pivot interval
        $ret_from = $this->calculate_date_pivot_interval($pivot, $from);
        $ret_to = $this->calculate_date_pivot_interval($pivot, $to);

        return [$ret_from, $ret_to];
    }

    /**
     * Make a date pivot value look nice.
     *
     * @param  string $pivot Current pivot
     * @param  integer $pivot_interval The pivot interval
     * @param  integer $pivot_value Pivot value
     * @return string Nice looking pivot interval/value
     */
    protected function make_date_pivot_value_nice(string $pivot, int $pivot_interval, int $pivot_value) : string
    {
        require_lang('dates');
        require_code('temporal');

        switch ($pivot) {
            case 'hour_of_day':
                return trim(cms_date('ga', cms_mktime($pivot_value)));

            case 'day_series':
                $timestamp = from_epoch_interval_index($pivot_interval, 'days');
                return cms_date('Y-m-d', $timestamp);

            case 'day_of_week':
                $dows = [
                    'SUNDAY',
                    'MONDAY',
                    'TUESDAY',
                    'WEDNESDAY',
                    'THURSDAY',
                    'FRIDAY',
                    'SATURDAY',
                ];
                return do_lang($dows[$pivot_value]);

            case 'week_series':
                // Proper Monday week start handling (we have to use Monday regardless of ssw because PHP only allows that)
                $epoch = 345600;

                $timestamp = from_epoch_interval_index($pivot_interval, 'weeks', $epoch);
                $year = intval(cms_date('Y', $timestamp));
                $week = intval(cms_date('W', $timestamp));
                return strval($year) . '-W' . str_pad(strval($week), 2, '0', STR_PAD_LEFT);

            case 'week_of_year':
                return do_lang('WEEK', comcode_escape(strval($pivot_value)));

            case 'month_series':
                $timestamp = from_epoch_interval_index($pivot_interval, 'months');
                return cms_date('Y-m', $timestamp);

            case 'month_of_year':
                $months = [
                    'JANUARY',
                    'FEBRUARY',
                    'MARCH',
                    'APRIL',
                    'MAY',
                    'JUNE',
                    'JULY',
                    'AUGUST',
                    'SEPTEMBER',
                    'OCTOBER',
                    'NOVEMBER',
                    'DECEMBER',
                ];
                return do_lang($months[$pivot_value]);

            case 'quarter_series':
                $timestamp = from_epoch_interval_index($pivot_interval * 3, 'months');
                $quarter = ($pivot_interval % 4) + 1;
                return cms_date('Y', $timestamp) . ' Q' . strval($quarter);

            case 'quarter_of_year':
                return 'Q' . strval($pivot_value + 1);

            case 'year_series':
                $timestamp = from_epoch_interval_index($pivot_interval, 'years');
                return cms_date('Y', $timestamp);
        }

        // All else fails
        return strval($pivot_interval) . '/' . strval($pivot_value);
    }

    /**
     * Get stats data for a pivot graph in batches.
     *
     * @param  ?array $range The graph time range from convert_day_range_filter_to_pair (null: we want flat data)
     * @param  ID_TEXT $bucket The bucket we are loading
     * @param  ?ID_TEXT $pivot The pivot at which we are viewing the graph (blank: graph does not support pivots, so use day_series data) (null: we want flat data)
     * @param  array $filters Array of active filters
     * @param  integer $start The starting row, passed by reference as we add 250 after each iteration
     * @return array The database rows, limited to 250 per iteration
     */
    protected function get_preprocessed_data_for_graph(?array $range, string $bucket, ?string $pivot, array $filters, int &$start = 0) : array
    {
        if ($pivot === '') {
            $pivot = 'day_series';
        }

        $max = 250;

        $where = [
            'p_bucket' => $bucket,
        ];
        if ($pivot !== null) {
            $where['p_pivot'] = $pivot;
        }

        $extra = '';

        if ($range !== null) {
            $extra .= ' AND p_pivot_interval>=' . strval($range[0]);
            $extra .= ' AND p_pivot_interval<=' . strval($range[1]);
        }

        $table = 'stats_preprocessed';
        if ($pivot === null) {
            $table = 'stats_preprocessed_flat';
        }

        $rows = $GLOBALS['SITE_DB']->query_select($table, ['*'], $where, $extra, $max, $start);

        $start += $max;

        return $rows;
    }

    /**
     * Check if the data buckets is getting large, and if so, dump to the database delta and then reset.
     * This should regularly be used in stats hooks to avoid out of memory errors.
     *
     * @param  boolean $force Whether to forcefully dump regardless of size, e.g. we are finished processing data buckets
     * @param  boolean $rebuild Whether to rebuild the delta array structure with the buckets for this hook
     * @param  boolean $flat Whether the data buckets are for the flat statistics data
     */
    public function dump_data_buckets_if_necessary(bool $force = false, bool $rebuild = true, $flat = false)
    {
        // Check memory use
        require_code('files');
        $ml = php_return_bytes(ini_get('memory_limit'));
        $current_memory = memory_get_usage(false);
        $near_limit = (($ml > 0) && ($current_memory >= ($ml - (1024 * 1024 * 8)))); // within 8 MB of PHP memory limit
        $large_bucket = (count($this->data_buckets, COUNT_RECURSIVE) >= 10000);

        $should_dump = ($force || $near_limit || $large_bucket);

        // Dump to the database if we determined that we should do so
        if ($should_dump) {
            // Flat data operates on a "replacement"; we replace the value in the database with the value that we calculated.
            // Also, we perform database operations immediately for flat data instead of using a delta
            if ($flat) {
                $groups = [];
                $insert_rows = [
                    'p_id' => [],
                    'p_bucket' => [],
                    'p_key' => [],
                    'p_value' => [],
                ];
                foreach ($this->data_buckets as $bucket => $data) {
                    $flattened = [];
                    $this->flatten_data_buckets($flattened, $data);

                    foreach ($flattened as $f_key => $f_value) {
                        $pid = stats_get_p_id($bucket, null, null, null, strval($f_key));
                        $groups[$pid] = true;

                        $insert_rows['p_id'][] = $pid;
                        $insert_rows['p_bucket'][] = $bucket;
                        $insert_rows['p_key'][] = $f_key;
                        $insert_rows['p_value'][] = $f_value;

                        // Time to perform a batch database operation?
                        if (count($insert_rows['p_id']) >= 100) {
                            $GLOBALS['SITE_DB']->query_delete('stats_preprocessed_flat', ['p_id' => array_keys($groups)]);
                            $GLOBALS['SITE_DB']->query_insert('stats_preprocessed_flat', $insert_rows);

                            $groups = [];
                            $insert_rows = [
                                'p_id' => [],
                                'p_bucket' => [],
                                'p_key' => [],
                                'p_value' => [],
                            ];
                        }
                    }

                    unset($flattened);
                }

                // Fnish what's left
                if (count($insert_rows['p_id']) > 0) {
                    $GLOBALS['SITE_DB']->query_delete('stats_preprocessed_flat', ['p_id' => array_keys($groups)]);
                    $GLOBALS['SITE_DB']->query_insert('stats_preprocessed_flat', $insert_rows);
                }

                unset($groups);
                unset($insert_rows);
            } else {
                // Timed data operates on a "delta"; we increment the value in the database by the value that we calculated.
                // For efficiency, we just dump to a delta table and let the scheduler merge it in later.
                $insert_rows = [
                    'p_id' => [],
                    'p_bucket' => [],
                    'p_pivot' => [],
                    'p_pivot_interval' => [],
                    'p_pivot_value' => [],
                    'p_key' => [],
                    'p_value' => [],
                ];
                foreach ($this->data_buckets as $bucket => $_) {
                    foreach ($_ as $pivot => $__) {
                        foreach ($__ as $pivot_interval => $___) {
                            foreach ($___ as $pivot_value => $data) {
                                $flattened = [];
                                $this->flatten_data_buckets($flattened, $data);

                                foreach ($flattened as $f_key => $f_value) {
                                    $insert_rows['p_id'][] = stats_get_p_id($bucket, $pivot, $pivot_interval, $pivot_value, strval($f_key));
                                    $insert_rows['p_bucket'][] = $bucket;
                                    $insert_rows['p_pivot'][] = $pivot;
                                    $insert_rows['p_pivot_interval'][] = $pivot_interval;
                                    $insert_rows['p_pivot_value'][] = $pivot_value;
                                    $insert_rows['p_key'][] = $f_key;
                                    $insert_rows['p_value'][] = $f_value;

                                    if (count($insert_rows['p_id']) >= 100) {
                                        $GLOBALS['SITE_DB']->query_insert('stats_preprocessed_delta', $insert_rows);

                                        $insert_rows = [
                                            'p_id' => [],
                                            'p_bucket' => [],
                                            'p_pivot' => [],
                                            'p_pivot_interval' => [],
                                            'p_pivot_value' => [],
                                            'p_key' => [],
                                            'p_value' => [],
                                        ];
                                    }
                                }

                                // Fnish what's left
                                if (count($insert_rows['p_id']) > 0) {
                                    $GLOBALS['SITE_DB']->query_insert('stats_preprocessed_delta', $insert_rows);
                                }
                                unset($flattened);
                                unset($groups);
                                unset($insert_rows);
                            }
                        }
                    }
                }
            }

            // Garbage collect
            $this->data_buckets = [];
            gc_collect_cycles();
            if (function_exists('gc_mem_caches')) {
                @gc_mem_caches();
            }

            // Rebuild data structure
            if ($rebuild) {
                $info = $this->info();
                if ($info === null) {
                    return;
                }
                foreach (array_keys($info) as $bucket) {
                    $this->data_buckets[$bucket] = [];
                }
            }
        }
    }

    /**
     * Flatten a data bucket associative array into a single map.
     * This takes every depth path in the array and generates a single key (using the || delimiter) mapped to its end value.
     *
     * @param  array $ret The flattened array, passed by reference
     * @param  mixed $cur_structure The current working data; you would pass the array to be flattened here
     * @param  integer $depth The current depth level of the array
     * @param  array $cur_key A map of $depth to key name for the current structure
     */
    protected function flatten_data_buckets(array &$ret, $cur_structure, int $depth = 0, array $cur_key = [])
    {
        // Did we find the end of the line?
        if (!is_array($cur_structure)) {
            $ret[implode('||', $cur_key)] = $cur_structure;
            unset($cur_key[$depth]);
            return;
        }

        // Recurse over the array
        foreach ($cur_structure as $i_key => $i_value) {
            $cur_key[$depth] = $i_key;
            $this->flatten_data_buckets($ret, $i_value, $depth + 1, $cur_key);
        }

        unset($cur_key[$depth]);
    }
}

/**
 * Base stats hook class for stats blob providers. These are hooks that provide graphs, but cannot break down data within the API (for tables or spreadsheets etc).
 *
 * @package stats
 */
abstract class Source_hook_stats_blob extends Source_hook_stats_base
{
    /**
     * Generate graph.
     *
     * @param  string $graph_name Graph name
     * @param  array $filters Filter settings to take precedence
     * @return Tempcode Graph
     */
    abstract public function generate(string $graph_name, array $filters) : object;
}

/**
 * Base stats hook class for simple redirect hooks.
 *
 * @package stats
 */
abstract class Source_hook_stats_redirect extends Source_hook_stats_base
{
    /**
     * Get the hook's redirect URL.
     *
     * @param  string $bucket_name The bucket name
     * @return URLPATH Redirect URL
     */
    abstract public function get_redirect_url(string $bucket_name) : string;
}
