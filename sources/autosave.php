function init__autosave()
{
    global $CLEAR_AUTOSAVE;
    $CLEAR_AUTOSAVE = [];
}

/**
 * AJAX script to store an autosave.
 *
 * @ignore
 */
function store_autosave_script()
{
    require_code('input_filter_2');
    if (get_value('disable_modsecurity_workaround') !== '1') {
        modsecurity_workaround_enable();
    }

    prepare_backend_response('text/plain');

    $member_id = get_member();
    $time = time();

    foreach (array_keys($_POST) as $key) {
        $value = post_param_string($key);

        $GLOBALS['SITE_DB']->query_insert('autosave', [
            // Will duplicate against a_member_id/a_key, but DB space is not an issue - better to have the back-archive of it
            'a_member_id' => $member_id,
            'a_key' => $key,
            'a_value' => $value,
            'a_time' => $time,
        ]);
    }

    cms_safe_exit_flow();
}

/**
 * AJAX script to delete an autosave.
 *
 * @ignore
 */
function delete_autosave_script()
{
    require_code('input_filter_2');
    if (get_value('disable_modsecurity_workaround') !== '1') {
        modsecurity_workaround_enable();
    }

    prepare_backend_response('text/plain');

    $page = get_param_string('the_page');
    clear_cms_autosave($page);

    cms_safe_exit_flow();
}

/**
 * AJAX script to retrieve an autosave.
 *
 * @ignore
 */
function retrieve_autosave_script()
{
    prepare_backend_response();

    $member_id = get_member();
    $stem = either_param_string('stem');

    require_code('xml');

    cms_ini_set('ocproducts.xss_detect', '0');

    echo '<?xml version="1.0" encoding="' . escape_html(get_charset()) . '"?' . '>';
    echo '<request><result>' . "\n";

    $rows = $GLOBALS['SITE_DB']->query_select(
        'autosave',
        ['a_key', 'a_value', 'a_time'],
        ['a_member_id' => $member_id],
        'AND a_key LIKE \'' . db_encode_like($stem) . '%\' ORDER BY a_time DESC'
    );

    $done = [];
    foreach ($rows as $row) {
        if (isset($done[$row['a_key']])) {
            continue;
        }
        echo '<field key="' . xmlentities($row['a_key']) . '" value="' . xmlentities($row['a_value']) . '" />' . "\n";
        $done[$row['a_key']] = true;
    }

    echo '</result></request>';

    cms_safe_exit_flow();
}

/**
 * Declare that an action succeeded - delete safety autosave.
 *
 * @param  ?ID_TEXT $page The name of the page we succeeded (null: current page)
 */
function clear_cms_autosave(?string $page = null)
{
    static $done_once = false;
    if ($done_once) {
        return;
    }

    if (!function_exists('get_member')) {
        return;
    }

    if ($page === null) {
        $page = get_page_name();
    }

    global $CLEAR_AUTOSAVE;

    // TODO: make specific to what we just did, if possible
    $sql = 'DELETE FROM ' . $GLOBALS['SITE_DB']->get_table_prefix() . 'autosave WHERE a_time<' . strval(time() - 60 * 60 * 24) . ' OR (a_member_id=' . strval(get_member()) . ' AND (a_key LIKE \'' . db_encode_like('%' . $page . '%') . '\'))';
    $GLOBALS['SITE_DB']->query($sql);

    $CLEAR_AUTOSAVE[get_page_name()] = true;

    $done_once = true;
}
