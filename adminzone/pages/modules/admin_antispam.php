/**
 * Module page class.
 */
class Module_admin_antispam
{
    /**
     * Find details of the module.
     *
     * @return ?array Map of module info (null: module is disabled)
     */
    public function info() : ?array
    {
        $info = [];
        $info['author'] = 'Patrick Schmalstig';
        $info['organisation'] = 'Composr';
        $info['hacked_by'] = null;
        $info['hack_version'] = null;
        $info['update_require_upgrade'] = true;
        $info['version'] = 1;
        $info['locked'] = false;
        $info['min_cms_version'] = 11.0;
        $info['addon'] = 'bayes_antispam';
        return $info;
    }

    /**
     * Uninstall the module.
     */
    public function uninstall()
    {
        $GLOBALS['SITE_DB']->drop_table_if_exists('antispam_bayes');
        $GLOBALS['SITE_DB']->drop_table_if_exists('antispam_bayes_trained');
    }

    /**
     * Install the module.
     *
     * @param  ?integer $upgrade_from What version we're upgrading from (null: new install)
     * @param  ?integer $upgrade_from_hack What hack version we're upgrading from (null: new-install/not-upgrading-from-a-hacked-version)
     */
    public function install(?int $upgrade_from = null, ?int $upgrade_from_hack = null)
    {
        if ($upgrade_from === null) {
            $GLOBALS['SITE_DB']->create_table('antispam_bayes', [
                'id' => '*AUTO',
                't_id' => 'SHORT_TEXT',
                't_lang' => 'LANGUAGE_NAME',
                't_category' => 'ID_TEXT',
                't_count' => 'REAL',
                't_last_date_and_time' => 'TIME',
            ]);
            $GLOBALS['SITE_DB']->create_index('antispam_bayes', 'tlang', ['t_lang']);
            $GLOBALS['SITE_DB']->create_index('antispam_bayes', 'tcategory', ['t_category']);

            $GLOBALS['SITE_DB']->create_table('antispam_bayes_trained', [
                't_content_type' => '*ID_TEXT',
                't_content_id' => '*ID_TEXT',
                't_lang' => 'LANGUAGE_NAME',
                't_categories' => 'LONG_TEXT', // Delimited by a new line
                't_date_and_time' => 'TIME',
            ]);
        }
    }

    private $title;

    /**
     * Find entry-points available within this module.
     *
     * @param  boolean $check_perms Whether to check permissions
     * @param  ?MEMBER $member_id The member to check permissions as (null: current user)
     * @param  boolean $support_crosslinks Whether to allow cross links to other modules (identifiable via a full-page-link rather than a screen-name)
     * @param  boolean $be_deferential Whether to avoid any entry-point (or even return null to disable the page in the Sitemap) if we know another module, or page_group, is going to link to that entry-point. Note that "!" and "browse" entry points are automatically merged with container page nodes (likely called by page-groupings) as appropriate.
     * @return ?array A map of entry points (screen-name=>language-code/string or screen-name=>[language-code/string, icon-theme-image]) (null: disabled)
     */
    public function get_entry_points(bool $check_perms = true, ?int $member_id = null, bool $support_crosslinks = true, bool $be_deferential = false) : ?array
    {
        if (!addon_installed('bayes_antispam')) {
            return null;
        }
        if (!addon_installed('bayes_common')) {
            return null;
        }

        return [
            'browse' => ['BAYES_ANTISPAM', 'spare/compare'], // TODO: Custom icon
        ];
    }

    /**
     * Module pre-run function. Allows us to know metadata for <head> before we start streaming output.
     *
     * @return ?Tempcode Tempcode indicating some kind of exceptional output (null: none)
     */
    public function pre_run() : ?object
    {
        $error_msg = new Tempcode();
        if (!addon_installed__messaged('bayes_antispam', $error_msg)) {
            return $error_msg;
        }
        if (!addon_installed__messaged('bayes_common', $error_msg)) {
            return $error_msg;
        }

        $type = get_param_string('type', 'browse');

        require_lang('bayes_antispam');

        set_helper_panel_tutorial('tut_antispam');

        if ($type == 'browse') {
            $this->title = get_screen_title('BAYES_ANTISPAM');
        }

        return null;
    }

    /**
     * Execute the module.
     *
     * @return Tempcode The result of execution
     */
    public function run() : object
    {
        $type = get_param_string('type', 'browse');

        if ($type == 'browse') {
            return $this->browse();
        }

        return new Tempcode();
    }

    /**
     * The main UI
     *
     * @return Tempcode The result of execution
     */
    public function browse() : object
    {
        // TODO

        return new Tempcode();
    }
}
